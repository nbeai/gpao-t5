// **자[尺]가 크기와 함께 자라지 않게 한다** — 게이트 벽시계 판정의 유휴 교체.
// 오너 결정 2026-08-07 (현재상황 §1-A). 규격 넷 중 ①(판정 교체)과 그 재료가 여기다.
//
// 벽시계 30s 고정선은 검사가 늘면 **반드시** 터진다 — 기다림이 아니라 크기를 재는 자가
// 되어 있었다. 목적(잠든 검사 잡기)은 그대로 두고, 크기와 무관한 축으로 옮긴다:
//
//     유휴 = 벽시계 − CPU ÷ 동시성        ← 아무도 일하지 않은 시간
//
//     검사가 늘면        CPU·벽시계가 같이 늘어 유휴가 따라 안 는다   ← 크기와 무관
//     sleep 30 이 섞이면  유휴가 30s 대로 튄다                        ← 목적 그대로 잡힌다
//     옆에서 부하가 돌면  CPU 가 부풀지만 벽시계도 같이 늘어 유휴는 오히려 준다
//
// 실측 (2026-08-08 · 같은 트리 · 검사 3,272건):
//     한가한 기계   벽시계 23.6  CPU 41.6  →  유휴 9.7s
//     부하 기계     벽시계 34.9  CPU 85.5  →  유휴 6.4s    ← 옛 자(30s 벽시계)로는 BLOCKED
//     부하 기계     벽시계 35.4  CPU 87.7  →  유휴 6.2s    ← 〃
// 부하가 유휴를 **늘리지 않는다**는 것이 실측으로 섰다 — 이 자는 부하에 안 뒤집힌다.
// 상한(`gate-baseline.json` 의 `testIdleSeconds`)은 이 실측 범위로 교정했고(§1-A 규격 ②),
// 자동 갱신하지 않는다(규격 ④) — 옮기는 것은 오너 결정이다.

/**
 * 검사 동시성 — `package.json` 의 test 스크립트에서 **읽는다.** 숫자를 박지 않는다(규격 ①).
 * 못 읽으면 `null` — 조용히 1 로 메우지 않는다. 1 로 메우면 유휴가 음수까지 내려가
 * 판정이 느슨해지는 쪽으로 조용히 틀린다.
 */
export function 동시성(pkg) {
  const m = String(pkg?.scripts?.test ?? '').match(/--test-concurrency=(\d+)/);
  return m ? Number(m[1]) : null;
}

/** 아무도 일하지 않은 시간. 재료가 하나라도 안 섰으면 `null` — 빈 측정을 통과로 세지 않는다. */
export function 유휴초({ wall, cpu, concurrency }) {
  if (![wall, cpu, concurrency].every((n) => Number.isFinite(n) && n > 0)) return null;
  return wall - cpu / concurrency;
}
