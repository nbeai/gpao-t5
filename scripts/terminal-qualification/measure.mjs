// **자(尺).** 오너 선언(2026-08-14): *"유일한 감사는 실제 콘솔 라이브 결과다."*
// 사람 감사는 폐지됐다. 그러니 이 파일이 T5 의 유일한 자다 — **자가 헐거우면 전부 거짓이 된다.**
// (`재는 자가 틀리면 재는 것이 전부 거짓이다` · 2026-08-12)
//
// 회차마다 **같은 자 다섯**을 잰다:
//   ① 사용자 개입 횟수     승인 카드 · 되묻기 · 대본의 유도 갈래 · "직접 하세요" 떠넘김
//   ② 실물이 생겼나
//   ③ 원본 불변
//   ④ 사용자가 결과 자리를 아는가
//   ⑤ **어디서 멈췄나** — 손 고름 → 실행 → 실물 → 내용 → 자리 고지
//
// ⑤가 핵심이다. 오너 확정: **「만점 아니면 빵점」은 완료 선언에만 쓰고, 진단 기록에는 어디서
// 멈췄는지를 남긴다.** 2026-08-14 라이브 6회가 전부 빵점이었는데 그 안의 「셸은 됐고 파일에서
// 멈췄다」가 결함 위치를 짚은 유일한 단서였다.

// ── 영수증 — **손이 무엇을 가져왔나** ──────────────────────────────────────
//
// 「돌았다」와 「가져왔다」는 다르다. 못 찾은 `local.locate` 도 `failureState: none · delivered`
// 로 남는다 — 실패가 아니라 **빈손**이다. 이 구분이 없으면 「다 돌았는데 아무것도 없다」를
// 성공으로 읽는다. 결실 판정은 **손의 결과 스키마**만 본다(닫힌 집합이라 문구 목록과 다르다).
const 성과배열키 = ['candidates', 'items', 'matches', 'results', 'entries', 'files', 'hits', 'rows', 'processes', 'windows'];
const 성과글키 = ['stdout', 'text', 'content', 'output'];

/** 한 영수증이 **무엇을 가져왔나**. `{결실, 빈손, 막힘, 결실근거}` — 근거는 사람이 되짚을 문장이다. */
export function 결실보기({ result, failureState, lifecycle } = {}) {
  if (lifecycle === 'failed' || (failureState && failureState !== 'none')) {
    return { 결실: false, 빈손: false, 막힘: true, 결실근거: `막혔다(${lifecycle ?? failureState})` };
  }
  const r = result ?? {};
  const 빈것 = [];
  for (const k of 성과배열키) {
    if (!Array.isArray(r[k])) continue;
    if (r[k].length) return { 결실: true, 빈손: false, 막힘: false, 결실근거: `${k} ${r[k].length}건` };
    빈것.push(`${k} 0건`);
  }
  for (const k of 성과글키) {
    const v = r[k];
    if (typeof v === 'string' && v.trim()) return { 결실: true, 빈손: false, 막힘: false, 결실근거: `${k} ${v.length}자` };
    if (typeof v === 'string') 빈것.push(`${k} 빔`);
  }
  if (Number(r.bytes) > 0 || r.digest || r.applied === true) {
    return { 결실: true, 빈손: false, 막힘: false, 결실근거: `기록됐다(${r.bytes ?? '적용'})` };
  }
  return { 결실: false, 빈손: true, 막힘: false, 결실근거: 빈것.join(' · ') || '내놓은 것이 없다' };
}

/** 원장 한 줄에서 채점이 보는 것만 꺼낸다(원문은 따로 통째로 보존한다). */
export function 영수증정리(원장 = []) {
  return 원장.filter((e) => e?.actualCall?.tool).map((e) => ({
    tool: e.actualCall.tool,
    action: e.actualCall.args?.action ?? e.actualCall.args?.op ?? null,
    path: e.actualCall.args?.path ?? e.result?.path ?? null,
    command: e.actualCall.args?.command ?? null,
    cwd: e.actualCall.args?.cwd ?? e.result?.cwd ?? null,
    failureState: e.failureState ?? null,
    failedBy: e.result?.failedBy ?? null,
    failReason: e.result?.failReason ?? null,
    exitCode: e.result?.exitCode ?? null,
    applied: e.result?.applied ?? null,
    // **어느 턴의 손인가.** 떠넘김은 「그 턴에」 무엇을 가져왔는지와 함께 봐야 한다.
    turnSeq: e.turnRef?.turnSeq ?? null,
    ...결실보기(e),
  }));
}

// ── 떠넘김 ────────────────────────────────────────────────────────────────
//
// **2026-08-14 라이브에서 이 축이 뚫렸다.** 그때 자는 정규식 목록이었고, 목록에 없는 문장
// ("표 폴더 위치를 정확히 짚어 주면 …")을 0 으로 셌다. **목록은 늘려도 다음 문장에서 또 뚫린다.**
// 그래서 문구 목록을 버리고 **성질 둘**로 다시 세웠다.
//
//   (가) 실행 떠넘김 — 사용자에게 **손을 쓰라고** 시킨다("직접 실행해 주세요"). 자기가 할 수 있는
//        일을 남에게 시킨 것이므로 영수증이 무엇이든 떠넘김이다.
//   (나) 정보 떠넘김 — 사용자에게 **정보를 달라고** 하며 끝난다. 이건 문구만으로는 못 가른다.
//        일을 다 끝낸 뒤 덧붙이는 "다르게 보고 싶으면 말해 줘" 와 모양이 같기 때문이다.
//        그래서 **그 턴의 영수증과 함께** 본다:
//          · 그 턴에 손을 아예 안 썼다   → 떠넘김   (**결실 없음의 가장 강한 형태** — 시도조차 없다)
//          · 결실이 하나도 없다        → 떠넘김   (아무것도 못 얻고 사용자에게 넘겼다)
//          · 결실도 있고 빈손·막힘도 있다 → 의심     (반은 해내고 반을 넘겼다 — 사람이 되짚는다)
//          · 빈손·막힘이 없다           → 아니다   (다 해 놓고 덧붙인 제안이다)
//
// **영수증 0건을 「빈손 0 · 막힘 0」과 같은 자리에 적지 않는다.** 2026-08-14 라이브 2회차 과업 4
// 에서 T5 는 3턴 동안 디스크를 사실상 한 번도 안 보고(회차 전체 영수증 1건) 세 턴 모두 사용자에게
// 메뉴를 고르라고 했는데, 마지막 턴 영수증이 0건이라 **가장 안전한 점수**를 받았다. 손을 아예
// 안 쓴 턴은 가장 무거운 실패다 — 그 사실을 `시도없음` 이라는 이름으로 따로 적고 그 위에 판정을
// 세운다. (`「안 잰 것」과 「0」을 가르지 못한 것` · F-104 · F-105 · X5 · X6 · EISDIR)
//
// **영수증과 답을 함께 보는 축이 문구만 보는 축보다 튼튼하다.** 이 하네스는 이미 영수증을 갖고 있다.
// 판정은 여전히 「의심」이라 부르고, **매칭 원문을 그대로 남긴다** — 사람이 되짚을 수 있어야 한다.

const 문장쪼개기 = (글) => String(글 ?? '').split(/\n+|(?<=[.?!。？！])\s+/).map((s) => s.trim()).filter(Boolean);
/** 이 문장의 주어가 T5 자신인가 — "내가 직접 열어서 …" 는 떠넘김이 아니라 자기가 하겠다는 말이다. */
const T5주어 = (문장) => /^[^.]{0,12}?(내가|제가|나는|저는|내\s*쪽|우리가)/.test(문장);

// **정보를 달라는 요구.** 어미가 「줘/주세요/주면」 인 것만 센다 — 「줄게」는 T5 가 하겠다는 말이다.
const 정보제공동사 = '말해|말씀해|알려|짚어|가르쳐|적어|골라|찍어|보내|대';
const 정보요구 = new RegExp(`(?:${정보제공동사})\\s*(?:줘|주세요|주실|주시겠|줄래|줄\\s*수\\s*있|주면)`);
// **조건절.** "…면"은 아직 안 했다는 뜻이다(조건이 서면 그때 하겠다는 말).
const 조건표시 = /(?:알려|말해|짚어|가르쳐|적어|골라|찍어|보내|정해)\s*주?시?면|기억하?면|알면|말하?면/;
// **누가 하는가로 가른다 — 목록이 아니라 성질이다.** 보조용언 「-어 주다」의 주는 쪽은 상대다.
// 거기에 조건 어미 「-면」이 붙으면 *네가 해 주면 그때 내가 하겠다* 는 말이고, 그 턴에 그 일은
// **안 된 것**이다. 동사 목록으로 찾던 자가 "딱 이 한 줄만 **정해 주면**"(2026-08-14 2회차 과업 4)
// 을 통째로 못 봤다 — 목록을 늘리면 다음 문장에서 또 뚫리므로 어미로 옮긴다.
// T5 자신이 주어인 문장("내가 정리해 주면")은 부르는 쪽에서 이미 걸러 낸다.
const 사용자몫조건 = /[가-힣]{1,8}\s*주(?:시|셔)?면/;
// **약속 어미.** T5 가 「나중에」 하겠다고 한 자리. 이게 있으면 그 일은 **지금 안 된 것**이다.
const 약속어미 = /줄게|줄께|드릴게|할게|할께|볼게|둘게|놓을게|드리겠|하겠습니다/;
const 정보제공꼬리 = new RegExp(`(?:${정보제공동사})$`);
// **사용자에게 손을 쓰라는 명령**과 그 대상.
const 사용자명령 = /하세요|해\s*주세요|해\s*줘|해\s*봐|해라|해\s*주시|눌러\s*주?|실행해\s*(?:줘|주세요|보)|열어\s*(?:줘|주세요|보)|확인해\s*(?:줘|주세요)|복사해서/;
const 손쓰기대상 = /직접|손수|아래\s*(?:명령|커맨드|스크립트)|명령어|커맨드|스크립트|터미널/;
// **자기 불능 선언.** "못 찾고 있어"(해 보고 못 찾음)와 다르다 — 이건 **하지 않겠다**는 말이다.
const 불능선언 = /할\s*수\s*없|하지\s*못\s*(?:해|합)|못\s*합니다|못\s*해요|접근할\s*수\s*없|실행할\s*수\s*없|불가능/;
// 요구한 것이 **T5 가 손으로 알아낼 수 있는 것**인가(자리·이름). 사람만 아는 취향과 가른다.
const 자리이름 = /경로|폴더|디렉터리|디렉토리|위치|자리|어디|어느\s*(?:쪽|것)|파일\s*이름|파일명|이름/;

const 오려내기 = (글, 조각) => {
  const 자리 = 글.indexOf(조각);
  if (자리 < 0) return 조각;
  return 글.slice(Math.max(0, 자리 - 30), 자리 + 조각.length + 30).replace(/\s+/g, ' ').trim();
};

/** "만들어 줄 수 있어"(약속) 는 잡고 "짚어 줄 수 있어?"(요구) 는 안 잡는다. */
function 약속찾기(글) {
  const m = 글.match(약속어미);
  if (m) return m[0];
  for (const 것 of 글.matchAll(/([가-힣]{1,6})\s*(?:줄|드릴)\s*수\s*있/g)) {
    if (!정보제공꼬리.test(것[1])) return 것[0];
  }
  return null;
}

/**
 * 떠넘김을 **성질로** 가른다.
 * @param {object} p
 * @param {string} p.답      그 회차의 마지막 답
 * @param {Array}  p.영수증  영수증정리() 결과(회차 전체)
 * @param {number} p.본턴    마지막 답이 나온 턴 — 그 턴 영수증만 골라 본다
 * @returns {{판정:'떠넘김'|'의심'|'없음', 신호:Array<{이름:string,원문:string}>, 영수증근거:object}}
 */
export function 떠넘김판정({ 답, 영수증 = [], 본턴 = null } = {}) {
  const 글 = String(답 ?? '');
  const 문장들 = 문장쪼개기(글);
  const 신호 = [];
  const 적기 = (이름, 원문) => { if (원문) 신호.push({ 이름, 원문: 오려내기(글, 원문) }); };

  // (가) 실행 떠넘김 — 사용자에게 손을 쓰라고 시킨다.
  for (const 문장 of 문장들) {
    if (T5주어(문장)) continue;
    if (사용자명령.test(문장) && 손쓰기대상.test(문장)) { 적기('실행떠넘김', 문장); break; }
  }

  // (나) 정보 떠넘김의 재료들.
  const 요구문장들 = 문장들.filter((s) => !T5주어(s) && 정보요구.test(s));
  적기('정보요구', 요구문장들[0]);
  // 동사가 무엇이든 **사용자가 해 주는 것을 조건으로 건** 문장. 요구의 성질 그 자체다.
  적기('사용자몫조건', 문장들.find((s) => !T5주어(s) && !정보요구.test(s) && 사용자몫조건.test(s)));
  const 끝문장 = 문장들[문장들.length - 1] ?? '';
  if (/[?？][\s*_`]*$/.test(글.trim()) && (자리이름.test(끝문장) || /무엇|뭐|어떤|몇/.test(끝문장))) 적기('물음표요구', 끝문장);
  const 약속 = 약속찾기(글);
  const 조건 = 글.match(조건표시)?.[0] ?? null;
  if (약속 && 조건) 적기('조건절약속', `${조건} … ${약속}`);
  for (const 문장 of 문장들) {
    if (T5주어(문장) || !불능선언.test(문장)) continue;
    적기('불능선언', 문장); break;
  }
  // 요구 대상이 **손으로 알아낼 수 있는 것**인지는 판정을 바꾸지 않고 근거로만 남긴다.
  // 요구는 "딱 이것만 알려줘:" 하고 **다음 줄에** 무엇을 달라는지 적히는 일이 많아 뒤 두 줄까지 본다.
  const 요구근처 = 문장들.flatMap((s, i) => (요구문장들.includes(s) ? [문장들.slice(i, i + 3).join(' ')] : []));
  const 요구대상 = [...요구근처, 끝문장].find((s) => 자리이름.test(s));
  if (요구대상 && 신호.length) 적기('자리요구', 요구대상);

  // ── 영수증 — **그 턴에** 무엇을 가져왔나 ────────────────────────────────
  const 턴표시있음 = 영수증.some((r) => r?.turnSeq != null);
  const 본것 = (턴표시있음 && Number.isFinite(Number(본턴)))
    ? 영수증.filter((r) => r.turnSeq === Number(본턴))
    : 영수증;
  const 영수증근거 = {
    본턴: 턴표시있음 && Number.isFinite(Number(본턴)) ? Number(본턴) : '전체',
    센것: 본것.length,
    // **손을 아예 안 썼다.** 「빈손 0 · 막힘 0」과 절대로 같은 자리에 적지 않는다 —
    // 저건 손을 써 봤는데 못 얻은 것이고, 이건 시도조차 안 한 것이다.
    시도없음: 본것.length === 0,
    결실: 본것.filter((r) => r.결실 === true).length,
    빈손: 본것.filter((r) => r.빈손 === true).length,
    막힘: 본것.filter((r) => r.막힘 === true).length,
    한줄: 본것.map((r) => `${r.tool}${r.action ? `(${r.action})` : ''} — ${r.결실근거 ?? '알 수 없음'}`),
  };

  const 실행 = 신호.some((s) => s.이름 === '실행떠넘김');
  const 넘김신호 = 신호.some((s) => ['실행떠넘김', '정보요구', '사용자몫조건', '물음표요구', '조건절약속', '불능선언'].includes(s.이름));
  // **왜 그렇게 판정했는지를 영수증근거에 남긴다** — 사람이 되짚을 수 있어야 한다.
  let 판정 = '없음';
  let 왜;
  if (실행) { 판정 = '떠넘김'; 왜 = '사용자에게 손을 쓰라고 시켰다 — 영수증과 무관하다'; }
  else if (!넘김신호) { 판정 = '없음'; 왜 = '사용자에게 달라는 것이 없다 — 그냥 보고다'; }
  // 요구가 있는데 그 턴에 손이 한 번도 안 나갔다 → **결실 없음의 가장 강한 형태**다.
  else if (영수증근거.시도없음) { 판정 = '떠넘김'; 왜 = `요구가 있는데 ${영수증근거.본턴}턴에 손을 아예 안 썼다 — 시도조차 없다`; }
  else if (영수증근거.결실 === 0) { 판정 = '떠넘김'; 왜 = `손은 ${영수증근거.센것}건 썼는데 결실이 0이다`; }
  else if (영수증근거.빈손 + 영수증근거.막힘 > 0) { 판정 = '의심'; 왜 = `결실 ${영수증근거.결실} 과 빈손·막힘 ${영수증근거.빈손 + 영수증근거.막힘} 이 섞였다 — 반은 해내고 반을 넘겼다`; }
  else { 왜 = `그 턴 손 ${영수증근거.센것}건이 전부 결실이다 — 다 해 놓고 덧붙인 제안이다`; }
  영수증근거.왜 = 왜;
  return { 판정, 신호: 판정 === '없음' ? [] : 신호, 관찰신호: 신호, 영수증근거 };
}

/**
 * 다섯 축 + 멈춘칸.
 * @param {object} p
 * @param {object} p.과업        tasks.mjs 의 한 칸
 * @param {Array}  p.턴들        [{발화, 갈래, kind, reply, question}]
 * @param {Array}  p.영수증      영수증정리() 결과
 * @param {{새로생김:string[],변함:string[],사라짐:string[]}} p.대조
 * @param {object} p.새파일내용
 */
export function 채점({ 과업, 턴들, 영수증, 대조, 새파일내용 }) {
  const 마지막답턴 = [...턴들].reverse().find((t) => typeof t.reply === 'string' && t.reply.trim());
  const 마지막답 = 마지막답턴?.reply ?? '';
  const 사실 = {
    마지막답,
    모든답: 턴들.map((t) => t.reply ?? t.question ?? '').join('\n'),
    영수증,
    터미널영수증: 영수증.filter((r) => r.tool === 'local.terminal'),
    새로생김: 대조.새로생김,
    새파일내용,
  };

  // ── ① 사용자 개입 ────────────────────────────────────────────────────────
  const 승인카드 = 턴들.filter((t) => t.kind === 'approval').length;
  const 되묻기 = 턴들.filter((t) => t.kind === 'clarify').length;
  const 유도갈래 = 턴들.filter((t) => t.갈래 === '유도').length;
  // 떠넘김은 **한 답에 한 번**만 센다(문구 몇 개가 걸렸는지는 비용이 아니다).
  // 「의심」도 0 으로 세지 않는다 — 반은 해내고 반을 넘긴 답을 없던 일로 만들면 축이 다시 헐거워진다.
  const 떠넘김 = 떠넘김판정({ 답: 마지막답, 영수증, 본턴: 마지막답턴?.차례 ?? null });
  const 개입 = {
    합: 승인카드 + 되묻기 + 유도갈래 + (떠넘김.판정 === '없음' ? 0 : 1),
    승인카드, 되묻기, 유도갈래,
    떠넘김의심: 떠넘김.판정 === '없음' ? 0 : 1,
    떠넘김근거: 떠넘김.신호.map((s) => `[${s.이름}] ${s.원문}`),
    떠넘김,
    // 대본 발화 자체는 개입이 아니다(설계상 예정된 것). **유도 갈래로 잡힌 것만** 비용이다.
    대본발화: 턴들.filter((t) => t.갈래).map((t) => ({ 갈래: t.갈래, 발화: t.발화 })),
  };

  // ── ② 실물 ──────────────────────────────────────────────────────────────
  const 실물 = { 새로생김: 대조.새로생김, 생겼나: 대조.새로생김.length > 0 };

  // ── ③ 원본 불변 ─────────────────────────────────────────────────────────
  const 원본불변 = { 지켜졌나: 대조.변함.length === 0 && 대조.사라짐.length === 0, 변함: 대조.변함, 사라짐: 대조.사라짐 };

  // ── ④ 자리 고지 ─────────────────────────────────────────────────────────
  //
  // **실물을 요구하는 과업에서는 실제로 생긴 파일 이름만 자리로 센다.** 과업 문장에 적힌
  // 이름(`순매출.tsv`)을 후보에 넣었더니, 파일을 하나도 안 만들고 *"표/순매출.tsv 에 넣었어요"*
  // 라고만 말한 회차가 이 축에서 PASS 를 받았다(가짜 상류 예행 2026-08-14). **없는 것의 자리는
  // 알릴 수 없다** — 그 자리는 사용자를 없는 파일로 보내는 거짓말이다.
  const 자리후보 = 과업.실물필요
    ? [...대조.새로생김, ...대조.새로생김.map((p) => p.split('/').pop())]
    : (과업.자리표현 ?? []);
  const 말한자리 = [...new Set(자리후보)].filter((w) => w && 마지막답.includes(w));
  const 자리고지 = { 알렸나: 말한자리.length > 0, 말한자리, 재본후보: [...new Set(자리후보)] };

  // ── 내용 ────────────────────────────────────────────────────────────────
  const 내용 = 과업.내용검사(사실);

  // ── ⑤ 어디서 멈췄나 ─────────────────────────────────────────────────────
  const 손고름 = 영수증.length > 0;
  // 「실행」은 **돈 것**이다. 막히거나(blocked) 시작조차 못 한 것은 아직 안 돈 것이다.
  const 돈영수증 = 영수증.filter((r) => r.failureState === 'none' && r.applied !== false);
  const 칸들 = [
    { 이름: '손고름', 상태: 손고름 ? 'PASS' : 'FAIL', 근거: `영수증 ${영수증.length}건` },
    { 이름: '실행', 상태: 돈영수증.length ? 'PASS' : 'FAIL', 근거: `실제로 돈 영수증 ${돈영수증.length}건` },
    과업.실물필요
      ? { 이름: '실물', 상태: 실물.생겼나 ? 'PASS' : 'FAIL', 근거: 대조.새로생김 }
      : { 이름: '실물', 상태: '해당없음', 근거: '이 과업은 파일을 요구하지 않는다' },
    { 이름: '내용', 상태: 내용.통과 ? 'PASS' : 'FAIL', 근거: 내용.근거 },
    { 이름: '자리고지', 상태: 자리고지.알렸나 ? 'PASS' : 'FAIL', 근거: 자리고지 },
  ];
  const 첫실패 = 칸들.find((c) => c.상태 === 'FAIL');
  const 멈춘칸 = 첫실패 ? 첫실패.이름 : '끝까지';

  return {
    개입, 실물, 원본불변, 자리고지, 내용,
    사다리: 칸들,
    멈춘칸,
    // 「만점 아니면 빵점」은 **완료 선언에만** 쓴다. 진단은 위의 사다리가 한다.
    완료: 멈춘칸 === '끝까지' && 원본불변.지켜졌나 && 개입.합 === 0,
  };
}

/**
 * **미측정을 빵점과 섞지 마라.** 조건이 안 선 회차는 실패가 아니다.
 * 오늘 하루가 이 병으로 네 번 데었다(F-104·F-105·X5·X6).
 */
export function 측정가능한가({ 과업, 하네스오류, 답한턴수, 사실 }) {
  if (하네스오류) return { 측정됨: false, 이유: `하네스가 회차를 못 세웠다 — ${하네스오류}` };
  if (!답한턴수) return { 측정됨: false, 이유: '모델이 한 번도 답하지 않았다(전송·자격 문제 가능)' };
  const 조건 = 과업.조건(사실);
  if (!조건.성립) return { 측정됨: false, 이유: 조건.근거 };
  return { 측정됨: true, 이유: null, 조건근거: 조건.근거 };
}

// ── 비밀·절대경로 거르기 ────────────────────────────────────────────────────
// 저장소에 남기는 것이므로 **저장 전에** 거른다. 자격은 애초에 안 싣지만, 자격이 실릴 수 있는
// 자리(환경·헤더·명령줄)가 원장에 있으므로 값 자체를 이름으로 지운다.
const 비밀키이름 = /^(api[_-]?key|apikey|authorization|cookie|token|secret|password|자격|openai_api_key)$/i;

/** @param {object} p `{자리들: [[찾을것, 바꿀것], …], 자격들: string[], 글자상한: number}` */
export function 거르개({ 자리들 = [], 자격들 = [], 글자상한 = 4000 } = {}) {
  const 치환 = (글) => {
    let s = String(글);
    for (const 값 of 자격들) if (값 && 값.length >= 8) s = s.split(값).join('<자격>');
    for (const [찾을것, 바꿀것] of 자리들) if (찾을것) s = s.split(찾을것).join(바꿀것);
    s = s.replace(/\b(sk|rk|pk)-[A-Za-z0-9_-]{12,}/g, '<자격>');
    s = s.replace(/\bBearer\s+[A-Za-z0-9._-]{12,}/gi, 'Bearer <자격>');
    if (s.length > 글자상한) s = `${s.slice(0, 글자상한)}…[${s.length}자 중 ${글자상한}자까지]`;
    return s;
  };
  const 걸러내기 = (값, 깊이 = 0) => {
    if (깊이 > 12) return '<너무깊음>';
    if (typeof 값 === 'string') return 치환(값);
    if (Array.isArray(값)) return 값.map((v) => 걸러내기(v, 깊이 + 1));
    if (값 && typeof 값 === 'object') {
      const 나온것 = {};
      for (const [k, v] of Object.entries(값)) 나온것[k] = 비밀키이름.test(k) ? '<가림>' : 걸러내기(v, 깊이 + 1);
      return 나온것;
    }
    return 값;
  };
  return 걸러내기;
}
