/** 답 안에서 `코드` 를 찾고, 그 뒤 `창` 자 안에 `기대수` 가 있는지 본다. 근거 조각을 함께 낸다. */
export function 근처숫자(답, 코드, 기대수, 창 = 40) {
  const 글 = String(답 ?? '');
  let 자리 = 글.indexOf(코드);
  while (자리 !== -1) {
    const 조각 = 글.slice(자리, 자리 + 창);
    // 숫자 경계를 지킨다 — `4` 를 찾을 때 `14` 에 걸리면 거짓 통과가 된다.
    if (new RegExp(`(?<![0-9])${기대수}(?![0-9])`).test(조각.slice(코드.length))) {
      return { 통과: true, 근거: 조각 };
    }
    자리 = 글.indexOf(코드, 자리 + 1);
  }
  return { 통과: false, 근거: 글.includes(코드) ? `${코드} 는 있는데 ${창}자 안에 ${기대수} 가 없다` : `${코드} 가 답에 없다` };
}

const 포함 = (답, 낱말들) => 낱말들.filter((w) => String(답 ?? '').includes(w));

/** 새로 생긴 파일 중 내용이 `바이트` 와 정확히 같은 것. 없으면 null. */
export function 바이트일치(새파일내용, 바이트) {
  for (const [상대, 내용] of Object.entries(새파일내용 ?? {})) {
    if (내용 === 바이트) return 상대;
  }
  return null;
}

