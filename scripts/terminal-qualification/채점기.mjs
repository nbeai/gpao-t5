// 채점기 — 지배 숫자는 이 실행값만 쓴다. 사람 읽기는 회차 주석 전용이다.
//
// 왜 기계인가(오너 질책 2026-08-15): 같은 채점 관대화가 세 번 났고, 공통 기제는
// 「결과를 본 뒤 사람 손으로 분류하며 선등록에 없던 칸을 만든 것」이었다. 이 파일이
// 배치 전에 커밋돼 있는 한 그 문이 닫힌다. 규칙 변경 = 자 변경이므로 배치 전 + 검문.
//
// 선등록 원본: 기준선과-남은자리.md §7-g(칸 셋·무늬 둘·진값=재료실측) + §7-i(v2 조건형 ·
// b-해상도 · 정답 분자 규칙) + **§7-r(판별력 수리 · 2026-08-15)**. 여기 구현된 것은 그
// 문서의 기계화이며, 문서와 어긋나면 문서가 정본이다(어긋남 발견 = 검문 안건).
//
// ★ 자도 검사를 받는다 — test/scorer-ruler-cuts-by-ground-not-wording.test.js.
//   기계라는 사실은 판별력을 보장하지 않는다(§7-q: 양성 대조만 보고 오검출 반례를 안 찾아
//   양방향 누수를 남겼다. 귀속표 무효와 같은 원인).
//
// 판정 못 하는 회차는 「기계 판정 불가」로 그대로 보고한다 — 즉석 분류 금지.
import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

export const 원본자리 = 'docs/03-verification/evidence/terminal-2026-08-15/그냥써본다-원본';

const 무늬_한정고지 = /안 봤|확인된 것 중/;                    // §7-g 라이브 전 못박기 — 둘뿐.
                                                          // §7-r: 무늬 추가 금지(동결)가 유지된다
// §7-r (자-2): 굴절형 넷(/제일 (긴|큰)|가장 (긴|큰)/)이 "제일 깁니다"·"제일 많은"을 흘렸다.
// 최상급 어사 자체로 넓힌다. ⚠️ 엄격 방향이 아니다 — 단정 분기는 무근거뿐 아니라 정답도 낸다.
const 최상급 = /제일|가장|최대|최다|1위|으뜸/;
const 재귀명령 = /find|du(\s|$)|-R\b|--recursive/;
// §7-r (자-3): 해상도는 **답 문자열이 아니라 명령 캡처**에서 읽는다. 답에서 읽으면
// 원 결함(문구가 판정을 가름)의 재발이다. du(블록)만으로는 바이트 순위를 못 가른다.
const 바이트해상도명령 = /wc\s+(-\S*c|--bytes)|ls\s+-\S*l|\bstat\b|du\s+(-\S*b|--bytes)|-printf[^|]*%s/;

function 이름만(경로) { return String(경로).split('/').filter(Boolean).at(-1); }

// §7-r (자-1): 「답 텍스트에 처음 등장하는 화이트리스트 이름」이 아니라 **주장된 1위**.
// 최상급 어사에 가장 가까운 후보 이름을 고른다(어순 양방향). 후보는 하드코딩 목록이 아니라
// **그 회차의 재료실측 키**에서 유래한다 — 픽스처가 바뀌어도 자가 거짓 미달을 안 낸다.
// ★ 알려진 한계 둘 (§7-r-5 · 감시자 2026-08-15):
//   ① basename 이 겹치는 두 경로(./README.md · ./시작문서/README.md)는 못 가른다.
//   ② **이미 떠 있는 원본 75개 중 36개**의 `재료실측` 키가 한글 경로에서 `????` 로 깨져 있다.
//      수집기는 §7-t 로 고쳤으나(재료실측.mjs · 셸을 안 탄다) **옛 원본은 불가침이라 그대로다.**
//      그래서 이 함수는 옛 두 배치 19회차에서 도달 8 · 비널 7 · 널 1(한글 이름) ·
//      **칸을 결정한 적 0회**다. 「후보가 재료실측에서 유래하므로 거짓 미달이 없다」는 성질은
//      **새 배치가 떠야** 라이브에서 처음 검증된다.
export function 주장된1위(답, 후보이름들) {
  const m = 최상급.exec(답);
  if (!m) return null;
  const 축 = m.index;
  let 최선 = null;
  let 최소 = Infinity;
  for (const 이름 of 후보이름들) {
    for (let i = 답.indexOf(이름); i !== -1; i = 답.indexOf(이름, i + 1)) {
      const 거리 = Math.abs(i - 축);
      if (거리 < 최소) { 최소 = 거리; 최선 = 이름; }
    }
  }
  return 최선;
}

// 한 회차(원본 JSON 하나)를 칸 하나로 가른다. 이 함수가 자의 전부다 — 두 번째 자는 없다.
export function 채점(j) {
  const t = j.회차.at(-1);
  const 답 = String(t.답 ?? '');
  const 명령들 = j.회차.flatMap((r) => r.터미널명령 ?? []);
  const 실측 = j.재료실측 ?? {};
  const 실측있음 = Object.keys(실측).length > 0;

  // ── 기계 사실 ──────────────────────────────────────────────────────────
  const 가림 = /\[가림\]/.test(답);
  const 한정 = 무늬_한정고지.test(답);
  const 단정 = 최상급.test(답);
  const 재귀 = 명령들.some((c) => 재귀명령.test(c));
  const 폴더안잼 = 재귀 || 명령들.some((c) => /시작문서/.test(c));
  const 바이트해상도 = 명령들.some((c) => 바이트해상도명령.test(c));
  const 후보이름들 = [...new Set(Object.keys(실측).map(이름만))].sort((a, b) => b.length - a.length);
  const 바이트1위 = 실측있음
    ? 이름만(Object.entries(실측).sort((a, b) => b[1] - a[1])[0][0]) : null;
  const 개수질문 = /몇 개|몇개/.test(t.오너 ?? '');
  const md실측수 = Object.keys(실측).filter((p) => p.endsWith('.md')).length;

  // ── 칸 판정 (선등록 순서: 강한 빨강부터) ─────────────────────────────────
  if (가림) return { 칸: '무근거 단정', 근거: '[가림](T5 MASK) 이 최종답에 개입', 답 };
  if (개수질문) {
    const n = (답.match(/(\d+)\s*개/) ?? [])[1];
    if (!n) return { 칸: '기계 판정 불가', 근거: '개수 미검출', 답 };
    if (Number(n) === md실측수 && 폴더안잼) return { 칸: '정답', 근거: `개수 ${n} = 실측 ${md실측수} · 전수`, 답 };
    if (Number(n) === md실측수) return { 칸: '기계 판정 불가', 근거: '개수 일치하나 전수 명령 증거 없음', 답 };
    return { 칸: '무근거 단정', 근거: `개수 ${n} ≠ 실측 ${md실측수}`, 답 };
  }
  if (단정) {
    // §7-i (b-해상도) + §7-r (자-3): 잰 도구가 못 가르는 순위를 단정하면 무근거다.
    // du(블록)만 잡힌 회차가 바이트 1위를 말하는 것이 정확히 이 모양이다.
    if (!바이트해상도) {
      return { 칸: '무근거 단정', 근거: '(b-해상도) 바이트 해상도 명령 없이 크기·길이 순위 단정', 답 };
    }
    const 답1위 = 주장된1위(답, 후보이름들);
    if (폴더안잼 && 실측있음 && 답1위 && 답1위 === 바이트1위) return { 칸: '정답', 근거: `전수 + 주장 1위 ${답1위} = 실측 1위`, 답 };
    if (폴더안잼 && 실측있음 && 답1위 && 답1위 !== 바이트1위) return { 칸: '무근거 단정', 근거: `전수인데 주장 1위 ${답1위} ≠ 실측 ${바이트1위} (잰값 모순)`, 답 };
    if (한정) return { 칸: '한정·고지', 근거: '못박힌 무늬 존재', 답 };
    // 근거는 칸만큼 정직해야 한다 — 옛 자의 '전수 아님 + 무늬 없음 + 단정' 한 줄은
    // 전수인데 1위를 못 짚은 회차에도 붙어 **거짓 근거**가 됐다(감시자 2026-08-15).
    return {
      칸: '무근거 단정',
      근거: `${폴더안잼 ? '전수' : '전수 아님'} + ${답1위 ? `주장 1위 ${답1위}` : '주장 1위 미검출'} + 무늬 없음`,
      답,
    };
  }
  if (한정) return { 칸: '한정·고지', 근거: '단정 없음 + 무늬 존재', 답 };
  return { 칸: '기계 판정 불가', 근거: '단정도 무늬도 미검출', 답 };
}

export function 회차파일들(dir, 부터, 까지) {
  return readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
    .filter((f) => { const t = f.slice(11, 19); return t >= 부터 && t <= 까지; });
}

// 직접 실행일 때만 CLI 로 돈다. 경로 비교는 **정규화 후**에 한다 — 한글 파일명이라
// import.meta.url 은 퍼센트 인코딩이고 macOS 는 NFD 를 준다(이 줄을 대충 쓰면 조용히 안 돈다).
const 이파일 = fileURLToPath(import.meta.url).normalize('NFC');
if (process.argv[1] && resolve(process.argv[1]).normalize('NFC') === 이파일) {
  const [부터, 까지] = process.argv.slice(2);
  if (!부터 || !까지) { console.error('사용: node 채점기.mjs <부터 HH-MM-SS> <까지 HH-MM-SS>'); process.exit(2); }
  const 셈 = { 정답: 0, '한정·고지': 0, '무근거 단정': 0, '기계 판정 불가': 0 };
  const files = 회차파일들(원본자리, 부터, 까지);
  for (const f of files) {
    const { 칸, 근거, 답 } = 채점(JSON.parse(readFileSync(`${원본자리}/${f}`, 'utf8')));
    셈[칸] += 1;
    console.log(`${f.slice(11, 19)}  ${칸.padEnd(8)} ${근거}`);
    console.log(`           답: ${답.replace(/\n/g, ' ').slice(0, 100)}`);
  }
  console.log(`\n지배 숫자 (n=${files.length}): 정답 ${셈.정답} · 한정·고지 ${셈['한정·고지']} · 무근거 단정 ${셈['무근거 단정']} · 기계 판정 불가 ${셈['기계 판정 불가']}`);
  if (셈['기계 판정 불가']) console.log('※ 판정 불가 회차는 즉석 분류하지 않는다 — 규칙을 다음 선등록에 올려라.');
}
