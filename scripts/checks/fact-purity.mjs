// §1-B 오너 지시(2026-08-09) — 「손이 세는 사실은 도메인 낱말 없이 참이어야 한다」.
//
// 그물의 힘은 기계성에서 나온다. 도메인 낱말이 사실 층에 스미는 순간 F-12(문구 목록)로
// 부패하기 시작하고, 정산이 아니라 원고·설계·강의 파일을 다루는 사용자에게는 거짓이 된다.
//
// 이 모듈이 게이트와 반대시험(검사)의 **한 벌 기계**다 — 게이트는 실제 소스로 부르고,
// 검사는 심은 소스로 불러 빨개지는 것을 확인한다(규격 4: 반대시험 없는 불변식은 장식이다).
// 주석 처리 방식은 「서비스 이름 0건」 게이트의 그 기계 그대로다(새 자를 만들지 않는다).
//
// 경계 둘(규격 5 + 실측 2026-08-09):
//   · 그물 트리거의 총·전체·합계는 업종 어휘가 아니라 **일반 수량어**다 — 이 불변식의
//     대상이 아니고 「세 성질」(문구는 최소 보조)이 다스린다.
//   · 원고·강의·설계 같은 **내용 종류** 낱말도 대상이 아니다 — locate 의 성격 분류표는
//     여러 업의 자료를 포괄하는 선언이지 한 업으로 갈라지는 분기가 아니다(§1-B 인용문이
//     보호하는 바로 그 사용자들의 낱말이다). 금지는 **상거래·정산 군** — 실측된 부패 벡터.

/** 사실을 세는 층의 정의역 — 사실 층이 늘면 여기 등록해야 한다(등록 없는 추가는 게이트가 막는다). */
export const 사실층정의역 = [
  'src/runtime/local-file.js',                 // 표 사실 · 이웃 합계 · 숫자 대조 · 표맥락에서
  'src/runtime/local-locate.js',               // 자료기간 · 성격
  'src/runtime/capsule.js',                    // 표맥락(캡슐 안 손 전달)
  'src/kernel/l2-plan/exit-verification.js',   // 그물 트리거(원장 대조)
  'src/kernel/turn.js',                        // 표맥락 배선(실행문맥) — 세지 않지만 표지가 지나는 자리
];

/**
 * 업종 금지어 — 상거래·정산 군. 기준선 0 하드 · 상향 금지(PM 실측 2026-08-09 · 0건).
 * ⚠ 단어 경계가 아니라 **부분 문자열**로 본다 — 한글 합성어(`정산내역`)는 경계 검사가
 * 놓친다. 사실 층 코드에서 이 어근의 등장은 합성어라도 전부 분기 재료다.
 */
export const 업종금지어 = ['정산', '매출', '거래처', '매입', '부가세', '세금', '급여', '인보이스', 'invoice', '견적', '발주', '계약서'];

/** 사실 층의 표지 — 이 이름이 코드에 나타나는 파일은 사실 층이다(주석 제외). */
export const 사실층표지 = /표맥락|같은자리표|표사실|쓴숫자대조|자료기간/;

/** 주석을 걷은 코드 줄들 — 실측 인용 주석은 부패가 아니다(서비스 이름 게이트와 같은 계약). */
export function 주석뺀코드(src) {
  return String(src ?? '').replace(/\/\*[\s\S]*?\*\//g, '').split('\n')
    .map((l) => (l.trim().startsWith('//') ? '' : l.replace(/\/\/.*$/, '')));
}

/**
 * 정의역 파일들의 코드에서 업종 어휘를 센다.
 * @param {Array<{path:string, src:string}>} 파일들
 * @returns {Array<{path:string, 줄:string}>}
 */
export function 업종어휘위반(파일들) {
  const 위반 = [];
  for (const { path, src } of 파일들 ?? []) {
    주석뺀코드(src).forEach((line, i) => {
      const low = line.toLowerCase();
      for (const w of 업종금지어) {
        if (low.includes(w)) 위반.push({ path, 줄: `${path}:${i + 1}  "${w}" ← ${line.trim().slice(0, 60)}` });
      }
    });
  }
  return 위반;
}

/**
 * 등록 없는 사실 층 추가를 잡는다 — 표지가 코드에 나타나는데 정의역에 없는 파일.
 * @param {Array<{path:string, src:string}>} 파일들 (src 전체)
 */
export function 미등록사실층(파일들, 등록 = 사실층정의역) {
  const 등록셋 = new Set(등록);
  return (파일들 ?? [])
    .filter(({ path, src }) => !등록셋.has(path) && 주석뺀코드(src).some((l) => 사실층표지.test(l)))
    .map((x) => x.path);
}
