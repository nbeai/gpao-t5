// L2 · **이월 행동** — 지난 턴에 시도했다 못 끝낸 행동이 이번 턴에 조용히 실행되지 않게 한다.
//
// 절대 게이트 "**현재 요청 침해**"의 보호다. 지금까지 그 자리를 지킨 것은 심문
// (`currentRequestCalls`)이었다 — 모델이 과거 행동과 현재 요청 행동을 함께 냈을 때
// **런타임이 모델에게 되물어** 현재 것만 남겼다.
//
// ── 심문을 걷는 이유(실측) ─────────────────────────────────────────────────
// 같은 코드·같은 문장·같은 437개 고정판, 2026-08-04:
//   A 팔(심문 켬) — 모델호출 18 · 토큰 178k · 무진전반복 4 · 이동 353
//   B 팔(심문 끔) — 모델호출  5 · 토큰  51k · 무진전반복 0 · 이동 367
// 심문은 왕복만 먹은 게 아니다. 모델의 선택을 **조용히 버리면서** 모델이 자기 계획을 잃고
// 같은 자리를 다시 밟게 만들었다(무진전반복 4). 계약 ①("모델이 낸 호출을 버리지 않는다")과
// 정면으로 어긋난다.
//
// ── 대체 보호는 "버리기"가 아니라 "보이기"다 ───────────────────────────────
// 그래도 위험은 가설이 아니라 실측됐다 — 다중 호출 병합을 걷어내자 걸음 루프가 심문이
// 걷어내던 **과거 삭제를 다시 받아 실행했다**(`pc-hands-c-closure` #293).
//
// 그래서 버리는 대신 **승인 경계로 올린다**. 지난 턴에 시도했다 못 끝낸 행동과 같은 지문이
// 이번 턴에 다시 나오면, 되돌릴 수 있든 없든 자동으로 실행하지 않고 사용자에게 보인다.
//   · 왕복 0 — 모델에게 되묻지 않는다
//   · 모델의 선택은 안 버려진다 — 카드에 그대로 실린다
//   · 사용자가 정말 "그거 마저 해줘"라고 했으면 한 번 누르면 된다
//   · 사용자가 다른 얘기를 하고 있었으면 **그 자리에서 보인다** — 조용히 실행되지 않는다
//
// 이건 모델 대신 판단하는 게 아니다. 런타임은 "이 행동은 이번 발화가 아니라 지난 턴에서
// 왔다"는 **사실**만 세우고, 할지 말지는 사용자가 정한다.
import { 호출지문 } from './recovery-ladder.js';

/**
 * 앞 턴 교환에서 **못 끝낸** 행동의 지문을 모은다.
 *
 * 성공한 것은 담지 않는다. 담으면 "아까 읽은 거 다시 보여줘" 같은 정상 이어가기가
 * 전부 승인 카드로 올라간다 — 마찰을 늘리는 쪽이 곧 뒤쳐지는 쪽이다.
 *
 * @param {Array<{tool?:string, args?:object, failureState?:string}>} 앞턴교환
 * @returns {Set<string>}
 */
export function 이월지문(앞턴교환) {
  const 모음 = new Set();
  for (const x of Array.isArray(앞턴교환) ? 앞턴교환 : []) {
    if (!x?.tool) continue;
    if ((x.failureState ?? 'none') === 'none') continue;   // 끝난 일은 이월이 아니다
    const k = 호출지문(x.tool, x.args ?? {});
    if (k) 모음.add(k);
  }
  return 모음;
}

/**
 * 이 호출이 **이월**인가 — 지난 턴의 미완료 행동과 같은 지문인가.
 *
 * 판정만 낸다. 무엇을 버릴지·무엇을 승인으로 올릴지는 호출자가 정한다. 여기서 실행 결정까지
 * 내면 이 모듈이 두 번째 심문이 된다.
 *
 * @param {{name?:string, tool?:string, args?:object}} 호출
 * @param {Set<string>} 지문모음
 * @returns {boolean}
 */
export function 이월행동(호출, 지문모음) {
  if (!(지문모음 instanceof Set) || 지문모음.size === 0) return false;
  const tool = 호출?.name ?? 호출?.tool;
  if (!tool) return false;
  return 지문모음.has(호출지문(tool, 호출?.args ?? {}));
}

/**
 * **이번 발화가 요구하지 않은 파괴인가.**
 *
 * 심문이 지키던 두 번째 자리다. 모델이 한 응답 안에서 이번 요청 행동과 함께 **사용자가 가리킨
 * 적 없는 파일의 삭제**를 냈을 때, 심문은 그것을 되물어 버렸다. 실측 두 건이 그 모양이다:
 *   · "정산_3월.csv를 지워줘" → 모델이 `옛파일.csv` 삭제까지 함께 냄
 *   · "정리본.md 에 적어줘"   → 모델이 `견적서-최종.md` 삭제까지 함께 냄
 *
 * 여기서도 **버리지 않고 보인다.** 그리고 목록으로 짐작하지 않는다(§4-6) — 발화를 이미 파싱하는
 * `parseFileRequest` 하나만 읽고, 그 결과의 **모양**으로만 가른다:
 *
 *   · `action: 'unknown'` — 발화가 작업을 특정하지 않았다("작업 폴더 좀 정리해줘").
 *     **범위는 모델의 판단이다. 자동.** 여기를 막으면 대량 정리가 통째로 죽는다.
 *   · `action: 'delete'` — 발화가 파괴를 요구했다. 자리를 가리켰으면 그 **안**이면 자동이고
 *     (폴더를 가리켰으면 그 안 전부), 자리를 안 가리켰으면("임시폴더 지워줘") 자동이다.
 *   · 그 밖(`write`·`read`·`move`) — 발화는 **다른 구체 작업**을 지목했는데 파괴가 섞였다.
 *     되돌릴 수 있어도 **묻는다.** 문제는 위험이 아니라 **이번 발화가 아니라는 것**이다.
 *
 * 묻기를 늘리는 것이므로 자리를 좁게 잡았다 — `delete` 하나뿐이고, 옮기기·쓰기·읽기는 안 본다.
 * 되돌릴 수 있는 이동까지 물으면 대량 정리가 카드 수백 장이 된다(자동성이 의무다).
 *
 * @param {{kind?:string, 대상?:string}} 행동  이 호출의 권한 종류와 파일 대상
 * @param {{action?:string, path?:string}} 발화  `parseFileRequest(현재 발화)` 의 결과
 */
export function 발화밖파괴(행동, 발화) {
  if (행동?.kind !== 'delete') return false;
  const 대상 = 정규화(행동?.대상);
  if (!대상) return false;                        // 대상을 모르면 이 판정으로 막지 않는다
  const 요구 = 발화?.action;
  if (!요구 || 요구 === 'unknown') return false;  // 발화가 작업을 특정 안 함 → 범위는 모델의 것
  if (요구 !== 'delete') return true;             // 발화는 다른 구체 작업을 지목했다
  const 가리킨곳 = 정규화(발화?.path);
  if (!가리킨곳) return false;                    // 파괴를 요구했고 자리는 안 가리켰다 → 모델의 판단
  return !(대상 === 가리킨곳 || 대상.endsWith(`/${가리킨곳}`) || 대상.startsWith(`${가리킨곳}/`)
    || 대상.includes(`/${가리킨곳}/`));
}

const 정규화 = (v) => String(v ?? '').replace(/\\/g, '/').replace(/^\.\//, '').replace(/\/+$/, '').trim();
