  // ── **답이 지어낸 실물** — 완료형인지 묻기 **전에** 잰다 (2026-08-11) ──────
  //
  // 바로 위 `못한걸음` 그물이 이미 밟은 길이다: *"이 그물만은 문구가 아니라 원장으로 연다."*
