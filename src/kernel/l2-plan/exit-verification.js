// L2 · **출구 검증** — 모델이 완료를 주장하면 원장·실물과 대조하고,
// 불일치면 **사용자에게 가지 않고 모델에게 돌려준다.**
//
// 정본 §S5 H08 재개봉 절차:
//   · 기존 통과: FILE 판정 + write 강제 + 계약 결합 영수증
//   · 무효화한 사실: **강제가 쓰레기 산출물을 만든다**(실측 2026-08-03 — 모델이 낼 것이
//     없는데 억지로 로그 파일을 만들었다). 그래서 중간 강제는 걷었다.
//   · **완료 검증 자체는 유지하되 출구로 옮긴다.** 여기가 그 자리다.
//
// ── 왜 중간이 아니라 출구인가 ───────────────────────────────────────────────
// 중간에서 강제하면 모델의 판단을 뺏는다 — 낼 것이 없을 때 억지로 무언가를 만들어 낸다.
// 출구에서 대조하면 판단은 모델의 것으로 두고 **거짓만 막는다.** 그리고 불일치를 사용자에게
// 보내지 않고 모델에게 돌려주므로 **대필도 아니다** — 모델이 사실을 보고 자기 말로 고쳐 쓴다.
//
// 실측 근거(2026-08-04 S4 라이브): 캡슐이 "손을 한 번도 쓰지 않았어요"를 정직하게 돌려줬는데
// 모델의 최종 답은 "옮겼어"였다. 원인 셋(응답 모양·이유·이름)은 고쳤지만, 원인을 고치는 것만
// 으로는 다음 계열 거짓 완료를 못 막는다. **출구가 마지막 그물이다.**
//
// ── 무엇을 재지 않는가 ─────────────────────────────────────────────────────
// 이 자리는 **문구 규칙을 키우는 곳이 아니다**(§4-6 금지). 재는 것은 둘뿐이다:
//   ① 완료를 주장했는가 — 지난 일을 가리키는 **완료형**인가
//   ② 원장에 그 일이 있는가 — 실행 사실과 숫자
// 예문을 늘려 잡으려 하면 다음 문장에서 또 샌다. 그래서 **주장은 넓게 잡고 판정은 원장으로**
// 한다 — 물어보는 답·계획 진술은 애초에 완료 주장이 아니므로 지나간다.

/** 완료를 주장하는 답인가 — **지난 일을 가리키는 완료형**만 본다. */
function 완료주장인가(reply) {
  const t = String(reply ?? '');
  if (!t.trim()) return false;
  // 물음·제안은 완료 주장이 아니다. 먼저 걷어낸다(과잉 차단 방지).
  if (/\?|까요|할까|드릴까|골라|말해줘|어떻게 할지/.test(t)) return false;
  // 미완료를 밝히는 답은 대상이 아니다 — 정직한 미완료를 막으면 반대 방향의 거짓이 된다.
  if (/아직|남았|남아|못 했|하지 않았|안 했/.test(t)) return false;
  // **목록으로 잡지 않는다.** 첫 판은 동사를 늘어놓았다가 "저장해 뒀어요"에 뚫렸고,
  // 글자를 늘어놓았다가 "끝냈어요"의 `냈` 에 또 뚫렸다. **목록은 늘 뚫린다**(§4-6).
  //
  // 한국어 과거형은 어간 + 았/었 이 줄어들며 **받침 ㅆ** 로 끝난다(했·갔·왔·봤·뒀·냈·췄…).
  // 그래서 글자 목록이 아니라 **글자 구조**로 본다: 종성이 ㅆ 이고 다음이 어·습니·다·네·지.
  // 이건 다음 동사에서도 같다 — 늘릴 것이 없다.
  return 과거형있나(t) || /완료(했|됐|입니다|예요|이에요)/.test(t);
}

/**
 * 종성이 ㅆ 인 음절 뒤에 종결 어미가 오는가 — 한국어 과거형의 **구조**.
 *
 * 다만 `있/없/계시` 는 ㅆ 받침이지만 **현재 상태**다("437개가 있어요"·"그런 건 없어요").
 * 이걸 과거로 읽으면 정상 답이 전부 완료 주장으로 잡힌다(실측 2026-08-04 — 구조로 바꾸자마자
 * 그 검사가 물었다). 예외 셋뿐이고, 늘어나는 목록이 아니라 **한국어의 붙박이**다.
 */
function 과거형있나(t) {
  const 종결 = ['어', '습', '다', '네', '지'];
  const 현재상태 = ['있', '없', '겠'];
  for (let i = 0; i < t.length - 1; i += 1) {
    const 글자 = t[i];
    const c = t.codePointAt(i);
    if (c < 0xAC00 || c > 0xD7A3) continue;       // 한글 음절이 아니면 지나간다
    if ((c - 0xAC00) % 28 !== 20) continue;        // 종성 ㅆ (인덱스 20) 만
    if (현재상태.includes(글자)) continue;
    // 뒤에 공백이 끼는 경우까지 본다("저장해 뒀 어요" 같은 띄어쓰기 흔들림).
    const 뒤 = t.slice(i + 1).replace(/^\s+/, '');
    if (종결.some((e) => 뒤.startsWith(e))) return true;
  }
  return false;
}

/** 답이 말한 개수 — "N개" 형태만. 없으면 null(숫자를 안 말했으면 대조하지 않는다). */
function 말한개수(reply) {
  const m = [...String(reply ?? '').matchAll(/(\d[\d,]*)\s*개/g)]
    .map((x) => Number(x[1].replace(/,/g, '')))
    .filter((n) => Number.isFinite(n) && n > 0);
  return m.length ? Math.max(...m) : null;
}

/** 실행 하나가 실제로 **몇 개를 바꿨는가**. 묶음·캡슐은 한 영수증이 여럿을 담는다. */
function 바꾼개수(rec) {
  if ((rec?.failureState ?? 'none') !== 'none') return 0;
  const r = rec?.result;
  if (Array.isArray(r?.moved)) return r.moved.length;              // bulk_move
  if (Array.isArray(r?.innerReceipts)) {
    return r.innerReceipts.reduce((s, x) => s + 바꾼개수(x), 0);   // 캡슐 — 안쪽을 센다
  }
  const action = rec?.actualCall?.args?.action;
  if (action && ['read', 'list', 'versions'].includes(action)) return 0;
  return r === undefined ? 0 : 1;
}

/**
 * 완료 주장을 원장과 대조한다.
 *
 * @param {{reply:string, receipts:Array, 이미돌려줬나?:boolean}} p
 * @returns {{일치:boolean, 사용자에게:boolean, 모델에게?:string, 실제:number}}
 */
export function 완료주장검증({ reply, receipts = [], 이미돌려줬나 = false }) {
  const 실제 = (receipts ?? []).reduce((s, r) => s + 바꾼개수(r), 0);
  // **확인된 실행이 하나라도 있는가.** 읽기도 실행이다 — 읽고 답한 턴은 "말로만 끝남"이 아니다.
  //
  // 첫 판은 `실제`(바꾼 수) 0 을 곧바로 거짓으로 봤다. 그러자 파일을 읽고 "정리했어요"라고
  // 답하는 **정상 턴**이 전부 걸렸고, 순서 동결 검사가 그것을 잡았다(실측 2026-08-04).
  // 정본이 말한 것은 "**파일 요청이 말로만 끝남**"이다 — 손이 아예 안 나간 자리다.
  const 확인된실행 = (receipts ?? []).filter((r) => (r?.failureState ?? 'none') === 'none'
    && r?.actualCall?.tool && r?.result !== undefined).length;
  const 지나감 = { 일치: true, 사용자에게: true, 실제 };

  if (!완료주장인가(reply)) return 지나감;
  // **한 턴에 한 번만 돌려준다.** 두 번 되돌리면 왕복이 무한이 되고, 그 비용은 사용자가 문다.
  if (이미돌려줬나) return 지나감;

  if (확인된실행 === 0) {
    return {
      일치: false,
      사용자에게: false,
      실제,
      // **사실만 준다.** "다시 써라"가 아니라 "원장에 이런 게 있다"이다 — 무엇을 말할지는 모델이 정한다.
      모델에게: '이 턴의 원장에 실제로 바뀐 것이 하나도 없다. 답은 끝냈다고 말하고 있다.',
    };
  }

  const 말한것 = 말한개수(reply);
  // 숫자를 안 말했으면 대조할 것이 없다. 말했으면 **자릿수가 다를 때만** 어긋남으로 본다 —
  // 하나 차이를 잡으려 들면 "대략 100개"처럼 정직한 어림을 거짓으로 만든다.
  if (말한것 !== null && (말한것 > 실제 * 2 || 실제 > 말한것 * 2)) {
    return {
      일치: false,
      사용자에게: false,
      실제,
      모델에게: `답은 ${말한것}개라고 말하는데 이 턴의 원장에 실제로 바뀐 것은 ${실제}개다.`,
    };
  }
  return 지나감;
}
