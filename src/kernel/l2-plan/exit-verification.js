// L2 · **출구 검증** — 모델이 완료를 주장하면 원장·실물과 대조하고,
// 불일치면 **사용자에게 가지 않고 모델에게 돌려준다.**
//
// 정본 §S5 H08 재개봉 절차:
//   · 기존 통과: FILE 판정 + write 강제 + 계약 결합 영수증
//   · 무효화한 사실: **강제가 쓰레기 산출물을 만든다**(실측 2026-08-03 — 모델이 낼 것이
//     없는데 억지로 로그 파일을 만들었다). 그래서 중간 강제는 걷었다.
//   · **완료 검증 자체는 유지하되 출구로 옮긴다.** 여기가 그 자리다.
//
// ── 왜 중간이 아니라 출구인가 ───────────────────────────────────────────────
// 중간에서 강제하면 모델의 판단을 뺏는다 — 낼 것이 없을 때 억지로 무언가를 만들어 낸다.
// 출구에서 대조하면 판단은 모델의 것으로 두고 **거짓만 막는다.** 그리고 불일치를 사용자에게
// 보내지 않고 모델에게 돌려주므로 **대필도 아니다** — 모델이 사실을 보고 자기 말로 고쳐 쓴다.
//
// 실측 근거(2026-08-04 S4 라이브): 캡슐이 "손을 한 번도 쓰지 않았어요"를 정직하게 돌려줬는데
// 모델의 최종 답은 "옮겼어"였다. 원인 셋(응답 모양·이유·이름)은 고쳤지만, 원인을 고치는 것만
// 으로는 다음 계열 거짓 완료를 못 막는다. **출구가 마지막 그물이다.**
//
// ── 무엇을 재지 않는가 ─────────────────────────────────────────────────────
// 이 자리는 **문구 규칙을 키우는 곳이 아니다**(§4-6 금지). 재는 것은 둘뿐이다:
//   ① 완료를 주장했는가 — 지난 일을 가리키는 **완료형**인가
//   ② 원장에 그 일이 있는가 — 실행 사실과 숫자
// 예문을 늘려 잡으려 하면 다음 문장에서 또 샌다. 그래서 **주장은 넓게 잡고 판정은 원장으로**
// 한다 — 물어보는 답·계획 진술은 애초에 완료 주장이 아니므로 지나간다.

/**
 * 못 한 것을 **밝히고 있는가.** 정직한 미완료를 거짓으로 몰지 않기 위한 유일한 문구 판정이고,
 * 한 곳에만 둔다 — 두 벌이 되면 언젠가 한쪽만 바뀐다.
 */
function 미완료를밝혔나(t) {
  return /아직|남았|남아|못 했|하지 않았|안 했|못 눌|확인.{0,3}못|실패/.test(String(t ?? ''));
}

/** 완료를 주장하는 답인가 — **지난 일을 가리키는 완료형**만 본다. */
function 완료주장인가(reply) {
  const t = String(reply ?? '');
  if (!t.trim()) return false;
  // 물음·제안은 완료 주장이 아니다. 먼저 걷어낸다(과잉 차단 방지).
  if (/\?|까요|할까|드릴까|골라|말해줘|어떻게 할지/.test(t)) return false;
  // 미완료를 밝히는 답은 대상이 아니다 — 정직한 미완료를 막으면 반대 방향의 거짓이 된다.
  if (미완료를밝혔나(t)) return false;
  // **목록으로 잡지 않는다.** 첫 판은 동사를 늘어놓았다가 "저장해 뒀어요"에 뚫렸고,
  // 글자를 늘어놓았다가 "끝냈어요"의 `냈` 에 또 뚫렸다. **목록은 늘 뚫린다**(§4-6).
  //
  // 한국어 과거형은 어간 + 았/었 이 줄어들며 **받침 ㅆ** 로 끝난다(했·갔·왔·봤·뒀·냈·췄…).
  // 그래서 글자 목록이 아니라 **글자 구조**로 본다: 종성이 ㅆ 이고 다음이 어·습니·다·네·지.
  // 이건 다음 동사에서도 같다 — 늘릴 것이 없다.
  return 과거형있나(t) || /완료(했|됐|입니다|예요|이에요)/.test(t);
}

/**
 * 종성이 ㅆ 인 음절 뒤에 종결 어미가 오는가 — 한국어 과거형의 **구조**.
 *
 * 다만 `있/없/계시` 는 ㅆ 받침이지만 **현재 상태**다("437개가 있어요"·"그런 건 없어요").
 * 이걸 과거로 읽으면 정상 답이 전부 완료 주장으로 잡힌다(실측 2026-08-04 — 구조로 바꾸자마자
 * 그 검사가 물었다). 예외 셋뿐이고, 늘어나는 목록이 아니라 **한국어의 붙박이**다.
 */
function 과거형있나(t) {
  const 종결 = ['어', '습', '다', '네', '지'];
  const 현재상태 = ['있', '없', '겠'];
  for (let i = 0; i < t.length - 1; i += 1) {
    const 글자 = t[i];
    const c = t.codePointAt(i);
    if (c < 0xAC00 || c > 0xD7A3) continue;       // 한글 음절이 아니면 지나간다
    if ((c - 0xAC00) % 28 !== 20) continue;        // 종성 ㅆ (인덱스 20) 만
    if (현재상태.includes(글자)) continue;
    // 뒤에 공백이 끼는 경우까지 본다("저장해 뒀 어요" 같은 띄어쓰기 흔들림).
    const 뒤 = t.slice(i + 1).replace(/^\s+/, '');
    if (종결.some((e) => 뒤.startsWith(e))) return true;
  }
  return false;
}

/**
 * 답이 말한 개수 — "N개" 형태만. 없으면 null(숫자를 안 말했으면 대조하지 않는다).
 *
 * `개월`·`개년` 은 개수가 아니라 **기간**이다. 실측(2026-08-04): 모델이
 * "`_정리됨/6개월_이전/` 으로 옮겼어"라고 답하자 이 자리가 "6개"로 읽어 개수 대조를
 * 걸었다 — 정직한 답이 거짓으로 잡혔다. 단위가 이어지면 개수가 아니다.
 */
function 말한개수(reply) {
  const m = [...String(reply ?? '').matchAll(/(\d[\d,]*)\s*개(?![월년])/g)]
    .map((x) => Number(x[1].replace(/,/g, '')))
    .filter((n) => Number.isFinite(n) && n > 0);
  return m.length ? Math.max(...m) : null;
}

/** 실행 하나가 실제로 **몇 개를 바꿨는가**. 묶음·캡슐은 한 영수증이 여럿을 담는다. */
function 바꾼개수(rec) {
  if ((rec?.failureState ?? 'none') !== 'none') return 0;
  const r = rec?.result;
  if (Array.isArray(r?.moved)) return r.moved.length;              // bulk_move
  if (Array.isArray(r?.innerReceipts)) {
    return r.innerReceipts.reduce((s, x) => s + 바꾼개수(x), 0);   // 캡슐 — 안쪽을 센다
  }
  const action = rec?.actualCall?.args?.action;
  if (action && ['read', 'list', 'versions'].includes(action)) return 0;
  return r === undefined ? 0 : 1;
}

/**
 * 답이 가리킨 **자리 이름**들 — 경로처럼 생긴 토막에서 마지막 마디만 뽑는다.
 *
 * 왜 마지막 마디인가: 모델은 `Downloads/_정리됨/설치_및_압축/` 처럼 사람이 읽을 형태로 쓴다.
 * 절대경로 전체를 맞추려 들면 표기 차이 하나에 전부 어긋난다. **이름**이면 원장과 맞출 수 있다.
 */
function 가리킨자리들(reply) {
  const 이름들 = new Set();
  // 백틱·따옴표 안이든 맨몸이든, `/` 를 낀 토막을 잡는다. 확장자만 있는 파일명은 안 잡는다 —
  // 그건 읽은 파일 이야기일 뿐이고, 여기서 재는 것은 **없는 자리를 만들었다고 말하는 것**이다.
  for (const m of String(reply ?? '').matchAll(/[`'"“”]?([^\s`'"“”]*\/[^\s`'"“”]+)[`'"“”]?/g)) {
    const 마디들 = m[1].split('/').filter((s) => s && s !== '.' && s !== '..');
    const 끝 = 마디들.at(-1);
    // 한 마디짜리(`a/b` 의 b) 도 담되, 너무 짧거나 흔한 것은 대조가 무의미하다.
    if (끝 && 끝.length >= 3 && 마디들.length >= 2) 이름들.add(끝);
  }
  return [...이름들];
}

/**
 * 답에 **실행하지 않은 명령**이 실렸는가 — 코드블록 안의 셸 명령만 본다.
 *
 * 라이브 실측 2회(2026-08-04 · 사람 사용시험 · gpt-5.1 · 격리 증명 통과):
 *   원장   `local.file list ~/Documents` → blocked
 *   T5     "터미널에서 직접 확인해 볼게.\n\n```\nls -al ~/Documents\n```"
 *   원장   `local.terminal` **호출 0건**
 *
 * 런타임은 매 호출에 터미널 손을 쥐어 줬다(같은 환경에서 3/3 확인). 모델이 쥐고도 안 쓰고
 * **명령을 글로 적었다.** 사용자에게 이건 떠넘김이다 — 자기가 실행해야 한다.
 *
 * **막지 않는다. 사실만 돌려준다.** "이 명령이 답에 있는데 원장에 그 실행이 없다."
 * 실행할지, 안 한다고 말할지, 설명으로 둘지는 모델이 정한다(§24). 문구 규칙을 키우는 것이
 * 아니라 **원장 대조**다 — 명령이 원장에 있으면 그냥 지나간다.
 */
function 안돌린명령(reply, 원장글) {
  const 명령들 = new Set();
  // **명령 이름을 목록으로 적지 않는다**(§4-6 · 절대원칙 8: 목록은 늘 뚫린다).
  // 게이트도 이것을 잡는다 — 커널 말귀 층에 서비스·도구 이름 분기가 늘면 침범이다.
  // 대신 **구조**로 본다: 셸이라고 **모델이 스스로 표시한** 코드블록만.
  for (const m of String(reply ?? '').matchAll(/```(bash|sh|shell|zsh|console|terminal)\n([\s\S]*?)```/g)) {
    for (const 줄 of m[2].split('\n')) {
      const c = 줄.trim().replace(/^[$#>]\s*/, '');       // 프롬프트 기호는 명령이 아니다
      if (!c || c.startsWith('#')) continue;               // 주석은 실행이 아니다
      if (c.length < 3) continue;
      명령들.add(c);
    }
  }
  return [...명령들].filter((c) => !원장글.includes(c));
}

/**
 * 완료 주장을 원장과 대조한다.
 *
 * @param {{reply:string, receipts:Array, 원장글?:string, 이미돌려줬나?:boolean}} p
 * @returns {{일치:boolean, 사용자에게:boolean, 모델에게?:string, 실제:number}}
 */
export function 완료주장검증({ reply, receipts = [], 원장글 = '', 이미돌려줬나 = false }) {
  const 실제 = (receipts ?? []).reduce((s, r) => s + 바꾼개수(r), 0);
  // **확인된 실행이 하나라도 있는가.** 읽기도 실행이다 — 읽고 답한 턴은 "말로만 끝남"이 아니다.
  //
  // 첫 판은 `실제`(바꾼 수) 0 을 곧바로 거짓으로 봤다. 그러자 파일을 읽고 "정리했어요"라고
  // 답하는 **정상 턴**이 전부 걸렸고, 순서 동결 검사가 그것을 잡았다(실측 2026-08-04).
  // 정본이 말한 것은 "**파일 요청이 말로만 끝남**"이다 — 손이 아예 안 나간 자리다.
  const 확인된실행 = (receipts ?? []).filter((r) => (r?.failureState ?? 'none') === 'none'
    && r?.actualCall?.tool && r?.result !== undefined).length;
  const 지나감 = { 일치: true, 사용자에게: true, 실제 };

  // **한 턴에 한 번만 돌려준다.** 두 번 되돌리면 왕복이 무한이 되고, 그 비용은 사용자가 문다.
  if (이미돌려줬나) return 지나감;

  // 답에 적어 놓고 안 돌린 명령은 **완료 주장이 아니어도** 본다 — "확인해 볼게" 하고
  // 명령만 보여 주는 답이 정확히 그 모양이다(미래형이라 완료 주장으로는 안 잡힌다).
  const 안돌린먼저 = 안돌린명령(reply, 원장글);
  if (안돌린먼저.length) {
    return {
      일치: false,
      사용자에게: false,
      실제,
      모델에게: `답에 명령이 실려 있는데 이 턴의 원장에 그 실행이 없다: ${안돌린먼저.join(' · ')}`,
    };
  }

  // **걸음 단위로 본다.** 손 단위로 보면 같은 손이 `focus` 로 성공했다는 이유로 그냥 지나간다 —
  // 누르기와 창 띄우기는 다른 일이다. 걸음 이름이 없는 손은 손 단위로 떨어진다(느슨하지만 정직하다).
  // 막혔다가 **같은 걸음으로 다시 해서 된 것**은 정상 회복이므로 지나간다.
  // 이 파일은 이미 `actualCall` 로 실행 사실을 읽는다(위 `확인된실행` 과 같은 자리) —
  // 실행된 호출만 여기 남고, 제안만 하고 안 부른 것은 안 남는다.
  const 걸음키 = (rec) => `${rec?.actualCall?.tool ?? ''}|${rec?.actualCall?.args?.action ?? rec?.actualCall?.args?.op ?? ''}`;
  const 된걸음 = new Set((receipts ?? [])
    .filter((r) => (r?.failureState ?? 'none') === 'none' && r?.actualCall?.tool)
    .map(걸음키));
  // 취소는 막힘이 아니다 — **사용자가 그만두라고 한 것**이고 모델의 거짓이 아니다.
  const 못한걸음 = [...new Set((receipts ?? [])
    .filter((r) => r?.failureState && r.failureState !== 'none' && r.failureState !== 'cancelled'
      && r?.actualCall?.tool && !된걸음.has(걸음키(r)))
    .map(걸음키))];

  // ── **막힌 걸음을 했다고 말한다** — 완료형인지 먼저 묻지 않는다 ──────────
  //
  // 라이브(2026-08-05, 사진으로 확인): 클릭이 안 들어갔는데(화면은 `778` 그대로)
  // 답은 *"숫자 3 버튼까지 눌러 둔 상태예요"* 였다. **완료 주장인데 과거형이 아니라**
  // (`둔`·`상태예요` 에는 ㅆ 받침이 없다) 아래 완료형 판정이 그냥 지나갔다.
  //
  // 그래서 이 그물만은 **문구가 아니라 원장으로 연다** — 이 턴에 못 한 걸음이 있는데
  // 답이 그걸 **밝히지 않으면** 사실을 돌려준다. 문구 목록을 늘리는 대신 재는 자리를 옮긴 것이다.
  // (아래 자리로 옮긴 이유: 개수·자리 대조는 완료 주장일 때만 뜻이 있지만, **못 한 걸음은
  //  주장 형태와 무관하게 사실**이다.)
  if (못한걸음.length && !미완료를밝혔나(reply)) {
    return {
      일치: false,
      사용자에게: false,
      실제,
      모델에게: `이 턴에 막힌 걸음이 있고 끝내 되지 않았다: ${못한걸음.join(' · ')}. 답은 그 사실을 말하지 않는다.`,
    };
  }

  if (!완료주장인가(reply)) return 지나감;

  if (확인된실행 === 0) {
    return {
      일치: false,
      사용자에게: false,
      실제,
      // **사실만 준다.** "다시 써라"가 아니라 "원장에 이런 게 있다"이다 — 무엇을 말할지는 모델이 정한다.
      모델에게: '이 턴의 원장에 실제로 바뀐 것이 하나도 없다. 답은 끝냈다고 말하고 있다.',
    };
  }

  const 말한것 = 말한개수(reply);
  // 숫자를 안 말했으면 대조할 것이 없다. 말했으면 **자릿수가 다를 때만** 어긋남으로 본다 —
  // 하나 차이를 잡으려 들면 "대략 100개"처럼 정직한 어림을 거짓으로 만든다.
  if (말한것 !== null && (말한것 > 실제 * 2 || 실제 > 말한것 * 2)) {
    return {
      일치: false,
      사용자에게: false,
      실제,
      모델에게: `답은 ${말한것}개라고 말하는데 이 턴의 원장에 실제로 바뀐 것은 ${실제}개다.`,
    };
  }

  // ── (아래 설명 · 계산은 위로 올렸다) ───────────────────────────────────
  //
  // 라이브 실측(2026-08-05): `계산기 앞으로 가져오고 숫자 7 눌러줘` 에 원장은
  // `click 7 → blocked`("이름이 여러 개라 어느 것을 누를지 알 수 없어요") 이고 **다시 시도되지
  // 않았는데**, 최종 답은 *"거기서 숫자 7 버튼까지 눌렀어요"* 였다. **안 눌렀다.**
  //
  // 앞의 셋은 전부 지나갔다 — `focus`·`observe` 가 성공해서 "실행 0"이 아니었고,
  // "숫자 7"은 개수가 아니라 수 대조도 안 걸렸고, 가리킨 자리도 없었다.
  //
  // ── **답이 가리킨 자리가 원장 어디에도 없다** ────────────────────────────
  //
  // 라이브 실측(2026-08-04, 재봉인 관통 A팔 둘째 턴): 모델이 목록만 한 번 부르고
  // "설치·압축 파일을 `Downloads/_정리됨/설치_및_압축/` 으로 옮겼어"라고 답했다.
  // **그 폴더는 만들어진 적이 없다.** 앞의 두 그물은 둘 다 지나갔다 —
  // 목록도 확인된 실행이라 "실행 0"이 아니었고, 개수를 안 말해서 수 대조도 안 걸렸다.
  //
  // 사용자에게 이건 가장 나쁜 거짓이다. 그 자리로 찾으러 간다.
  //
  // 문구 규칙을 늘리는 게 아니다. 재는 것은 **원장에 있는 이름인가** 하나다 —
  // 이 턴에 실제로 다룬 자리도, 앞 턴에 다룬 자리도 원장에 이름이 남아 있다.
  const 없는자리 = 가리킨자리들(reply).filter((이름) => !원장글.includes(이름));
  if (없는자리.length) {
    return {
      일치: false,
      사용자에게: false,
      실제,
      모델에게: `답이 가리킨 자리가 원장에 없다: ${없는자리.join(' · ')}. 이 턴과 앞 턴의 원장에는 그 이름으로 다룬 것이 없다.`,
    };
  }
  return 지나감;
}
