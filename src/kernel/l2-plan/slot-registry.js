// L2 · **계약 슬롯 등록소 (S8)** — 커널이 슬롯을 정의하고, 기능이 드라이버로 등록된다.
//
// 왜 있나(전환 계획 §8 · 오너 착수 지시 ①③): 같은 종류의 손이 **여럿일 때 고르는 구조**가
// 없으면, 새 능력이 붙을 때마다 코어 파일의 배열을 고쳐야 한다. 그게 §4 발자국 사다리의
// **6칸(코어 도구)** 이고 불변식 B(코어 하나가 매 API 콜 비용)와 정면으로 부딪힌다.
//
// 밟은 사실: `web-search.js` 는 `deps.providers ?? [셋]` 으로 인자 자리가 열려 있었는데
// **호출부가 아무도 안 넘겼다.** 인자만 있고 등록할 자리가 없으면 그건 슬롯이 아니라 **이음매**다 —
// 결국 새 검색기는 그 파일의 배열에 손으로 적어야 했다.
//
// ── 이 파일이 하는 일과 안 하는 일 ────────────────────────────────────────
//
// **한다**   슬롯을 세운다 · 계약을 검사한다 · 드라이버를 붙인 순서로 돌려준다
// **안 한다** 어느 드라이버가 좋은지 고른다 · 실행한다 · 결과를 판정한다
//
// 고르는 것은 그 슬롯의 소비자(예: `makeWebSearch` 의 층 순서)이고, 여기는 **누가 있는가**만 안다.
// 커널이 "무엇이 답이냐"를 정하기 시작하면 걷어낸 병이 돌아온다(절대원칙 8 · §1.2).
//
// ── 계약 미달을 조용히 넘기지 않는다 ──────────────────────────────────────
// 안 받았는데 받은 척하면 **"붙였는데 안 돈다"** 가 되고, 그건 거짓 성공의 한 종류다.
// 배선 시점에 크게 실패한다 — 배선은 사용자 턴이 아니라 기동 때 도는 자리라 여기서 터지는 것이
// 가장 싸다.

/**
 * 등록소 하나를 만든다. **전역 하나를 강제하지 않는다** — 검사는 자기 등록소를 세워 쓰고,
 * 그래야 한 검사가 다른 검사의 등록을 오염시키지 않는다(전역 상태는 순서 의존을 만든다).
 */
export function makeSlotRegistry() {
  /** @type {Map<string, {id:string, 계약:string[], 설명:string, 드라이버:object[]}>} */
  const 슬롯들 = new Map();

  return {
    /**
     * 슬롯을 세운다. `계약` 은 **드라이버가 반드시 밝혀야 하는 칸**이다.
     * @param {{id:string, 계약?:string[], 설명?:string}} p
     */
    슬롯세우기({ id, 계약 = [], 설명 = '' }) {
      const key = String(id ?? '').trim();
      if (!key) throw new TypeError('슬롯세우기: id 필수');
      // 다시 세워도 **있던 드라이버를 안 버린다.** 배선 순서에 따라 두 번 불릴 수 있는데,
      // 거기서 조용히 비면 "붙였는데 없다"가 된다.
      if (!슬롯들.has(key)) 슬롯들.set(key, { id: key, 계약: [...계약], 설명, 드라이버: [] });
      return this;
    },

    /**
     * 드라이버를 붙인다. **계약을 못 채우면 거절한다**(조용히 안 받지 않는다).
     * @param {string} slotId
     * @param {object} driver
     */
    붙이기(slotId, driver) {
      const 슬롯 = 슬롯들.get(String(slotId ?? ''));
      if (!슬롯) throw new TypeError(`붙이기: 그런 슬롯이 없다(${slotId}) — 슬롯을 먼저 세운다`);
      if (!driver || typeof driver !== 'object') throw new TypeError('붙이기: 드라이버는 객체다');
      const 빠진것 = 슬롯.계약.filter((칸) => driver[칸] === undefined || driver[칸] === null);
      if (빠진것.length) {
        throw new TypeError(`붙이기: 슬롯 ${슬롯.id} 의 계약을 못 채웠다 — 빠진 칸: ${빠진것.join(', ')}`);
      }
      // 같은 id 를 두 번 붙이면 **뒤엣것으로 갈아끼운다.** 늘어놓으면 같은 드라이버가 두 번 돈다.
      const 자리 = 슬롯.드라이버.findIndex((d) => d.id === driver.id);
      if (자리 >= 0) 슬롯.드라이버[자리] = driver;
      else 슬롯.드라이버.push(driver);
      return this;
    },

    /** 붙인 순서 그대로 돌려준다 — **여기서 고르지 않는다.** 고르는 것은 소비자의 일이다. */
    드라이버(slotId) {
      return [...(슬롯들.get(String(slotId ?? ''))?.드라이버 ?? [])];
    },

    /** 어떤 슬롯이 서 있는가(진단·검사용). */
    슬롯목록() {
      return [...슬롯들.keys()];
    },

    /** 그 슬롯의 계약(무엇을 밝혀야 붙을 수 있는가). */
    계약(slotId) {
      return [...(슬롯들.get(String(slotId ?? ''))?.계약 ?? [])];
    },
  };
}
