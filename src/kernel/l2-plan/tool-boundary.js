// L2 · **도구 실행 경계** (S6-a) — 판정이 사는 한 자리.
//
// 원리 ④(OpenClaw): 정책은 **실행 경계의 훅**에 있다. 프롬프트의 안전 문구는 권고이지 강제가 아니다.
//   `prepare → before_tool_call(거부 가능) → execute → normalize → after_tool_call → persist`
//
// ── 왜 이 파일이 생겼나 ────────────────────────────────────────────────────
// `turn.js` 는 같은 판정을 **두 벌** 돌린다: 계획 경로(`runTurn`)와 걸음 경로(`executePlan` 루프).
// 주석이 그 대가를 이미 기록하고 있다 —
//   *"`reversible:false` 로 선언된 `rm -rf` 가 **걸음 경로에서만** 자동으로 실행됐다.
//     같은 명령이 계획 경로에서는 승인을 받았다 — **한 턴 안에서 같은 행동에 두 개의 답이 나왔다**"*
//   *"여기만 빠져 있어서, 모델이 도구 호출로 전송을 고르면 **빈 대상 카드**가 떴다"*
// 그리고 재현으로 확정된 것 하나 더(F-20): **헌장 ③ 이 어느 경로로 왔느냐에 따라 갈린다.**
//
// **S6 의 성공 기준은 "경계로 옮겼다"가 아니라 "두 벌이 한 벌이 됐다"이다.**
//
// ── 이 파일의 지금 범위 (S6-a) ────────────────────────────────────────────
// **행동을 하나도 바꾸지 않는다.** 걸음 경로에 인라인으로 있던 판정을 **글자 그대로** 옮겼다.
// 회귀·돌연변이가 그대로여야 이 단계가 닫힌다. 계획 경로를 같은 자리로 넣는 것은 S6-b 다.
//
// ── 여기 오면 안 되는 것 ──────────────────────────────────────────────────
// 턴 전체를 다루는 것은 루프에 남는다 — 예산·취소·승인 반환·되묻기 반환·줄세우기.
// **훅은 판정을 돌려주고, 턴을 끝내는 것은 루프의 일이다.**
import { toolActionKind } from './action-plan.js';
import { 발화밖파괴 } from './carryover.js';
import { isKnownCounterpart } from './known-counterpart.js';

/**
 * **실행 전 판정** — 이 호출이 무슨 등급이고, 자동인가 승인인가를 정할 사실을 만든다.
 *
 * 부작용이 없다(probe 는 도구가 스스로 "돌려 보면 아는 것"을 묻는 읽기다).
 * 판정만 하고 **아무것도 실행하지 않으며 턴을 끝내지도 않는다.**
 *
 * @param {object} p
 * @param {string} p.toolId
 * @param {object} p.args              모델이 낸 인자
 * @param {object} p.selfState
 * @param {object} [p.tools]           `ctx.tools` — probe 를 가진 도구 등록부
 * @param {boolean} [p.이번이월]        앞 턴에서 넘어온 같은 일인가
 * @param {object} [p.이번발화]         `parseFileRequest` 결과 — 발화밖 파괴 판정용
 * @param {boolean} [p.fresh]           승인 뒤처럼 현실을 반드시 다시 재야 하는 실행 경계
 * @returns {Promise<{판정인자: object, kind: string, 판정행동: {kind: string, revocable?: boolean, needsApproval?: boolean}}>}
 */
export async function 실행전판정({ toolId, args, selfState, tools, 이번이월 = false, 이번발화, fresh = false }) {
  // ── **못 재면 조인다**(fail-closed · 이음매 ① · 2026-08-12) ────────────────
  //
  // 탐침은 화면·샌드박스 같은 바깥 현실을 만진다 — 터지는 것이 정상 범위다. 그런데 이 자리는
  // `await …probe(…)` 를 맨몸으로 불렀다. 계획 경로까지 여기로 들어오면(아래 turn.js 수리)
  // 탐침 하나가 터질 때 **턴 전체가 죽는다** — 그건 조이는 것도 여는 것도 아니고 그냥 사라지는 것이다.
  //
  // 못 잰 것은 **안 실린다.** 그러면 `action-plan` 의 자동 조건(`눌러본사실.찾음===true`)이
  // 애초에 안 서서 미상·field_input 으로 떨어지고, 미상은 언제나 카드다.
  // 오픈클로 `docs/tools/exec.md:98-100`: *"Explicit `host=sandbox` still fails closed instead of
  // silently running on the gateway host."* — 재는 길이 막히면 조용히 진행하지 않는다.
  const 재본다 = async (fn) => { try { return await fn(); } catch { return null; } };
  // 등급 판정. 명령은 **돌려 봐야 아니까** 계획 때와 똑같이 probe 를 먼저 탄다.
  let 판정인자 = args;
  // **같은 사실을 두 번 묻지 않는다**(이음매 ①). 앞 레인이 이미 재서 실어 보낸 인자가 오면
  // 그대로 쓴다 — 재는 것은 왕복이고 왕복은 사용자 비용이다(0번 비용: 에너지·시간).
  // 두 번 재면 느린 것보다 **답이 갈리는 것**이 문제다: 화면은 그 사이에 바뀐다(두 진실 금지).
  const 이미잰것 = !fresh && (toolId === 'local.terminal'
    ? args?.probeResult !== undefined || args?.changes !== undefined
    : args?.눌러본사실 !== undefined);
  if (!이미잰것 && toolId === 'local.terminal' && typeof args?.command === 'string') {
    const probed = await 재본다(() => tools?.tools?.[toolId]?.probe?.(args.command, { cwd: args.cwd }));
    판정인자 = {
      ...args,
      // **probe 가 알아낸 자리를 그대로 받는다.** 빈 칸은 없는 칸이라 손이 기본 자리로 푸는데
      // (`local-terminal.js:57` — `blank(opts.cwd) ?? cwdOf()`), 그 사실을 여기서 버리면
      // 원장에는 빈 자리가 남는다. 실행 자리는 handler 가 같은 식으로 다시 풀어 안 갈리지만,
      // **기록이 갈린다** — 감사도 사용자도 그 명령이 어디서 돌았는지 못 본다.
      // 계획 경로는 처음부터 이걸 받고 있었다(`turn.js` 의 terminalOp). 두 벌이라 한쪽만 챙긴 자리다.
      ...(probed?.cwd ? { cwd: probed.cwd } : {}),
      changes: probed?.changes,
      granted: probed?.changes === true,
      probeResult: probed?.probe,
      ...(probed?.writeEffect ? { writeEffect: probed.writeEffect } : {}),
    };
  }
  // **화면 누르기도 돌려 봐야 안다**(CU E). 터미널과 같은 자리, 같은 이유다 —
  // 위험한 버튼 이름을 세는 대신 **화면에 그 자리가 무엇인지 다시 물어본다.**
  // 여기서 안 태우면 `action-plan` 의 판정은 늘 "돌려 본 사실 없음"을 보고 미상으로 답한다.
  // 창 넷(`focus` 등)에는 probe 가 `{해당없음:true}` 로 답한다 — 볼 일이 없는데 안 읽는다.
  // press_key·hotkey 는 **창 신분만** 탐침한다(F-58 (가-2)) — 실질의 창을 모델 신고가 아니라
  // 기계 사실로 세우는 자리다. 요소 탐색은 없으니 등급 판정(값있음)은 그대로 미상이다.
  if (!이미잰것 && toolId === 'desktop.act' && (args?.action === 'click' || args?.action === 'type'
    || args?.action === 'press_key' || args?.action === 'hotkey')) {
    // fresh 재판정에는 과거 probe 사실을 인자에서 걷는다. 도구가 그 칸을 보고
    // 현재 화면 관찰을 생략하면 승인 전 현실이 다시 현재 사실인 척 살아난다.
    const 탐침인자 = fresh ? (({ 눌러본사실, ...나머지 }) => 나머지)(args ?? {}) : args;
    const 돌려본것 = await 재본다(() => tools?.tools?.[toolId]?.probe?.(탐침인자));
    // 돌려 본 사실을 **판정인자에 실어 보낸다** — 원장도 사용자도 왜 물었는지 볼 수 있어야 한다.
    if (돌려본것 && !돌려본것.해당없음) 판정인자 = { ...탐침인자, 눌러본사실: 돌려본것 };
  }
  const kind = toolActionKind({ toolId, args: 판정인자, selfState });
  // **판정은 계획 경로와 같은 사실 위에서 한다**(두 층이 같은 질문에 다른 답을 내면 결함이다).
  // 헌장은 종류만으로 답할 수 없다 — 되돌릴 수 있는지, 아는 상대인지가 자동을 연다.
  // 여기서 종류 하나만 넘기던 동안 `reversible:false` 로 선언된 `rm -rf` 가 걸음 경로에서만
  // 자동 실행됐다(실측 2026-08-03).
  const 손선언 = selfState?.connectedTools?.find((t) => t.id === toolId);
  // 이월이거나 이번 발화 밖 파괴면 손의 선언과 무관하게 승인으로 간다 —
  // 되돌릴 수 있어도 **지금 요청이 아니다.** 버리지 않고 사용자에게 보인다.
  const 발화밖 = 발화밖파괴({ kind, 대상: args?.path ?? args?.target }, 이번발화);
  return {
    판정인자,
    kind,
    판정행동: {
      kind,
      revocable: toolId === 'local.terminal' && 판정인자?.writeEffect?.reversible === true
        ? true : 손선언?.reversible,
      // ── **한 칸에 세 사실이 뭉쳐 있었다** (오너 지시 2026-08-12:
      //    *"불필요한 승인카드는 모두 없애야해"*) ────────────────────────────
      //
      // 예전엔 셋이 `||` 로 한 칸이었다: 손 **선언**(정적) · **이번이월** · **발화밖**.
      // 뒤의 둘은 「이번 요청이 아니다」라는 **이번 턴 사실**이고 언제나 카드여야 한다.
      // 앞의 하나는 손이 스스로 단 선언이고, 그것이 헌장을 덮으면 안 된다 —
      // 발신 손 셋이 `needsApproval: true` 를 달아서 헌장 ③ 이 조건으로 연 것
      // (`counterpartKnown` — 아는 상대)이 **영영 안 열렸다.** 같은 사람에게 백 번째
      // 보내도 매번 카드였다. 판정도 배선도 서 있었는데 이 한 칸이 덮고 있었다.
      //
      // 뭉쳐 두면 한쪽을 풀 때 나머지가 같이 풀린다 — 실제로 그랬다(회귀가 잡았다:
      // 선언을 헌장에 양보시키자 **이월된 파괴가 자동 실행**되는 방향으로 갔다).
      // 그래서 가른다. 등급을 올리는 소비자(`classifyTier:110`)는 예전 칸을 그대로 읽는다.
      needsApproval: 손선언?.needsApproval || 이번이월 || 발화밖,
      // 현재 요청 밖 행동은 승인으로 바꾸지 않는다. 실행에서 빼고 모델이 현재 요청으로
      // 재계획하게 하는 범위 경계다.
      outOfScope: Boolean(이번이월 || 발화밖),
    },
  };
}

/**
 * **승인 면제 — 같은 질문을 두 번 하지 않는다.** (S6-b)
 *
 * 면제는 둘인데 **각 경로가 서로 다른 하나만** 읽고 있었다:
 *   `isKnownCounterpart`(헌장 ③ · 아는 상대) → 계획 경로에서만(turn.js:1324)
 *   `허락한손`(이번 요청에서 허락한 손)      → 걸음 경로에서만(turn.js:2036)
 *
 * 재현(F-20 · 기계 사실): 아는 상대인데 전송이 **다음 왕복**으로 오면(걸음 경로)
 * **카드가 다시 떴다.** 헌장 ③ 이 어느 경로로 왔느냐에 따라 갈린 것이다.
 * 두 벌 판정의 실제 대가다 — **한 벌이면 안 생긴다.**
 *
 * ── 왜 `decideAutoGrant` **앞**에서 봐야 하나 ──────────────────────────────
 * 뒤에서 `needsApproval` 만 비우면 **호출이 조용히 증발한다**(밟아서 확인).
 * 걸음 경로는 승인 분기에 들어간 뒤 카드를 못 만들면 `멈춘이유` 를 세우고 **루프를 빠져나간다**
 * — 실행 목록으로 돌아가지 않는다. 면제는 **애초에 승인 분기로 안 들어가게** 하는 것이다.
 *
 * @param {object} p
 * @param {string} p.toolId
 * @param {object} [p.판정인자]        대상이 확정된 인자(전송이면 `target` 이 여기 있다)
 * @param {Set<string>} [p.허락한손]    이번 요청에서 이미 허락받은 손
 * @param {Set<string>} [p.knownCounterparts]
 * @param {boolean} [p.전송인가]
 * @returns {{면제: boolean, 이유?: '허락한손'|'아는상대'}}
 */
/**
 * **이 걸음의 신분** — 무엇을 · 어디에 하느냐. 사용자가 허락한 것이 무엇이었는지 못 박는 값이다.
 *
 * 왜 손 id 로는 부족한가(라이브 2026-08-05 · F-34): 사용자가 `7 누르기` 를 허락했는데
 * 손 단위로 열면 *"앞으로 화면 마음대로"* 가 된다. 반대로 인자 전체로 잠그면 **재시도가
 * 영영 막힌다** — A02 로 막힌 뒤 토큰을 더해 다시 부르면 인자가 달라지기 때문이다.
 *
 * 그래서 **무엇을(걸음) · 어디에(대상)** 둘로 만든다. 토큰이 붙어도 같은 걸음이고,
 * 대상이 바뀌면 다른 걸음이다 — `rm -rf ./임시` 를 허락해도 `rm -rf /전혀다른곳` 은 다시 묻는다.
 *
 * 대상 표현은 **이미 이 파일이 쓰던 것**(`path ?? target`)을 그대로 잇는다. 화면 손의
 * 대상은 라벨이고(그게 실행 값이다), 터미널은 명령 자체가 대상이다.
 */
export function 걸음신분({ toolId, 판정인자 }) {
  const 걸음 = String(판정인자?.action ?? 판정인자?.op ?? '');
  const 대상 = String(
    판정인자?.path ?? 판정인자?.target ?? 판정인자?.대상?.label ?? 판정인자?.command ?? '',
  ).trim();
  return `${toolId}|${걸음}|${대상}`;
}

export function 승인면제({
  toolId, 판정인자, 허락한손, 허락한걸음, knownCounterparts, 전송인가 = false,
  이번이월 = false, 발화밖 = false, 되돌릴수있나, 실질열쇠 = null,
}) {
  // ── **면제는 "같은 질문 반복"만 없앤다. 게이트를 뚫지 않는다.** ──────────────
  //
  // 판정 대조표(216칸)가 잡았다(2026-08-05): `이월=true · 허락=true` 칸이
  // **`자동(면제:허락한손)`** 으로 나왔다. 즉 **이월된 파괴가 자동 실행된다.**
  //
  // `허락한손` 의 뜻은 *"**이번 요청**에서 이 손을 허락했다"* 인데,
  // **이월은 정의상 이번 요청이 아니다.** 발화밖 파괴도 마찬가지다.
  // 둘은 절대 게이트 **"현재 요청 침해"** 의 자리이고, 면제가 덮을 대상이 아니다.
  //
  // (옛 코드는 여기서 멈췄다 — 승인 분기에 들어간 뒤 카드를 못 만들어 `break` 했다.
  //  그것도 옳지 않았지만 **뚫리지는 않았다.** S6-b 가 면제를 앞으로 옮기며
  //  뚫리게 만들었다 — 이사가 아니라 **개조**였다. 표가 아니었으면 못 봤다.)
  if (이번이월 || 발화밖) return { 면제: false };

  // ① 이 요청에서 이미 허락받은 **같은 손**이면 다시 묻지 않는다.
  //    손이 다르면 다른 결정이므로 그때는 묻는다 — 면제되는 것은 같은 손뿐이다.
  //
  // **다만 되돌릴 수 없는 것은 손 면제 대상이 아니다.**
  // 밟은 사실(2026-08-05): 사용자가 `rm -rf ./임시` 를 승인했더니 재개 루프에서 모델이 낸
  // **`rm -rf /전혀다른곳` 이 승인 없이 실행됐다.** 손 단위 면제가 그 손의 **다음 인자**까지
  // 덮었기 때문이다. 사용자가 승인한 것은 **그 명령**이지 "앞으로 터미널 마음대로"가 아니다.
  // 자동성 헌장 ②("되돌릴 수 없는 파괴는 묻는다")는 면제가 덮을 대상이 아니다.
  //
  // 되돌릴 수 있는 것에는 그대로 면제한다 — 파일 목록을 허락했으면 또 묻지 않는 게 옳다.
  // (`되돌릴수있나` 를 안 넘기면 보수적으로 면제하지 않는다 — 모르면 묻는다.)
  // **조기 반환하지 않는다.** 처음엔 여기서 `return { 면제: false }` 로 끊었는데,
  // 그러면 아래 ②(헌장 ③ · 아는 상대)까지 막혀 **F-20 이 되살아난다**(표가 잡았다).
  // 면제 둘은 서로를 막지 않는다 — 각자의 조건으로 각자 판단한다.
  if (허락한손?.has?.(toolId) && 되돌릴수있나 === true) return { 면제: true, 이유: '허락한손' };
  // ③ **사용자가 허락한 바로 그 걸음**이면 같은 질문이다 — 되돌림과 무관하다.
  //    ① 은 손 전체를 여는 것이라 되돌릴 수 있을 때만 준다(`rm -rf` 사고). 여기는 **그 걸음
  //    하나**뿐이고 대상이 신분에 들어 있어서, 인자가 바뀌면 애초에 안 걸린다.
  //
  //    이게 없으면 A02·A04 로 막힌 걸음을 **다시 시도할 길이 없다** — 라이브에서 사용자가
  //    `7 누르기` 를 허락하고도 T5 가 *"승인이 한 번 더 필요합니다"* 라며 떠넘겼다(F-34).
  if (허락한걸음?.has?.(걸음신분({ toolId, 판정인자 }))) return { 면제: true, 이유: '허락한걸음' };
  // ② 헌장 ③ — 사용자가 전에 **이 상대**에게 보내는 것을 직접 허락했으면 같은 질문의 반복이다.
  //    대상이 확정된 뒤에만 물을 수 있다(계획 단계에서는 어디로 보낼지 아직 모른다).
  if (전송인가) {
    const 대상 = String(판정인자?.target ?? '').trim();
    if (대상 && isKnownCounterpart(knownCounterparts, toolId, 대상)) return { 면제: true, 이유: '아는상대' };
  }
  // ②-b 헌장 ③ 의 화면 얼굴(F-58 (가-2) · 2026-08-09) — 화면 손의 상대는 target 이 아니라
  //    **실질**(도구 previewOf 가 낸 앱·창·내용, 카드가 보여 준 그것)이다. 사용자가 그 실질을
  //    직접 허락한 적이 있으면 같은 질문의 반복이다. 열쇠가 못 서면(신분 불성립 fail-closed)
  //    이 조항은 영영 안 닿는다 — 새 상대·새 내용·모호한 창은 그대로 카드다.
  //    이 조항이 없으면 경계는 "승인 필요", 분기 안의 계획은 기억을 보고 "자동" —
  //    두 진실이 어긋나 걸음이 흔적 없이 증발한다(리허설 원장 실측 · F-20 계열 세 번째).
  if (실질열쇠 && (knownCounterparts instanceof Set ? knownCounterparts : new Set(knownCounterparts ?? [])).has(실질열쇠)) {
    return { 면제: true, 이유: '아는상대' };
  }
  return { 면제: false };
}
