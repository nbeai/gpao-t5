// **주객 회복 슬라이스 플래그** — S1 실험 전용, 기본 꺼짐.
//
// 정본: `design/T5-MODEL-SOVEREIGNTY-DEVELOPMENT-PLAN-2026-08-04-ko.md` (오너 승인 2026-08-04)
// 실험 계약: `design/S1-EXPERIMENT-FREEZE-2026-08-04-ko.md` (실행 전 동결)
//
// ── 왜 플래그인가 ──────────────────────────────────────────────────────────
// "주객을 되돌리면 모델이 목적을 끝낸다"는 아직 **가설**이다(계획 R6: 시뮬레이션은 가설이다).
// 코드 전체를 뒤집기 전에 한 경로에서만 뒤집어 같은 문장·같은 규모·같은 모델로 A/B 를 잰다.
// 그래서 이 플래그는 **끄면 기준선과 글자 하나 다르지 않아야 한다** — preflight 가 시스템
// 프롬프트와 도구 스키마의 sha256 으로 그것을 매 실행 전에 확인한다.
//
// ── 이 플래그가 여는 셋 (동결 §1, 이 밖은 없다) ────────────────────────────
//   ① 현재 행동 재심사 호출 미실행       (`currentRequestCalls`)
//   ② FILE/CHAT 완료 형식 판정 호출 미실행 (`fileDeliverablesFor`)
//   ③ 실패·차단 호출도 tool exchange 로 반환
//
// ── 열지 않는 것 ───────────────────────────────────────────────────────────
// **완료 계약 강제는 이 플래그의 일이 아니다.** 기준선(`e2e73f3`)이 이미 `enum:['write']` 잠금과
// `산출물이어가기` 의 `requiredTool` 을 걷었다 — A·B 둘 다 강제가 없다(실측 2026-08-04).
//
// (2026-08-04 갱신) 걸음 상한 6 은 **걷혔다** — S3 에서 예산(왕복·외부효과·벽시계)과
// 가드레일(같은 지문 반복 실패 · 읽기 전용 동일 결과 무진전)이 서고, 그 사실이 모델 방에
// 실린 뒤에 걷었다. `turn-budget.js` 머리말이 그 순서와 근거를 든다.
//
// ── 읽는 자리 ──────────────────────────────────────────────────────────────
// 환경변수를 **매번** 읽는다. import 시점에 얼리면 같은 프로세스에서 A/B 를 번갈아 돌릴 수
// 없고, 회차 러너가 그것을 필요로 한다. (Hermes 의 YOLO 동결과 반대 방향인데, 이유가 다르다 —
// 저건 프롬프트 주입으로 안전을 끄는 것을 막는 자리이고, 이건 안전을 건드리지 않는 실험
// 스위치다. 헌장 넷·원장·보호 영역은 이 플래그와 무관하게 그대로 선다.)

/** 주객 회복 슬라이스가 켜져 있는가. */
export function 모델주도(env = process.env) {
  return env.T5_MODEL_SOVEREIGN === '1';
}

/**
 * 심문 호출을 해도 되는가. 끄면 모델의 왕복을 런타임 판정이 소비하지 않는다.
 * (①② — `currentRequestCalls` · `fileDeliverablesFor`)
 */
export function 심문허용(env = process.env) {
  return !모델주도(env);
}

/**
 * 실패·차단 호출도 모델 자신의 행동 이력(tool exchange)으로 돌려주는가.
 *
 * 켜면 성공만이 아니라 실패도 `assistant tool_call → tool result` 로 간다(계약 ②).
 * **인자는 모델이 실제로 쓴 사실 그대로 가고, 가림은 결과 내용에서 건다** — 확인되지 않은
 * 절대 경로가 사용자면으로 새지 않게 하는 기존 계약(`02375fe`)은 그 자리에서 유지된다.
 */
export function 실패도교환(env = process.env) {
  return 모델주도(env);
}
