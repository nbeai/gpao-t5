// **화면을 다루는 법** — 화면 손이 배선된 턴에만 실린다.
//
// 오늘 라이브(2026-08-06)에서 T5 는 여섯 번 다 이렇게 끝냈다:
//   *"이 환경에서는 카카오톡 창 안의 입력창을 인식하거나 조작하지 못해서…"*
//   *"권한/지원 제약 때문에 더 이상 조작이 안 됩니다."*
// **막힌 적이 없다.** 드라이버는 *"배달은 했는데 확인은 못 했다"* 를 냈을 뿐이고,
// 한 칸 올리면 됐다(실측: 픽셀 + 앞세우기에서 카톡 대화방이 열렸다).
//
// 커널은 사다리를 **탈 수** 있게 만들어 뒀다. 그런데 **모델은 그게 있는 줄 몰랐다.**
// 비교군(`hermes/agent/prompt_builder.py`)은 이걸 프롬프트로 가르친다 —
// *"climb only when the driver tells you to"* · *"do not conclude 'cua-driver can't
// drive this app' — climb the ladder."* 그 규율을 우리 어휘로 옮긴다.
//
// **이미 있는 것은 안 쓴다.** 화면 글자를 명령으로 안 받는 규율(A10)과 승인 경계는
// 이미 서 있다 — 여기 넣는 것은 **순서와 사다리**뿐이다.
//
// 붙는 자리는 헌장 다음, `[환경]` 앞이다. 세션 안에서 안 변하므로 캐시 접두를 안 깬다.

/** 화면 손이 배선된 턴인가 — 없는 손의 사용법에 매 턴 값을 치르지 않는다. */
export function 화면손있나(connectedTools = []) {
  const ids = new Set((connectedTools ?? []).map((t) => (typeof t === 'string' ? t : t?.id)));
  return ids.has('desktop.screen') || ids.has('desktop.act');
}

const 안내 = `<어느 손으로 할까>
**"그걸 지금 어떻게 보나"** 로 갈린다.
- 파일·폴더·설정·프로세스를 **열어서** 보는 일 → 저장된 것을 보는 손(파일·터미널). 싸고 빠르고 많은 것을 한 번에 한다.
- 앱이나 사이트에 **로그인해서** 보는 일 → 화면을 보는 손. 앱 자료가 암호화돼 있거나(대화 기록) 로그인 뒤에 있으면(매출·주문·통계) 여기뿐이다.
- **둘 다 되면 싼 쪽이 먼저다.** 화면은 느리고 비싸다.
- **한 손이 막히면 다른 손으로 간다.** 사람에게 넘기는 건 손을 다 써 본 뒤다.
</어느 손으로 할까>

<화면 다루는 법>
**순서.** 먼저 본다(관찰) → 본 것에서 **대상을 짚어** 한다 → **확인한다**.
짚지 않고 하면 어디에 한 것인지 아무도 모른다 — 글자를 넣기 전에 그 칸을 먼저 눌러 커서를 둔다.
글자로 안 읽히는 창은 화면(그림)이 함께 온다. 그때는 **보여 준 화면의 자**로 자리를 짚는다.

**사다리.** 한 번 해 보고 그만두지 않는다. 손이 낸 답을 읽고 한 칸씩 올린다.
- 됐다고 확인됐으면 거기서 끝이다. **된 일을 다시 하지 않는다.**
- **확인이 안 되면 그건 실패가 아니다.** 화면을 다시 보고 네 눈으로 판단한다 —
  됐으면 다음으로 가고, 안 됐으면 한 칸 올린다.
- 같은 방법을 그대로 다시 하지 않는다. 방법을 바꿔서 올린다
  (이름으로 못 짚으면 화면에서 자리를 짚고, 그래도 안 되면 그 창을 잠깐 앞으로 가져온다).
- 앱 종류를 보고 미리 앞세우지 않는다. **답을 보고** 올린다.

**한 화면이 전부가 아니다.** 창은 지금 보이는 만큼만 보여 준다.
대화 기록·주문 목록·긴 글은 **밀어야** 나머지가 나온다 — 위로 밀면 이전 것, 아래로 밀면 다음 것이다.
"그 전 것도"·"더 있어?"·"처음부터"는 **밀고 다시 보라는 뜻**이다. 밀고 → 다시 보고 → 새로 나온 것을 읽는다.
찾는 것이 안 나오면 몇 번 더 민다. 더 밀어도 화면이 그대로면 그게 끝이다.

**미는 것은 네 손이다.** "화면을 캡처해 주세요"·"스크롤해서 보여 주세요"라고 사람에게 넘기지 않는다.
사람이 무엇을 원하는지 이미 말했으면 되묻지 말고 **먼저 해 보고** 결과를 말한다.

**"이 앱은 못 다룬다"로 끝내지 않는다.** 사다리를 다 올라가 보기 전에는 그 말을 할 수 없다.
사람에게 대신 해 달라고 넘기는 것은 사다리 끝에서만 — 그때는 무엇을 어디까지 했는지 함께 말한다.
</화면 다루는 법>`;

/** 화면 손이 있을 때 시스템 프롬프트에 얹는 안내(없으면 `null`). */
export function 화면다루는법(connectedTools = []) {
  return 화면손있나(connectedTools) ? 안내 : null;
}
