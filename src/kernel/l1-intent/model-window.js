// L1 · **모델의 창을 알고 몫을 나눈다** (노드 W · 2026-08-08).
//
// 지금까지 이력 4,000자·결과 1,200자는 **창을 모른 채 박은 고정값**이었다. 실측:
//   · gpt-5.1 의 입력 여유는 272,000토큰인데 이력은 그 1% 남짓만 실렸다 — ⑪(스무 턴 뒤)이
//     0/3 인 직접 기제다(잡담 스무 턴이면 아침 발화가 상한 밖으로 밀려난다).
//   · 웹 본문 4,588자가 1,183자로 접혀 폭염경보 날 "31도" 가 나갔다(2026-08-05).
//   · ⑬ 라이브에서 locate 후보 목록이 "(가운데 621자 생략)" 으로 접혀 갔다(2026-08-08 덤프).
//
// 구조는 비교군에서 배웠고 **숫자는 안 가져왔다**(오너 규율 — 그쪽 숫자는 그쪽 모델의 값이다).
//   OpenClaw   공급자에게 묻고 → 설정으로 덮고 → 번들 표로 받친다 · 둘 다 있으면 **작은 쪽**
//   Hermes     models.dev 카탈로그를 통째로 캐시한다
// 우리는 셋째 겹(표)+둘째 겹(설정 덮기)만 세운다. 첫째 겹(공급자에게 묻기)은 **비워 둔다** —
// OpenAI·Anthropic 응답 어디에도 창 크기가 안 실려 온다(밟음). 밝혀 주는 공급자가 생기면
// 그 값이 표를 덮는 자리만 남겨 둔다. 지어내지 않는다.
//
// **모르는 모델은 null 이다.** null 이면 부르는 쪽이 옛 고정값(4,000·1,200)으로 간다 —
// 모르는 창에 큰 예산을 지어내면 요청이 통째로 터진다. 모름은 좁은 쪽이다.

/**
 * 지원 모델의 **입력 토큰 한도** 표. 값의 출처는 models.dev 공개 카탈로그
 * (Hermes 캐시에서 실측 대조 · 2026-08-07)다. 여기 없는 모델은 null — 표를 넓히는 것은
 * 값의 출처를 함께 적을 때만 한다.
 */
export const 창표 = {
  'gpt-5.1': { 입력토큰: 272_000 },
  'gpt-5.5': { 입력토큰: 922_000 },
  'claude-opus-5': { 입력토큰: 1_000_000 },
};

/** 한 턴이 손을 이어 쓸 수 있는 상한 — `turn.js` 의 MAX_TOOL_STEPS 와 같은 값이어야 한다.
 *  (그쪽에서 import 하면 커널 전체가 딸려 와 순환이 생긴다 — 검사가 두 값의 일치를 잰다.) */
export const 결과몫걸음 = 6;

/**
 * 창 예산 — 이력·발화·결과 상한이 전부 이 계산의 **파생값**이다.
 *
 * 비율의 근거(우리 실측이지 남의 숫자가 아니다):
 *   쓸자 = 입력토큰 × 0.5   토큰↔자 어림(한글 1자≈1토큰, 영어 4자≈1토큰)의 오차와
 *                           시스템 프롬프트·도구 스키마·커널 블록이 같은 창을 쓰는 몫을
 *                           절반으로 흡수한다 — "둘 다 있으면 작은 쪽"과 같은 정신(안전쪽 오차)
 *   이력자 = 쓸자 × 0.5     노드 W 의 명제: 사용자가 말한 것과 도구가 찾아온 것이 왕이다 — 반반
 *   발화자 = 이력자 × 0.3   옛 구조의 비율(1,200/4,000)을 유지 — 한 발화가 이력을 삼키지 않게
 *   결과자 = 나머지 절반 ÷ 걸음상한   한 턴의 결과 여섯이 전부 원문으로 실려도 창 안이게
 *
 * @returns {null | {입력토큰:number, 이력자:number, 발화자:number, 결과자:number}}
 */
export function 창예산({ modelId, 설정입력토큰 } = {}) {
  const 표값 = 창표[String(modelId ?? '').trim()]?.입력토큰 ?? null;
  const 덮음 = Number(설정입력토큰) > 0 ? Math.floor(Number(설정입력토큰)) : null;
  // 둘 다 있으면 **작은 쪽** — 안전 쪽으로 틀린다.
  const 입력토큰 = 표값 && 덮음 ? Math.min(표값, 덮음) : (덮음 ?? 표값);
  if (!입력토큰) return null;
  const 쓸자 = Math.floor(입력토큰 * 0.5);
  const 이력자 = Math.floor(쓸자 * 0.5);
  return {
    입력토큰,
    이력자,
    발화자: Math.floor(이력자 * 0.3),
    결과자: Math.floor((쓸자 - 이력자) / 결과몫걸음),
  };
}
