// L1 · 이름 지어주기 감지 (P-ID-1). "니 이름은 이제부터 아이기스야" 를 알아듣는다.
//
// 왜 추정이 아니라 지시인가: 사용자가 **명시적으로** 이름을 지정한 문장만 잡는다. 추정으로 이름을
// 바꾸면 "추정≠반영"(§6.18) 계약을 어기므로, 애매하면 잡지 않는다(놓치는 편이 낫다).
// 오너 실사용: 이름을 지어줬는데 다음 대화에서 다시 "저는 ChatGPT예요" 로 돌아갔다 — 안 남았다.

const PATTERNS = [
  // "네/니/너의 이름은 (이제부터) X야"
  /(?:네|니|너의|당신의)\s*이름(?:은|는)\s*(?:이제부터\s*|앞으로\s*)?([^\s.,!?]{1,20}?)(?:야|이야|다|이다|입니다|로|으로)?\s*[.!]?$/,
  // "이름을 X로 해/바꿔/정해"
  /이름을\s*([^\s.,!?]{1,20}?)(?:로|으로)\s*(?:해|하자|바꿔|정해|불러)/,
  // "(이제부터) X라고 불러"
  /(?:이제부터\s*|앞으로\s*)?([^\s.,!?]{1,20}?)(?:라고|이라고)\s*불러/,
];

// 이름으로 받으면 안 되는 말(질문·대명사) — 잘못 잡느니 안 잡는다.
const NOT_A_NAME = /^(뭐|뭐야|무엇|누구|어떻게|왜|그거|이거|저거|당신|너|나|없어|몰라)$/;

/**
 * @param {string} text
 * @returns {{name:string}|null}
 */
export function detectSelfNaming(text) {
  const t = String(text ?? '').trim();
  if (!t) return null;
  for (const re of PATTERNS) {
    const raw = t.match(re)?.[1]?.trim();
    if (!raw || NOT_A_NAME.test(raw)) continue;
    return { name: raw };
  }
  return null;
}
