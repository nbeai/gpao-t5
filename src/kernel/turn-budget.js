// **턴 예산과 가드레일** — 고정 상한 6을 걷기 위해 먼저 서는 것.
//
// 정본: `design/T5-MODEL-SOVEREIGNTY-DEVELOPMENT-PLAN-2026-08-04-ko.md` §S3
//   *"가드레일 먼저, 6상한 제거는 마지막. 예산이 서고 그 사실이 모델의 방에 공급된 뒤에만
//     고정 6을 걷는다. 순서를 바꾸면 무한 루프·비용 폭주가 열린다."*
// 오너 구속 계약(2026-08-04) 넷을 그대로 반영한다.
//
// ── 왜 옛 상한이 틀렸나 ────────────────────────────────────────────────────
// `MAX_TOOL_STEPS = 6` 은 **도구 실행 횟수**를 셌다. 그 시절엔 그게 곧 비용이었다 —
// 한 왕복에 한 호출만 실행됐으므로 실행 6 = 왕복 6 이었다. 다중 호출 병합·폐기를 걷어낸 뒤
// (2026-08-04) 등식이 깨졌다: 한 응답에 move 여섯을 내면 **왕복 하나에 실행 여섯**이다.
// 그런데 상한은 여전히 실행을 세므로 비용이 안 드는 쪽을 조이고 비용이 드는 쪽은 안 셌다.
//
// ── 세 축, 서로 다른 것을 잰다 ──────────────────────────────────────────────
//   **왕복**     비용 축. 이 작업에서 발생한 **모든 모델 호출** — 최초 계획·심문·이어쓰기·
//                산출물 재요청·최종 답까지 전부. 승인 재개에도 **누적**한다(리셋하면 무한이다).
//   **외부효과** 비용 모델이 **아니다.** 되돌릴 수 있는 것/없는 것 두 칸으로 나눈 **폭주 뒷단**이다.
//                되돌릴 수 있는 이동 200번은 사용자가 복구할 수 있지만, 되돌릴 수 없는 것은
//                한 번도 많다. 도구별 비용표(추측 목록)를 만들지 않고 **이미 있는 계약**
//                (`reversible`)에서 파생한다.
//   **벽시계**   사용자가 실제로 기다리는 시간. 도구마다 timeout 이 있어도 **큐 전체**의 길이는
//                아무도 안 잡는다 — 200번이 각각 3초면 10분이다. 그 자리를 여기서 잡는다.
//
// 그리고 **사용자 취소**는 예산과 무관하게 즉시 소진이다. 취소 신호가 큐 전체에 전파되지
// 않으면 "멈춰"라고 말한 뒤에도 손이 계속 움직인다.
//
// ── 가드레일은 멈추지 않는다 ────────────────────────────────────────────────
// Hermes `tool_guardrails` 의 **원리**만 흡수한다. 값과 축은 T5 의 것으로 정한다:
//   · **성공한 같은 도구 반복은 경고하지 않는다.** 437개를 옮기려면 같은 손을 수백 번 부르는 게
//     정상이다. 초안은 Hermes 의 `같은 도구 3/8` 을 그대로 가져왔는데, 그러면 정상 진행이
//     3번째부터 계속 경고를 내고 모델은 경고를 무시하는 법을 배운다(오너 지적).
//   · 재는 것은 둘뿐이다: **같은 지문으로 반복 실패** · **읽기 전용에서 같은 결과를 다시 받음**.
//     둘 다 "다시 해도 같다"는 기계 사실이고, 그것만이 되풀이다.
// 그리고 **경고 기본 켬 · 하드스톱 기본 끔**이다. 런타임이 대신 멈추면 그게 다시 주객 전도다 —
// 사실을 모델 방에 놓고 판단은 모델이 한다(계약 ① 모델이 작업 루프를 소유한다).

/**
 * 기본 예산 — **잠정값**이다. §S3 이 "값은 실측으로 정한다"고 했고 아직 이 값으로 도는
 * 실모델 회차가 없다. 환경으로 바꿀 수 있게 두고 회차 뒤에 다시 정한다.
 *
 *   왕복 12         S1 여섯 회차 실측 모델 호출 6~11회. 지금 흐름을 조이지 않는 최소값.
 *   되돌릴수있는것 200  파일 이동·정리처럼 휴지통·원본이 남는 작업. 사용자가 복구할 수 있다.
 *   그밖 3          되돌릴 수 없는 실행(승인을 받은 것들). 한 턴에 셋이면 이미 많다.
 *   벽시계 180초     사용자가 한 답을 기다리는 한계. 도구 timeout 의 합이 아니라 큐 전체다.
 */
const 기본예산 = Object.freeze({ 왕복: 12, 되돌릴수있는것: 200, 그밖: 3, 벽시계ms: 180_000 });

/** 되풀이 창 — Hermes 의 분모를 참조하되 축은 T5 의 것이다. */
const 창 = Object.freeze({ 반복실패: 5, 무진전: 5 });
const 기준 = Object.freeze({ 반복실패: 2, 무진전: 2 });

/**
 * 이번 턴의 예산. 환경으로 바꿀 수 있다 — 값을 코드에 못 박으면 실측으로 고칠 수 없다.
 * 말이 안 되는 값(0·음수·숫자 아님)은 조용히 받지 않고 기본값으로 되돌린다: 0 을 받으면
 * 손이 통째로 잠겨서, 설정 실수가 "T5 가 아무것도 못 한다"로 보인다.
 */
export function 턴예산(env = process.env) {
  const 읽기 = (키, 기본) => {
    const v = Number(env?.[키]);
    return Number.isInteger(v) && v > 0 ? v : 기본;
  };
  return {
    왕복: 읽기('GPAO_T5_TURN_ROUNDTRIPS', 기본예산.왕복),
    되돌릴수있는것: 읽기('GPAO_T5_TURN_REVERSIBLE', 기본예산.되돌릴수있는것),
    그밖: 읽기('GPAO_T5_TURN_IRREVERSIBLE', 기본예산.그밖),
    벽시계ms: 읽기('GPAO_T5_TURN_WALLCLOCK_MS', 기본예산.벽시계ms),
  };
}

/**
 * 더 갈 수 있는가. **어느 축이든 하나만 닿아도 멈춘다**, 그리고 사용자 취소는 즉시다.
 * 취소가 예산 뒤에 오면 "멈춰"라고 말한 뒤에도 남은 큐가 다 돈다.
 */
export function 예산소진(쓴것, 예산) {
  if (쓴것?.취소됨) return true;
  return (쓴것?.왕복쓴것 ?? 0) >= 예산.왕복
    || (쓴것?.되돌릴수있는것쓴것 ?? 0) >= 예산.되돌릴수있는것
    || (쓴것?.그밖쓴것 ?? 0) >= 예산.그밖
    || (쓴것?.지난ms ?? 0) >= 예산.벽시계ms;
}

/** 어느 축이 닿았는가 — 사용자와 모델에게 **왜 멈췄는지**를 사실로 주기 위해. */
export function 소진사유(쓴것, 예산) {
  if (쓴것?.취소됨) return '사용자가 멈춰 달라고 해서 남은 것은 하지 않았어요.';
  if ((쓴것?.왕복쓴것 ?? 0) >= 예산.왕복) return '한 번에 이어갈 수 있는 만큼 하고 멈췄어요.';
  if ((쓴것?.그밖쓴것 ?? 0) >= 예산.그밖) return '되돌리기 어려운 일은 한 번에 여기까지만 했어요.';
  if ((쓴것?.되돌릴수있는것쓴것 ?? 0) >= 예산.되돌릴수있는것) return '한 번에 다룰 수 있는 만큼 하고 나머지는 남겨 뒀어요.';
  if ((쓴것?.지난ms ?? 0) >= 예산.벽시계ms) return '오래 걸려서 여기까지 하고 멈췄어요.';
  return undefined;
}

/** 이 호출의 **호출지문** — 같은 손·같은 작업·의미상 같은 인자인가(S1 §5.1.1 과 같은 정의). */
function 지문(rec) {
  const a = rec?.actualCall?.args ?? {};
  const 값 = Object.entries(a)
    .map(([k, v]) => `${k}=${typeof v === 'string' ? v.trim() : JSON.stringify(v)}`)
    .sort().join('|');
  return `${rec?.actualCall?.tool}#${값}`;
}

/** 이 실행이 **실물을 바꾸지 않는 것**인가 — 읽기 전용 무진전 판정에만 쓴다. */
const 읽기전용 = (rec) => ['read', 'list', 'versions'].includes(rec?.actualCall?.args?.action);

/** 결과가 **같은가** — 같은 것을 다시 받았으면 진전이 아니다. */
const 결과지문 = (rec) => {
  try { return JSON.stringify(rec?.result ?? null); } catch { return '(비교불가)'; }
};

/**
 * 최근 실행에서 읽히는 **되풀이 신호**. 사실만 낸다 — 지시하지 않고 멈추지도 않는다.
 *
 * 재는 것은 둘뿐이다(오너 구속 계약 2026-08-04):
 *   ① **같은 지문 반복 실패** — 같은 손을 같은 인자로 다시 불러 또 막혔다. 인자가 다르면
 *      전략 전환이지 되풀이가 아니다.
 *   ② **읽기 전용 동일 결과 무진전** — 같은 목록·같은 본문을 다시 받았다. 사고 당시
 *      `list → list → list` 가 정확히 이것이다. 쓰기는 매번 실물이 바뀌므로 해당 없다.
 *
 * 창 밖으로 밀려난 것은 세지 않는다 — 옛일이 영원히 경고로 남으면 모델은 그 경고를 무시한다.
 *
 * @param {Array} receipts 이번 턴 영수증(오래된 것 → 최근 것)
 * @returns {Array<{종류:string, tool?:string, 횟수:number, 사람말:string}>}
 */
export function 가드레일신호(receipts = []) {
  const 부른것 = receipts.filter((r) => r?.actualCall?.tool);
  const 신호 = [];

  // ① 같은 지문 반복 실패
  const 실패창 = 부른것.slice(-창.반복실패).filter((r) => (r?.failureState ?? 'none') !== 'none');
  const 실패수 = new Map();
  for (const r of 실패창) {
    const k = 지문(r);
    실패수.set(k, { 횟수: (실패수.get(k)?.횟수 ?? 0) + 1, tool: r.actualCall.tool });
  }
  for (const [, v] of 실패수) {
    if (v.횟수 >= 기준.반복실패) {
      신호.push({
        종류: '반복실패', tool: v.tool, 횟수: v.횟수,
        사람말: `${v.tool} 을(를) 같은 인자로 최근 ${창.반복실패}번 중 ${v.횟수}번 불렀고 같은 자리에서 막혔다.`,
      });
    }
  }

  // ② 읽기 전용 동일 결과 무진전
  const 읽기창 = 부른것.slice(-창.무진전).filter((r) => 읽기전용(r) && (r?.failureState ?? 'none') === 'none');
  const 결과수 = new Map();
  for (const r of 읽기창) {
    const k = `${지문(r)}::${결과지문(r)}`;
    결과수.set(k, { 횟수: (결과수.get(k)?.횟수 ?? 0) + 1, tool: r.actualCall.tool });
  }
  for (const [, v] of 결과수) {
    if (v.횟수 >= 기준.무진전) {
      신호.push({
        종류: '무진전', tool: v.tool, 횟수: v.횟수,
        사람말: `${v.tool} 에서 같은 것을 ${v.횟수}번 받았다 — 지난번과 같은 결과다.`,
      });
    }
  }

  return 신호;
}
