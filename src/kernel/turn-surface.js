// L2 · 턴이 **사용자 화면으로 내보내는 것의 경계** (HRT-ST-002 첫 추출)
//
// 왜 파일이 따로 있나: 이 다섯은 turn.js 안에 흩어져 있었지만 하는 일이 하나다 —
// **커널이 만든 것 중 무엇이, 어떤 모양으로, 언제 사용자 눈에 닿는가.** 모델 호출을
// 하나도 하지 않는다.
//
// 이음매는 두 가지를 나눠 봐야 한다.
//   · **함수 입력**(호출자가 그때그때 건네는 것): `value` / `ctx, rec, ledger` / `reply, pv`
//   · **모듈 의존**(파일이 바깥에서 끌어오는 것): `확인된사실` 하나 — 그게 전부다
// turn.js 의 모듈 범위에서 끌어 쓰던 이름은 없었다. 그래서 옮기는 데 새 배선이 필요 없었다.
//
// 그런데 같은 파일에 있는 바람에 화면과 무관한 정리가 이 경계를 함께 흔들 수 있었다.
// 실제로 P90-2 에서 통제 접두어가 스트리밍 조각으로 샌 것도, 차단 장치가 **최종 답에만**
// 붙어 있고 조각이 그 경계를 안 지났기 때문이다.
//
// 이 추출은 **행동 보존**이다. 호출 위치와 await 순서를 그대로 두고 자리만 옮겼다.
// `response-surface.js` 와 합치지 않는다 — 그쪽은 답이 **어디로** 나가는가(채널의 성질)이고,
// 여기는 **무엇이 언제** 나가는가다.
import { 확인된사실 } from './l0-evidence/ledger.js';

// **채널 이름도 목록으로 적지 않는다.** 여기 손으로 적어 두면 채널이 하나 늘 때마다
// 그 하나가 사용자 화면으로 샌다 — 실제로 `work.state` 가 빠져 있었다(실측 2026-08-04).
// 채널을 정의한 **한 자리**에서 파생한다(§2-C).
import { MODEL_CONTROL_SCHEMAS } from './l2-plan/model-control.js';

const 통제이름 = `(?:${MODEL_CONTROL_SCHEMAS.map((s) => s.name.replace('.', '\\.')).join('|')})`;
const INTERNAL_CONTROL_PREFIX = new RegExp(`^\\s*${통제이름}\\s*:\\s*`, 'i');
// **답 끝에 붙어도 지운다.** 앞에만 보던 시절, 팀원 실사용에서 답 마지막 줄에
// `memory.cite: "현재 목표: …"` 가 그대로 나갔다(실측 2026-08-03). 통제 표식이 어디에
// 붙든 그건 OS 와 모델 사이의 말이지 사람에게 하는 말이 아니다. 줄 단위로 걷어낸다.
// **장식을 목록으로 열거하지 않는다.** 첫 판은 `^[ \t>*-]*` 로 공백·인용·별표·하이픈만
// 허용했는데, 모델이 백틱으로 감싸자(` \`memory.cite\`: `) 그대로 통과했다
// (실측 2026-08-04 말귀 재측정 5번 — 같은 자리가 **두 번째** 뚫렸다).
// 목록은 늘 뚫린다(절대원칙 8). 그래서 **글자가 아닌 것 전부**를 넘긴다 —
// 마크다운 장식은 늘어나도 "글자가 아니다"는 안 늘어난다.
const INTERNAL_CONTROL_LINE = new RegExp(`^[^\\p{L}\\p{N}]*${통제이름}[^\\p{L}\\p{N}]*:.*$`, 'gimu');

export function userFacingModelText(value) {
  return String(value ?? '')
    .replace(INTERNAL_CONTROL_PREFIX, '')
    .replace(INTERNAL_CONTROL_LINE, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/**
 * **기다림을 사실로 채운다** (P90-2).
 *
 * 실측(2026-08-03, 로컬 파일 경로 6회): 도구 턴 20초 동안 사용자가 보는 것은
 * `○○ 실행 중이에요` 하나뿐이고 첫 내용은 마지막 왕복에서야 뜬다(중앙 17.5초).
 * 그런데 걸음마다 영수증이 **이미 사용자 언어 문장을 들고** 도착한다 —
 * "3곳이 후보예요", "정산_3월_수정.csv 을(를) 읽었어요". 그걸 안 보여주고 있었을 뿐이다.
 *
 * 경계:
 *   · **원장이 "확인한 것"으로 세는 것만.** 판정을 여기서 새로 만들지 않고 `확인된사실()` 을
 *     쓴다. 실패가 아니어도 결과가 안 온 걸음(lifecycle `attempting`)은 확인이 아니다 —
 *     손이 아무것도 반환하지 않으면 userSafeSummary 가 기본 문구로 채워져 성공처럼 보인다.
 *     흐르는 사실과 최종 답의 확인 목록이 갈라지면 사용자는 한 턴에서 두 진실을 본다.
 *   · **실행 뒤에만.** 영수증은 결과이지 예고가 아니다(계획서 §4-5 실행 전 성공 예고 금지).
 *   · **실행 신분과 함께.** 그래야 "확인 중" 문구와 구분된다(계획서 §4 측정 기준). 신분은
 *     이 턴 원장에서의 자리(`step`)다 — 커널 영수증에는 `receiptRef` 가 없다(그건 표면이
 *     발급한다). 없는 필드를 신분이라 적으면 화면도 문서도 거짓이 된다.
 *   · 모델 내용을 싣지 않는다 — 이것은 OS 가 만든 문장이다. 참고 원천 두 곳도 같은 규율이다
 *     (OpenClaw `AgentToolProgress{privacy:'public'}` "never model content",
 *      Hermes `ToolCallFinished` "No tool output travels here").
 *   · 중복은 **문장이 아니라 실행**으로 센다. 같은 손이 두 파일을 처리해 요약이 같아도
 *     실행은 둘이다 — 문장으로 지우면 두 번째 실행 사실이 화면에서 사라진다.
 */
export async function 확인된중간결과(ctx, rec, ledger) {
  if (!ctx?.emit) return;
  if (!확인된사실(rec)) return;
  if (rec.surfaceRequest) return;   // 공이 사용자에게 넘어간 것은 이번 걸음의 결과가 아니다
  const text = String(rec.userSafeSummary ?? '').trim();
  if (!text) return;
  // 이 턴 원장에서의 자리 = 실행 신분. **선택 인자가 아니다** — 원장 없이 부르면 여기서
  // 터진다. 가드로 "신분 없으면 안 흘린다"를 적으면 그 가드는 도달 불가라 검증도 안 된다.
  const step = ledger.entries.length;
  const 보낸것 = ctx.보낸중간결과 ?? (ctx.보낸중간결과 = new Set());
  if (보낸것.has(step)) return;
  보낸것.add(step);
  await ctx.emit('partial_result', {
    text,
    step,
    ...(rec.actualCall?.tool ? { tool: rec.actualCall.tool } : {}),
  });
}

/**
 * **화면에 이미 나간 조각과 지속되는 최종 답은 같은 사실이어야 한다**(H 진단 계열 ④).
 *
 * 도구 턴이 스트리밍되면 한 턴 안의 여러 모델 호출이 조각을 흘릴 수 있다 — 모델이 도구를
 * 고르며 이미 한 말("잠깐 볼게요")도 사용자 화면에 나갔다. 나간 말은 물릴 수 없으므로 버리지
 * 않는다(승인 카드의 `지금까지` 와 같은 원리). 이 원장이 그 누적을 들고 있다가, 최종 답이
 * 정해지는 자리에서 `미리보기정렬` 로 둘을 하나의 사실로 만든다.
 */
export function 미리보기원장(ctx) {
  if (!ctx.onAnswerDelta || ctx.미리보기) return;
  const raw = ctx.onAnswerDelta;
  const pv = {
    shown: '',
    // P90-2 실측(2026-08-02 라이브, 24개 답 중 3개): 모델이 통제 접두어를 **조각으로** 흘리면
    // `memory.cite: [현재 합의] …` 가 그대로 화면에 나갔다. 최종 답에는 `userFacingModelText`
    // 가 붙어 있었지만, 정제된 답은 오염된 누적으로 시작하지 않으므로 정렬이 둘을 이어 붙이거나
    // 조각 쪽을 그대로 돌려줬다. **화면은 물릴 수 없으니 나가기 전에 지나야 한다.**
    //
    // 접두어는 답의 맨 앞에서만 뜻을 갖는다(정규식이 `^` 앵커다). 그래서 **아직 아무것도 안
    // 나간 동안에만** 같은 경계를 적용한다 — 본문 중간에 우연히 같은 글자가 오면 건드리지
    // 않는다. 새 문구 규칙을 만들지 않고 기존 `INTERNAL_CONTROL_PREFIX` 하나를 공유한다.
    emit(piece) {
      let p = String(piece ?? '');
      if (!p) return;
      if (!pv.shown) {
        p = p.replace(INTERNAL_CONTROL_PREFIX, '');
        if (!p.trim()) return; // 접두어만 온 조각은 화면에 아무것도 아니다
      }
      pv.shown += p;
      try { raw(p); } catch { /* 화면 갱신 실패가 응답을 깨지 않는다 */ }
    },
    /**
     * **나간 말을 되물린다.** 런타임이 답을 *대체*하기로 정했을 때만 부른다(출구 검증 되돌림).
     *
     * 아래 `미리보기정렬` 의 마지막 갈래는 *"화면을 물릴 수 없으므로 답이 화면을 따라온다"*
     * 였다. 그 전제는 되돌릴 방법이 없던 시절의 것이다. 라이브 실측(2026-08-04 사람 사용시험):
     * 앞 문단 "터미널로 가져올게요", 뒤 문단 "직접 실행할 수는 없어요" 가 **한 답으로 저장돼**
     * 사용자에게 자기모순인 답이 갔다(F-8).
     *
     * 이제 표면에 `answer_reset` 이 있으니 물릴 수 있다. **되돌림은 이어감이 아니라 대체다.**
     * 되물리지 않는 다른 이어감(중간에 흐른 말 + 최종 답)은 그대로 둔다 — 그건 잃으면 안 되는 말이다.
     */
    retract() {
      if (!pv.shown) return;
      pv.shown = '';
      try { ctx.onAnswerReset?.(); } catch { /* 화면 갱신 실패가 응답을 깨지 않는다 */ }
    },
  };
  ctx.onAnswerDelta = (piece) => pv.emit(piece);
  ctx.미리보기 = pv;
}

/**
 * 최종 답과 미리보기 누적을 정렬한다. 네 경우뿐이다:
 *   · 같다 → 그대로 · 아직 아무 것도 안 나감 → 답 전체를 한 조각으로 내보냄(완료 전에 도착)
 *   · 답이 누적을 이어 감 → 남은 꼬리만 내보냄 · 누적이 답으로 끝남(중간 말 + 최종 답이 전부
 *     흐른 경우) → 나간 말을 버리지 않고 누적 전체가 답이 된다
 * 그 밖(중간에 흐른 말과 무관한 답이 계산된 경우)은 나간 말 뒤에 답을 잇는다 — 화면을 물릴 수
 * 없으므로 답이 화면을 따라온다.
 */
export function 미리보기정렬(reply, pv) {
  const 답 = String(reply ?? '');
  if (!pv) return 답;
  if (!pv.shown) { pv.emit(답); return 답; }
  if (답 === pv.shown) return 답;
  if (답.startsWith(pv.shown)) { pv.emit(답.slice(pv.shown.length)); return 답; }
  if (pv.shown.endsWith(답)) return pv.shown;
  // **앞 말과 무관한 답이 계산됐다 — 이건 이어감이 아니라 대체다.**
  //
  // 옛 전제는 *"화면을 물릴 수 없으므로 답이 화면을 따라온다"* 였다. 이제 물릴 수 있다
  // (`answer_reset`). 그대로 이어붙이면 서로 어긋나는 두 답이 한 답으로 저장되고
  // 사용자에게 그대로 간다 — 라이브에서 두 번 나왔다(F-8, 그리고 승인 경로에서 또):
  //   "…안전 때문에 rm -rf 실행은 보류했어." + "지금 내가 볼 수 있는 범위에는 그 폴더가 없어."
  //
  // 위 갈래들(같음·이어감·흐른 말이 답으로 끝남)은 **잃으면 안 되는 말**이라 그대로 둔다.
  // 여기 오는 것만 대체다.
  if (!답.trim()) return pv.shown;
  pv.retract?.();
  pv.emit(답);
  return 답;
}
