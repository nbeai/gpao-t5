// L3 · **화면 슬롯 (CU A · S8 의 두 번째 슬롯)**
//
// 오너가 못 박았다: *"슬롯이 진짜인지는 두 번째 슬롯이 설 때 판명됩니다. 그 두 번째가 CU 입니다.
// **CU 는 다음 기능이 아니라 S8 의 판정입니다.**"*
//
// 그래서 여기서 **아무것도 새로 발명하지 않는다.** 검색 슬롯과 같은 등록소·같은 계약 검사·
// 같은 순서 규칙을 쓴다. 발명해야 했다면 그건 슬롯이 아니라 검색 전용 함수였다는 뜻이다.
//
// 계약이 `id`·`status`·`observe` 인 이유 — 정본 §4.2 가 *"환경변수나 문서가 아니라 네이티브
// 호스트의 **실제 probe 결과**만 사용한다"* 고 못 박았다. 드라이버는 **상태를 스스로 말할 수
// 있어야** 붙는다. 상태를 못 말하는 백엔드는 권한이 없을 때 빈 목록을 내고, 그러면 T5 가
// *"창이 없네요"* 라고 답하게 된다(조용한 0).
import { makeSlotRegistry } from '../kernel/l2-plan/slot-registry.js';

/** 슬롯 이름. 문자열을 흩뿌리지 않는다 — 오타 하나로 조용히 빈 목록이 된다. */
export const DESKTOP_SLOT = 'desktop';

/**
 * 화면 슬롯의 계약 — **드라이버가 반드시 밝혀야 하는 칸.**
 *
 * `status` 가 계약인 것이 이 슬롯의 핵심이다. 목록만 낼 줄 아는 백엔드는 **못 볼 때와
 * 볼 게 없을 때를 구분해 주지 못한다.** 그 둘을 커널이 내용으로 짐작하면 심문이 되고,
 * 안 하면 없는 사실이 나간다. 그래서 **드라이버가 스스로 밝히게** 한다.
 */
const 화면계약 = ['id', 'status', 'observe'];

/**
 * 화면 슬롯을 세운다. **드라이버는 안 붙인다** — 네이티브 백엔드는 배선하는 쪽이 붙인다.
 * 검색 슬롯은 있던 셋을 여기서 붙였는데, 그건 이미 코어 안에 있던 것이라 그랬다.
 * 화면 백엔드는 코어 밖에 있고, 그게 **발자국 사다리를 안 올라간다는 증거**다.
 *
 * @param {object} [등록소] 다른 슬롯과 한 등록소를 나눠 쓰고 싶을 때
 */
export function 화면슬롯세우기(등록소 = makeSlotRegistry()) {
  등록소.슬롯세우기({
    id: DESKTOP_SLOT,
    계약: 화면계약,
    설명: '화면·앱·창을 관찰한다. 드라이버는 `status` 로 자기 권한·준비 상태를 스스로 밝힌다.',
  });
  return 등록소;
}

/** 기본 등록소 — 제품 배선이 쓰는 자리. 검사는 자기 등록소를 세워 쓴다(오염 방지). */
let 기본등록소 = null;
export function 화면등록소() {
  기본등록소 ??= 화면슬롯세우기();
  return 기본등록소;
}

/**
 * 붙은 드라이버. **0개면 빈 배열을 그대로 돌려준다** — 검색과 다르다.
 *
 * 검색은 0개면 터진다(배선이 깨진 것이므로). 화면은 **이 컴퓨터에 백엔드가 없는 것이 정상**이다
 * (macOS 아닌 곳 · 백엔드를 안 깐 곳). 그래서 없음은 오류가 아니라 사실이고,
 * 그 사실을 손이 *"볼 수 없다"* 로 말한다 — *"창이 없다"* 가 아니라.
 */
export function 화면드라이버(등록소 = 화면등록소()) {
  return 등록소.드라이버(DESKTOP_SLOT);
}
