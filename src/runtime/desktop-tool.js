// 손은 그 사실을 읽어 *못 본 것*과 *볼 게 없는 것*을 가른다(심문 금지 · 손이 스스로 밝힌다).
//
// 도구를 넷으로 안 풀고 한 손의 `action` 으로 표현한다(정본 §4.1) — 매 콜 비용이 손 수에
// 비례하고(불변식 B), status/observe 는 같은 대상·같은 권한·같은 영수증 계약을 지난다.

import { createHash } from 'node:crypto';

/**
 * **요소의 신분 지문**(반대시험 A04 준비 · CU B).
 *
 * B 는 관찰이지만 **C(첫 손)가 이 결과를 받아 누른다.** 그때 화면은 이미 바뀌어 있을 수 있다.
 * A04: *"AX ref 가 다른 요소를 가리키게 변경 → fingerprint 불일치, 실행 0."*
 * 신분 없이 좌표나 순번만 주면 **C 가 다른 것을 누른다.** 지문을 만드는 것은 B 의 일이고,
 * 여기서 안 만들면 C 가 만들 수 없다.
 *
 * 무엇으로 만드나 — **바뀌면 다른 것이어야 하는 것들**만 넣는다: 종류·이름·자리·켜짐.
 * 값(`value`)은 안 넣는다. 사용자가 타이핑만 해도 지문이 바뀌면 아무것도 대조 못 한다.
 * 그리고 **비밀칸의 값은 애초에 여기 오면 안 된다** — 지문은 원장에 남는다.
 */
function 요소지문(e = {}) {
  const b = e.bounds ?? {};
  const 재료 = [e.type ?? '', e.role ?? '', e.label ?? '', e.isEnabled === false ? '0' : '1',
    b.x ?? '', b.y ?? '', b.w ?? b.width ?? '', b.h ?? b.height ?? ''].join('|');
  return createHash('sha256').update(재료).digest('hex').slice(0, 12);
}

/**
 * **비밀칸인가**(반대시험 A09). 백엔드가 뭐라고 부르든 알아본다.
 *
 * **백엔드를 믿지 않는다.** 남이 만든 것이고 다음 판에서 표기가 바뀔 수 있다 —
 * 실제로 `AXSecureTextField` 는 role 로도 subrole 로도 오고, 종류 이름도 판마다 다르다.
 * 그쪽이 값을 실어 보내도 **우리 손이 지운다.** 계약을 지키는 자리는 우리 쪽이다.
 * 모르면 **가리는 쪽**으로 기운다 — 한 번 새면 되돌릴 수 없다(절대 게이트: 비밀 노출).
 */
function 비밀칸인가(e = {}) {
  const 표기 = `${e.role ?? ''} ${e.subrole ?? ''} ${e.type ?? ''}`.toLowerCase();
  return /secure/.test(표기);
}

/**
 * 요소 하나를 **내보낼 수 있는 모양**으로 바꾼다.
 *
 * A09 의 자리다 — 비밀칸의 `value` 는 **아예 싣지 않는다.** 지우는 것이 아니라 안 만든다.
 * 그러나 **요소 자체는 남긴다**: 비밀번호 칸이 있다는 것은 사실이고 모델이 알아야 한다.
 * 통째로 빼면 모델은 로그인 창을 보고도 "비밀번호 칸이 없다"고 말하게 된다.
 */
function 내보낼요소(e = {}) {
  const 비밀 = 비밀칸인가(e);
  const { value, ...나머지 } = e;
  return {
    ...나머지,
    ...(비밀 ? { 비밀칸: true } : (value === undefined ? {} : { value })),
    지문: 요소지문(e),
  };
}

