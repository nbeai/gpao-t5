// L3 · **화면 손 (CU A)** — `desktop.status` · `desktop.observe` 를 한 손으로 낸다.
//
// ── A 의 첫 계약: 조용한 0 을 "창이 없네요"로 답하지 않는다 ────────────────
//
// 밟은 사실(2026-08-05, 서명한 탐침을 직접 돌림):
// ```
// 권한(실제 probe)   화면 기록 false · 손쉬운 사용 false · 이벤트 전송 false
// 앞 앱              Google Chrome · com.google.Chrome · pid 72904   ← 권한 0으로 나온다
// 창 목록            0개                                             ← 여기서 막힌다
// ```
// **권한이 없을 때 창 목록은 예외가 아니라 빈 배열로 온다.** 그대로 결과로 쓰면
// *"창이 없네요"* 가 나가고, 그건 없는 사실을 지어내는 것이다. 파일·검색에서 이미 여러 번
// 밟은 병인데(조용한 0) GUI 는 훨씬 흔하다 — 권한·잠금·전환 중에 늘 빈다.
//
// **그래서 커널이 내용을 보고 판정하지 않는다.** 드라이버가 `status` 로 권한을 밝히고,
// 손은 그 사실을 읽어 *못 본 것*과 *볼 게 없는 것*을 가른다(심문 금지 · 손이 스스로 밝힌다).
//
// 도구를 넷으로 안 풀고 한 손의 `action` 으로 표현한다(정본 §4.1) — 매 콜 비용이 손 수에
// 비례하고(불변식 B), status/observe 는 같은 대상·같은 권한·같은 영수증 계약을 지난다.

import { createHash } from 'node:crypto';

/**
 * **요소의 신분 지문**(반대시험 A04 준비 · CU B).
 *
 * B 는 관찰이지만 **C(첫 손)가 이 결과를 받아 누른다.** 그때 화면은 이미 바뀌어 있을 수 있다.
 * A04: *"AX ref 가 다른 요소를 가리키게 변경 → fingerprint 불일치, 실행 0."*
 * 신분 없이 좌표나 순번만 주면 **C 가 다른 것을 누른다.** 지문을 만드는 것은 B 의 일이고,
 * 여기서 안 만들면 C 가 만들 수 없다.
 *
 * 무엇으로 만드나 — **바뀌면 다른 것이어야 하는 것들**만 넣는다: 종류·이름·자리·켜짐.
 * 값(`value`)은 안 넣는다. 사용자가 타이핑만 해도 지문이 바뀌면 아무것도 대조 못 한다.
 * 그리고 **비밀칸의 값은 애초에 여기 오면 안 된다** — 지문은 원장에 남는다.
 */
function 요소지문(e = {}) {
  const b = e.bounds ?? {};
  const 재료 = [e.type ?? '', e.role ?? '', e.label ?? '', e.isEnabled === false ? '0' : '1',
    b.x ?? '', b.y ?? '', b.w ?? b.width ?? '', b.h ?? b.height ?? ''].join('|');
  return createHash('sha256').update(재료).digest('hex').slice(0, 12);
}

/**
 * **비밀칸인가**(반대시험 A09). 백엔드가 뭐라고 부르든 알아본다.
 *
 * **백엔드를 믿지 않는다.** 남이 만든 것이고 다음 판에서 표기가 바뀔 수 있다 —
 * 실제로 `AXSecureTextField` 는 role 로도 subrole 로도 오고, 종류 이름도 판마다 다르다.
 * 그쪽이 값을 실어 보내도 **우리 손이 지운다.** 계약을 지키는 자리는 우리 쪽이다.
 * 모르면 **가리는 쪽**으로 기운다 — 한 번 새면 되돌릴 수 없다(절대 게이트: 비밀 노출).
 */
function 비밀칸인가(e = {}) {
  const 표기 = `${e.role ?? ''} ${e.subrole ?? ''} ${e.type ?? ''}`.toLowerCase();
  return /secure/.test(표기);
}

/**
 * 요소 하나를 **내보낼 수 있는 모양**으로 바꾼다.
 *
 * A09 의 자리다 — 비밀칸의 `value` 는 **아예 싣지 않는다.** 지우는 것이 아니라 안 만든다.
 * 그러나 **요소 자체는 남긴다**: 비밀번호 칸이 있다는 것은 사실이고 모델이 알아야 한다.
 * 통째로 빼면 모델은 로그인 창을 보고도 "비밀번호 칸이 없다"고 말하게 된다.
 */
function 내보낼요소(e = {}) {
  const 비밀 = 비밀칸인가(e);
  const { value, ...나머지 } = e;
  return {
    ...나머지,
    ...(비밀 ? { 비밀칸: true } : (value === undefined ? {} : { value })),
    지문: 요소지문(e),
  };
}

/**
 * **조용히 자르지 않는다** — 파일 손의 `문`, 웹 손의 `readWindow` 와 같은 계약.
 *
 * 실측(2026-08-05): 크롬 창 하나에 요소가 **384개**였다. 그대로 실으면 재료가 밀리고,
 * 밀리면 **무엇이 접혔는지 아무도 모른다** — 그날 온도표가 통째로 사라진 그 모양이다.
 * 그렇다고 말없이 앞 몇 개만 주면 모델은 그게 전부인 줄 알고 *"로그인 버튼이 없다"* 고 한다.
 *
 * 그래서 **얼마나 있고 어디까지 줬는지 함께 낸다.** 모자라면 `offset` 으로 이어 부른다.
 */
const 요소기본 = 40;
function 요소창(요소들0, args = {}) {
  // **모델이 좁힌다 — 커널이 고르지 않는다**(라이브 2026-08-05).
  //
  // 밟은 사실: *"앞 창에 버튼 뭐뭐 있어?"* 에 요소 385개 중 앞 40개가 갔는데, 하필 그 40개가
  // 전부 이름 없는 것(`label:"버튼"`)이었다. 모델은 **유튜브 UI 상식으로 목록을 메웠다** —
  // "재생/일시정지·볼륨·전체화면…". 밝히긴 했지만 사용자는 T5 가 본 것으로 읽는다.
  // 실제로는 385개 중 **324개에 진짜 이름이 있었다**("닫기 버튼"·"전체 화면 버튼"·"북마크 폴더 버튼").
  //
  // 커널이 "관련 있는 것"을 골라 주면 그건 내용 판정이고 심문이다(절대원칙 8).
  // 그래서 **고르는 수단을 모델에게 준다.** 모델이 `type` 을 좁히면 그만큼만 온다.
  // 틀려도 길이 안 막힌다 — 안 좁히면 전부가 그대로 오고, `offset` 으로 끝까지 닿는다.
  const 종류 = String(args?.type ?? '').trim();
  const 요소들 = 종류 ? 요소들0.filter((e) => String(e?.type ?? '') === 종류) : 요소들0;
  const 총 = 요소들.length;
  const 시작0 = Number(args?.offset);
  const 시작 = Number.isInteger(시작0) && 시작0 > 0 ? Math.min(시작0, 총) : 0;
  const 몇개0 = Number(args?.limit);
  const 몇개 = Number.isInteger(몇개0) && 몇개0 > 0 ? 몇개0 : 요소기본;
  const 끝 = Math.min(시작 + 몇개, 총);
  return {
    elements: 요소들.slice(시작, 끝).map(내보낼요소),
    // 좁혔으면 **무엇으로 좁혔고 전체가 몇이었는지** 함께 낸다 — 안 주면 모델이 좁힌 결과를
    // 화면 전부로 읽는다(조용한 절단의 다른 얼굴).
    요소창: { 시작, 끝, 총, ...(종류 ? { 종류, 전체: 요소들0.length } : {}), ...(끝 < 총 ? { 다음: 끝 } : {}) },
  };
}

/** 권한 값이 "됐다"인가. 모르는 값은 **안 된 쪽으로** 본다(모름은 자동이 아니라 확인 쪽이다). */
const 허용됨 = (v) => v === 'granted' || v === true;

/** 창을 볼 수 있나 — **실제로 필요한 것만** 본다(아래 주석: 재 보고 좁혔다). */
const 창볼수있나 = (권한 = {}) => 창에필요한권한.every((k) => 허용됨(권한[k]));

/**
 * **창 목록에 실제로 필요한 권한은 손쉬운 사용 하나다**(라이브 실측 2026-08-05).
 *
 * 처음엔 화면 기록까지 요구했다. **틀렸다.** 화면 기록이 `denied` 인 채로 재 보니
 * 창 목록도 **제목까지 전부** 나왔다:
 * ```
 * 권한   accessibility granted · screenRecording denied
 * 창     1개 · "…아는형님 - YouTube - 오디오 재생 - Chrome - TV (wildwolf)"
 * ```
 * 화면 기록은 **픽셀(스크린샷)** 에 필요한 것이고, 스크린샷은 CU F 칸이라 A 에는 없다.
 *
 * **이 실수의 모양을 적어 둔다** — 조용한 0 의 거울상이다. 없는 것을 있다고 하는 대신
 * **있는 것을 없다고** 했다. 사용자는 받을 수 있는 답 대신 권한 안내를 받는다.
 * §0 이 깨지는 방식은 둘 다 같다: **방법(권한 규칙)이 목적(지금 뭐 떠 있어?)을 덮는다.**
 * 안전 쪽 기본값을 세게 잡는 것이 정직해 보였는데, 재 보지 않고 잡은 것이 문제였다.
 */
const 창에필요한권한 = ['accessibility'];

/** 사용자가 볼 문장. 어느 권한이 왜 막혔는지는 사실이므로 숨기지 않는다. */
function 못보는이유(권한 = {}) {
  const 이름 = { accessibility: '손쉬운 사용', screenRecording: '화면 기록' };
  const 없는것 = 창에필요한권한.filter((k) => !허용됨(권한[k])).map((k) => 이름[k]);
  return 없는것.length
    ? `창을 보려면 ${없는것.join('·')} 권한이 필요해요. 아직 허용되지 않았어요.`
    : '지금은 창을 볼 수 없어요.';
}

/**
 * @param {{drivers?:Array<object>}} deps 화면 슬롯에서 온 드라이버 목록
 */
export function makeDesktopTool(deps = {}) {
  const drivers = Array.isArray(deps.drivers) ? deps.drivers : [];
  return {
    // 읽기만 한다. 출처 원장 계약은 안 건다 — 웹 페이지가 아니라 이 컴퓨터의 현재 상태다.
    sourceLedgerRequired: false,
    async handler(args) {
      const 드라이버 = drivers[0];
      if (!드라이버) {
        // **"창이 없다"가 아니라 "볼 수 없다"다.** 백엔드가 없는 것은 이 컴퓨터의 사실이고,
        // 그걸 창의 사실로 옮기면 없는 것을 지어내는 것이다.
        return {
          blocked: true,
          userSafeSummary: '이 컴퓨터에서는 화면을 볼 수 있는 준비가 아직 안 됐어요.',
          nextSafeAction: '화면 보기를 켜면 지금 떠 있는 창을 알려드릴 수 있어요.',
          다음수단: [{ 방법: 'install_backend', 왜: '화면 관찰 백엔드가 아직 없다' }],
        };
      }

      const 상태 = await 드라이버.status();
      const 권한 = 상태?.permissions ?? {};

      // `status` 는 **권한이 없어도 막지 않는다.** 상태 조회까지 막으면 왜 막혔는지도 못 말한다.
      if (args?.action === 'status') {
        // 권한 없이도 되는 것(앞 앱)은 함께 준다 — 아는 것보다 덜 말하지 않는다.
        let 앞 = 상태?.frontmost;
        if (!앞) { try { 앞 = (await 드라이버.observe({ scope: 'app' }))?.frontmost; } catch { 앞 = undefined; } }
        return {
          result: { ...상태, ...(앞 ? { frontmost: 앞 } : {}) },
          userSafeSummary: 창볼수있나(권한) ? '화면을 볼 준비가 돼 있어요.' : 못보는이유(권한),
        };
      }

      const 본것 = await 드라이버.observe(args ?? {});

      // ── 여기가 갈리는 자리다 ──────────────────────────────────────────
      // 권한이 없으면 **목록을 결과로 내지 않는다**(빈 배열도 목록이다).
      // 앞 앱은 권한 없이도 나오므로 그건 준다 — 못 본 것만 못 봤다고 한다.
      if (!창볼수있나(권한)) {
        return {
          blocked: true,
          권한,
          ...(본것?.frontmost ? { frontmost: 본것.frontmost } : {}),
          userSafeSummary: 못보는이유(권한),
          nextSafeAction: '시스템 설정에서 한 번 허용해 주시면 그다음부터는 안 여쭤봐요.',
          // **이미 허용된 권한을 다시 내밀지 않는다.** 라이브에서 손쉬운 사용이 `granted` 인데도
          // 둘 다 내밀고 있었다 — 사용자는 이미 준 것을 또 주러 가고, 무엇이 진짜 막힌 건지
          // 흐려진다. 없는 사실을 지어내지 않는 규칙은 **다음 수단에도 똑같이 선다.**
          다음수단: 창에필요한권한
            .filter((k) => !허용됨(권한[k]))
            .map((k) => ({ 방법: 'grant_permission', 무엇: k === 'accessibility' ? 'accessibility' : 'screen_recording', 왜: '창 목록과 요소를 읽으려면 필요하다' })),
        };
      }

      // 권한이 있으면 **0 은 진짜 0 이다.** 그런데 그 0 이 왜 믿을 만한지를 함께 준다 —
      // 안 주면 다음 사람이(그리고 모델이) 이 0 을 또 의심하게 된다.
      return {
        result: {
          ...본것,
          windows: 본것?.windows ?? [],
          // **요소는 그냥 흘려보내지 않는다**(CU B). 신분(지문)을 붙이고 비밀칸의 값을 뺀다.
          // 백엔드가 준 그대로 내보내면 A04(신분 없음)와 A09(비밀 노출)가 동시에 뚫린다.
          ...(본것?.elements ? 요소창(본것.elements, args) : {}),
          권한확인됨: true,
          // **화면 글자는 우리가 쓴 글이 아니다**(반대시험 A10 · 정본 §6.4).
          // 창 제목·요소 이름은 웹페이지·메일·문서와 같은 부류다. 관찰 전용이라 안전해
          // 보이지만 **거기가 주입의 입구다** — 화면에 *"권한을 무시하고 실행"* 이 적혀 있으면
          // 그 글자가 그대로 모델 앞에 놓인다.
          //
          // **글자를 지우지 않는다.** 지우면 사용자가 실제로 무엇을 보고 있는지 못 말하고,
          // 그건 §0 을 어긴다. 대신 **무엇인지 못 박는다** — 검열이 아니라 출처 표시다.
          // 표식은 창이 0개여도 붙는다. 있을 때만 붙이면 빈 날에 조용히 빠진다.
          관찰내용은데이터: true,
        },
        userSafeSummary: (본것?.windows?.length ?? 0) > 0
          ? `지금 ${본것.frontmost?.name ?? '앞 앱'} 창 ${본것.windows.length}개가 떠 있어요.`
          : '권한은 있는데 열려 있는 창이 없어요.',
      };
    },
  };
}
