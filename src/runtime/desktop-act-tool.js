// L3 · **화면 손 · 행동 (CU C)** — 첫 손. 눌렀는지가 아니라 **됐는지**로 판정한다.
//
// ── 왜 관찰 손과 나눠 두나 ──────────────────────────────────────────────
// `desktop.screen` 은 읽기(`read`)다. 행동은 아니다. 권한 종류는 **손 단위로 판정**되므로
// (`toolActionKind`), 한 손에 합치면 읽기와 행동이 같은 등급을 받는다 —
// 읽기가 행동 등급으로 올라가 카드가 늘거나, 행동이 읽기로 새거나 둘 중 하나다.
// 정본 §4.1 이 `observe` 와 `act` 를 나눈 이유가 그것이다.
//
// ── C 는 넷만 받는다 ────────────────────────────────────────────────────
// 계획 §5.1: 클릭·타이핑을 **일부러 뺐다.** 반대시험 A14(*"dispatch 성공, 화면 변화 없음
// → 성공 영수증 0"*)가 CU 에서 제일 어려운 요구인데 **화면은 대조 기준이 없다**
// (시계·애니메이션으로 늘 조금씩 변한다). 그런데 이 넷은 대조가 자명하다:
//
//     focus         frontmost 값
//     scroll        스크롤 위치
//     move·resize   창 좌표
//     launch·quit   프로세스 존재
//
// **가장 어려운 계약을 가장 쉬운 대상에서 먼저 세운다.** 여기서 A14 가 "전후 값 비교 한 줄"로
// 서면, D(클릭·입력)부터는 같은 계약을 어려운 대상에 적용하는 일이 된다.
//
// ── 정본 §7 의 다섯 상태 ────────────────────────────────────────────────
//   requested → resolved → dispatched → effect_observed → goal_verified
// **`dispatched` 만으로 성공을 만들지 않는다.** 이 파일의 전부가 그 한 줄이다.

/** C 가 받는 넷. 여기 없는 것은 **없다고 정직하게 말한다**(있는 척도 조용한 실패도 아니다). */
const 받는행동 = new Set(['focus', 'scroll', 'move', 'resize', 'launch', 'quit', 'click', 'type']);

/**
 * **누르는 것들 (CU D)** — C 의 넷과 갈리는 자리.
 *
 * C 의 넷은 대조가 자명했다(frontmost·스크롤·좌표·프로세스). 클릭은 아니다 —
 * **버튼을 누르면 무엇이 바뀌어야 하는지 커널은 모른다.** 그러면 A14 를 잴 수가 없다.
 *
 * 두 갈래가 있었다:
 *   ✗ 커널이 화면 글자를 읽고 "저장 버튼이니 저장됐나 보자"고 판정한다 → **심문**이고,
 *     화면 글자는 남이 쓴 글이라(A10) **주입이 판정을 조종한다.**
 *   ✓ **모델이 기대 효과를 먼저 선언한다.** 커널은 그 선언을 **확인만** 한다.
 *
 * 두 번째가 정본 §5(*"클릭이 아니라 의미 효과를 판정한다"*)이고 §1.2 그대로다.
 */
const 누르는것 = new Set(['click', 'type']);

/**
 * **무엇을 보면 됐는지 아나** — 행동마다 대조할 값이 다르다.
 *
 * 이 표가 C 의 알맹이다. 여기 없는 행동은 **대조할 값이 없다는 뜻**이고,
 * 대조할 값이 없으면 성공을 주장할 수 없다 — 그래서 애초에 안 받는다.
 */
const 대조할값 = {
  focus: (본것) => ({ frontmost: 본것?.frontmost?.name ?? null }),
  scroll: (본것) => ({ 스크롤: 본것?.scroll ?? null }),
  move: (본것) => ({ 창자리: JSON.stringify(본것?.windows?.[0]?.bounds ?? null) }),
  resize: (본것) => ({ 창자리: JSON.stringify(본것?.windows?.[0]?.bounds ?? null) }),
  launch: (본것) => ({ 앱들: (본것?.apps ?? []).length, frontmost: 본것?.frontmost?.name ?? null }),
  quit: (본것) => ({ 앱들: (본것?.apps ?? []).length, frontmost: 본것?.frontmost?.name ?? null }),
  // 누르기는 **모델이 지목한 요소의 값**을 본다. 무엇을 볼지는 모델이 정하고 커널은 대조만 한다.
  click: (본것, args) => ({ 값: 요소값(본것, args?.기대?.요소) }),
  type: (본것, args) => ({ 값: 요소값(본것, args?.기대?.요소) }),
};

/** 관찰 결과에서 그 요소의 현재 값. 없으면 `null` — 못 찾은 것과 값이 빈 것을 안 섞는다. */
function 요소값(본것, 요소id) {
  if (!요소id) return null;
  const e = (본것?.elements ?? []).find((x) => x?.id === 요소id);
  return e ? (e.value ?? null) : null;
}

const 같은가 = (a, b) => JSON.stringify(a) === JSON.stringify(b);

/**
 * **됐는가는 "바뀌었나"가 아니라 "목표 상태인가"다**(라이브 2026-08-05 에 잡음).
 *
 * 처음엔 전후가 같으면 무조건 실패로 냈다. 그러자 **이미 앞에 있는 크롬을 앞으로 띄워 달라**는
 * 요청에서 *"화면이 안 바뀌었어요"* 가 나갔다 — **됐는데 안 됐다고 한 것**이고,
 * 조용한 0 의 거울상을 오늘 두 번째로 밟은 것이다.
 *
 * 정본 §7 이 이미 적어 뒀다: *"변화가 없어도 정상인 행동은 사전에 정의된 verification
 * contract 로 확인한다."* 그러니 행동마다 **무엇이면 목표 도달인지**를 여기 적는다.
 * 목표 상태를 말할 수 없는 행동(스크롤·창 옮기기)만 **변화**로 판정한다 —
 * 거기서는 "얼마나"를 우리가 모르기 때문이다.
 *
 * @returns {true|false|null}  null = 목표를 정의할 수 없다(변화로 판정한다)
 */
function 목표도달(행동, args, 후) {
  const 대상 = String(args?.app ?? '').trim().toLowerCase();
  if (!대상) return null;
  const 앞 = String(후?.frontmost ?? '').toLowerCase();
  if (행동 === 'focus' || 행동 === 'launch') {
    // 이름이 딱 같지 않아도 된다 — 사용자는 "크롬"이라 하고 OS 는 "Google Chrome"이라 한다.
    return Boolean(앞) && (앞.includes(대상) || 대상.includes(앞));
  }
  if (행동 === 'quit') return !(앞.includes(대상) || 대상.includes(앞));
  return null;
}

/** 누르기의 목표 도달 — **모델이 말한 값이 됐는가.** 커널은 그 말을 확인만 한다. */
function 누르기도달(args, 후) {
  const 원한값 = args?.기대?.값;
  if (원한값 === undefined) return null;
  return String(후?.값 ?? '') === String(원한값);
}

/**
 * @param {{drivers?:Array<object>}} deps 화면 슬롯에서 온 드라이버 목록
 */
export function makeDesktopActTool(deps = {}) {
  const drivers = Array.isArray(deps.drivers) ? deps.drivers : [];
  return {
    sourceLedgerRequired: false,
    async handler(args) {
      const 드라이버 = drivers[0];
      if (!드라이버) {
        return {
          blocked: true,
          userSafeSummary: '이 컴퓨터에서는 화면을 다룰 준비가 안 됐어요.',
          다음수단: [{ 방법: 'install_backend', 왜: '화면 백엔드가 없다' }],
        };
      }

      const 행동 = String(args?.action ?? '').trim();
      if (!받는행동.has(행동)) {
        // **없는 것을 없다고 말한다.** 조용히 실패하면 모델은 "했는데 안 됐다"로 읽고,
        // 있는 척하면 못 지킬 약속이 된다.
        return {
          blocked: true,
          userSafeSummary: `그건 아직 못 해요 — 지금은 창을 앞으로 띄우거나, 내리거나, 옮기거나, 앱을 켜고 끄는 것까지예요.`,
          다음수단: [{ 방법: 'observe', 왜: '무엇이 있는지 먼저 본다' }],
        };
      }

      // ── A04 · 지문이 다르면 **부르지도 않는다** ─────────────────────────
      // 관찰과 실행 사이에 화면이 바뀌었을 수 있다. 그때 옛 신분으로 실행하면
      // **다른 것을 조작한다.** 값이 안 맞으면 실행 0 이고, 다시 보라고 한다.
      const 준지문 = args?.대상?.지문;
      const 확인지문 = args?.확인지문;
      if (준지문 && 확인지문 && 준지문 !== 확인지문) {
        return {
          blocked: true,
          userSafeSummary: '그 사이에 화면이 바뀌었어요. 안전을 위해 실행하지 않았어요.',
          다음수단: [{ 방법: 'observe', 왜: '지금 화면을 다시 보고 대상을 다시 고른다' }],
        };
      }

      // ── D · 누르기 전에 갖춰야 하는 것 ─────────────────────────────────
      if (누르는것.has(행동)) {
        const 막힘 = (문장, 수단 = 'observe') => ({
          blocked: true, userSafeSummary: 문장,
          다음수단: [{ 방법: 수단, 왜: '지금 화면을 다시 보고 무엇을 누를지 정한다' }],
        });

        // **A17 — 이름 없는 것은 안 누른다.** B 실측에서 창 하나에 385개 중 61개가 이름 없는
        // `"버튼"` 이었다. 좌표로 누르면 **원장에 적을 것이 좌표뿐**이고, 무엇을 눌렀는지
        // 아무도 모른다. 밋밋한 이름(`"버튼"`)은 받는다 — 그건 앱이 그렇게 준 것이고 신분은 있다.
        if (!String(args?.대상?.label ?? '').trim()) {
          return 막힘('무엇을 누르는 건지 이름이 없어서 누르지 않았어요.');
        }

        // **비밀칸에는 입력하지 않는다**(헌장 ① · A09). 비밀은 사람만 넣는다.
        // 거절하면서 값을 실어 보내지도 않는다 — 영수증은 남는다.
        if (args?.대상?.비밀칸 === true) {
          return 막힘('비밀번호 칸에는 제가 직접 입력하지 않아요. 그건 직접 넣으셔야 해요.', 'user_input');
        }

        // **A02 — 같은 이름이 둘이면 누르지 않는다.**
        //
        // 실측(2026-08-05)이 길을 바꿨다: 요소 **신분(id)으로 누르면** 백엔드가 저장된 것을
        // 살아 있는 AX 요소로 못 되살려 `snapshotStale` 로 떨어지고, **이름으로 누르면 눌린다.**
        // 그래서 클릭은 이름으로 나간다. **그런데 이름은 신분이 아니다** —
        // 같은 이름이 둘이면 어느 것이 눌릴지 우리가 모르고, **모르면 안 누른다**(A02).
        let 지금요소 = null;
        try { 지금요소 = (await 드라이버.observe({ scope: 'window' }))?.elements ?? null; } catch { 지금요소 = null; }
        if (Array.isArray(지금요소)) {
          const 이름 = String(args.대상.label);
          const 겹침 = 지금요소.filter((e) => String(e?.label ?? '') === 이름).length;
          if (겹침 > 1) {
            return 막힘(`"${이름}" 이라는 이름이 여러 개라 어느 것을 누를지 알 수 없어요.`);
          }
        }

        // **무엇이 바뀌면 된 것인지 안 말하면 누르지 않는다.** 그게 없으면 눌러 놓고
        // 됐는지 잴 방법이 없고, 그 클릭은 A14 를 통과할 수 없다.
        if (!args?.기대?.요소) {
          return 막힘('무엇이 바뀌면 된 것인지 정해야 눌러 보고 확인할 수 있어요.');
        }

        // **바깥으로 나가는 것은 이 칸이 아니다.** 커널이 화면 글자로 위험을 판정하지 않는다 —
        // **모델이 밝힌 것**으로 갈린다. 밝혔으면 승인 경계가 받는 자리(E)이고 여기서는 안 한다.
        if (args?.기대?.바깥으로 === true) {
          return 막힘('그건 바깥으로 나가는 일이라 아직 제가 누르지 않아요.', 'observe');
        }
      }

      const 재기 = 대조할값[행동];
      let 전;
      try { 전 = 재기(await 드라이버.observe({ scope: 누르는것.has(행동) ? 'window' : 'screen' }), args); } catch { 전 = null; }

      // ── dispatched ─────────────────────────────────────────────────────
      try {
        // 대상에 **이름을 반드시 실어 보낸다** — 백엔드가 id 로는 못 되살린다(위 실측).
        await 드라이버.act({ 행동, 대상: { app: args?.app, window: args?.window, ...(args?.대상 ?? {}) }, 값: args?.값 });
      } catch {
        // 내부 오류는 사용자면으로 안 보낸다(진단면 분리). 실패는 실패라고 한다.
        return {
          failed: true,
          userSafeSummary: '그 동작을 실행하지 못했어요.',
          // 실행이 아예 안 나갔다 — 이건 모르는 것이 아니라 **안 한 것**이다.
          진행: { 단계: 'resolved', 판정: 'not_dispatched', 전 },
          다음수단: [
            { 방법: 'observe', 왜: '지금 상태를 다시 본다' },
            { 방법: 'retry', 왜: '실행이 아예 안 나갔으므로 다시 해도 두 번 되지 않는다' },
          ],
        };
      }

      // ── effect_observed · 여기가 A14 다 ────────────────────────────────
      let 후;
      try { 후 = 재기(await 드라이버.observe({ scope: 누르는것.has(행동) ? 'window' : 'screen' }), args); } catch { 후 = null; }

      // **먼저 목표 도달을 본다.** 변화 여부는 그다음이다 —
      // 이미 목표 상태였으면 안 바뀐 것이 정상이고, 그걸 실패로 내면 됐는데 안 됐다고 하는 것이다.
      const 도달 = 후 === null ? null : (누르는것.has(행동) ? 누르기도달(args, 후) : 목표도달(행동, args, 후));
      // ── **"안 됐다"와 "모르겠다"는 다르다** ────────────────────────────
      //
      // 뜻이 정반대다:
      //   안 됐다   → 다시 하거나 다른 길로 간다
      //   모르겠다  → **다시 하면 안 된다.** 이미 됐는데 못 본 것일 수 있고,
      //              그 상태에서 또 누르면 두 번 실행된다(절대 게이트: 중복 실행)
      //
      // cua-driver 계약이 그걸 문장으로 못 박아 뒀다(감사 2026-08-05):
      //   *"unknown never implies success. absence remains unknown unless the observed
      //    search domain is proven exhaustive."*
      // 앞줄은 우리 A14 와 같고 **뒷줄이 우리에게 없던 것**이다 — 다 봤다는 증명이 없으면
      // "없다"가 아니라 "모른다". 드라이버를 갈기 전에 우리 손에 그 자리부터 만든다.
      if (후 === null) {
        return {
          failed: true,
          userSafeSummary: '실행은 했는데 그 결과를 확인하지 못했어요. 됐는지 안 됐는지 모르겠어요.',
          진행: { 단계: 'dispatched', 판정: 'unknown', 전, 후 },
          // **다시 하라고 권하지 않는다.** 이미 됐을 수 있다.
          다음수단: [{ 방법: 'observe', 왜: '지금 실제 상태를 보고 됐는지부터 확인한다' }],
        };
      }
      if (도달 === false) {
        return {
          failed: true,
          userSafeSummary: '실행은 했는데 원하신 상태가 되지 않았어요.',
          진행: { 단계: 'dispatched', 판정: 'unsatisfied', 전, 후 },
          다음수단: [
            { 방법: 'observe', 왜: '지금 실제 상태를 보고 다시 판단한다' },
            { 방법: 'retry', 왜: '앱이 뜨는 데 시간이 걸렸을 수 있다' },
          ],
        };
      }
      if (도달 === true) {
        return {
          result: {
            단계: 'goal_verified', 행동, 전, 후,
            확인방법: Object.keys(후).join('·'),
            // **안 바뀐 것도 사실이다.** 이미 그 상태였다는 것을 숨기면 모델이 자기가 바꾼 줄 안다.
            ...(같은가(전, 후) ? { 이미그상태였다: true } : {}),
          },
          userSafeSummary: 누르는것.has(행동)
            ? `${args?.대상?.label ?? '그것'} 을(를) ${행동 === 'type' ? '입력했' : '눌렀'}고, 실제로 바뀐 것까지 확인했어요.`
            : (같은가(전, 후)
              ? `${후.frontmost ?? '그 앱'} 은(는) 이미 앞에 떠 있었어요.`
              : `${후.frontmost ?? '그 창'} 을(를) 앞으로 띄웠어요.`),
        };
      }

      // 목표 상태를 말할 수 없는 행동(스크롤·창 옮기기)만 **변화**로 판정한다.
      // 목표 상태를 말할 수 없는 행동은 **변화**로 판정한다.
      // `후 === null` 은 위에서 이미 걸렀다 — **같은 판정을 두 곳에서 내리지 않는다**(두 진실 금지).
      // 실제로 두 겹으로 뒀더니 한쪽을 지워도 다른 쪽이 받아 **그물이 안 물었다.**
      // 여기서 남은 것은 `전` 을 못 찍은 경우뿐이고, 그것도 모르는 것이다.
      if (전 === null) {
        return {
          failed: true,
          userSafeSummary: '실행 전 상태를 못 찍어서 됐는지 안 됐는지 모르겠어요.',
          진행: { 단계: 'dispatched', 판정: 'unknown', 전, 후 },
          다음수단: [{ 방법: 'observe', 왜: '지금 실제 상태를 보고 됐는지부터 확인한다' }],
        };
      }
      if (같은가(전, 후)) {
        // **부르긴 했는데 아무것도 안 바뀌었다.** 이걸 성공으로 세면 사용자는 됐다고 듣고
        // 실제로는 안 된 것이다 — 거짓 성공이고, CU 에서 가장 위험한 자리다.
        return {
          failed: true,
          userSafeSummary: '실행은 했는데 화면이 안 바뀌었어요.',
          진행: { 단계: 'dispatched', 판정: 'unsatisfied', 전, 후 },
          다음수단: [
            { 방법: 'observe', 왜: '지금 실제 상태를 보고 다시 판단한다' },
            { 방법: 'retry', 왜: '앱이 뜨는 데 시간이 걸렸을 수 있다' },
          ],
        };
      }

      // ── goal_verified ──────────────────────────────────────────────────
      return {
        result: {
          단계: 'goal_verified',
          행동,
          전, 후,
          // 무엇을 근거로 됐다고 하는지 함께 낸다 — 이게 없으면 다음 사람이 이 성공을 못 믿는다.
          확인방법: Object.keys(후).join('·'),
        },
        userSafeSummary: 행동 === 'focus'
          ? `${후.frontmost ?? '그 창'} 을(를) 앞으로 띄웠어요.`
          : '그렇게 했어요. 화면이 실제로 바뀐 것까지 확인했어요.',
      };
    },
  };
}
