        // `"버튼"` 이었다. 좌표로 누르면 **원장에 적을 것이 좌표뿐**이고, 무엇을 눌렀는지
        // 아무도 모른다. 밋밋한 이름(`"버튼"`)은 받는다 — 그건 앱이 그렇게 준 것이고 신분은 있다.
