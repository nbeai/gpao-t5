/**
 * **화면 경유 전송의 상대 신분** (F-58 · PM 조건 ①② 2026-08-09).
 *
 * 채널 손은 `채널(도구 id) + 정규화된 수신자` 로 상대를 안다(`known-counterpart.js`).
 * 화면 손에는 그 자리가 없어서, 같은 "카톡에 이 말 보내기"가 채널로는 한 번만 묻고
 * 화면으로는 매번 물었다 — **사거리 비대칭병**이다.
 *
 * 신분은 **카드가 보여 준 그 실질**에서만 만든다: 앱 · 창(방) 이름 · 내용.
 * 내용을 넣는 것은 채널 손과 다른 점이고 의도한 것이다 — 화면 전송은 오클릭 위험이 있어
 * **문구가 달라지면 다시 묻는다**(PM 판정).
 *
 * **정규화가 안 서면 신분을 만들지 않는다(fail-closed · PM 조건 ②).** 창 제목에 미리보기·
 * 안 읽음 배지처럼 **매번 바뀌는 것**이 섞이면 같은 방이 매번 다른 상대가 되거나, 더 나쁘게
 * 다른 방이 같은 상대로 보인다. 채널 손 주석의 규율 그대로다 — *"모르는 형태는 다른 상대로
 * 둔다(안전한 쪽)"*. 여기서는 한 걸음 더: **모르는 형태면 상대를 아예 안 만든다.**
 *
 * 정규화(채널 손과 같은 수위 — 대소문자·공백만):
 *   · 앞뒤 공백 제거 · 연속 공백 하나로 · 소문자
 *   · 유니코드 NFC (한글 자모 분리 표기가 다른 상대로 보이지 않게)
 * 신분 불성립 조건(하나라도 걸리면 null):
 *   · 앱 또는 창 이름이 비었다
 *   · 창 이름에 **숫자 배지**가 붙어 있다(`… 4`·`(3)`·`[12]` — 안 읽음 수는 매번 바뀐다)
 *   · 창 이름에 **미리보기 구분자**가 있다(`:`·`—`·`|` 뒤에 본문이 붙는 꼴)
 *   · 창 이름이 너무 짧거나(1자) 너무 길다(60자 초과 — 제목이 아니라 본문일 것이다)
 *   · 보낼 내용이 비었다
 */
export function 발신실질(앱, 창, 내용) {
  const 다듬기 = (v) => String(v ?? '').normalize('NFC').replace(/\s+/g, ' ').trim();
  const a = 다듬기(앱).toLowerCase();
  const w = 다듬기(창);
  const c = 다듬기(내용);
  if (!a || !w || !c) return null;
  if (w.length < 2 || w.length > 60) return null;
  if (/(^|\s)[([]?\d{1,4}[)\]]?$/.test(w)) return null;   // 끝에 붙은 안 읽음 수
  if (/[:—|]\s*\S/.test(w)) return null;                   // 제목 뒤에 본문 미리보기가 붙었다
  return `desktop.act|${a}|${w.toLowerCase()}|${c}`;
}

