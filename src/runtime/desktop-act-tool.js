      let 전;
      // **마지막으로 본 화면 하나로 모은다.** 관찰할 때마다 새 스냅샷이 생기고, 그러면
      // 앞서 잡아 둔 토큰이 낡는다 — 낡은 토큰으로 누르면 **아무 데도 안 눌리는데**
      // 드라이버는 `background`·`unverifiable` 을 돌려주고, 우리는 *"했어요"* 라고 말한다.
