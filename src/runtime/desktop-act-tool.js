        // (라이브 2026-08-06 · 12×34 가 `1,492,031` 로 끝났다).
        //
        // 반대로 **짚어도 실을 것이 없으면**(토큰도 번호도 없는 드라이버) 드라이버가 쥔 건
        // 결국 이름뿐이다. 그때는 A02 가 그대로 문다 — 규율이 느슨해진 게 아니라 **정확해졌다.**
        // 낡은 신분은 여기가 아니라 A04(지문)가 맡는다.
        //
        // 갈래가 셋이다. 뭉치면 **틀린 이유를 말하게 된다** — 모델은 그 이유대로 다음 수를 고른다.
        //   ① 신분을 아예 안 줬다 → 이름뿐이다. A02.
        //   ② 신분을 줬는데 지금 화면에 없다 → **낡은 것이다. 다시 보라**(이름 탓이 아니다).
        //   ③ 신분을 줬고 찾았다 → 실을 것이 있으면 통과, 없으면(그 드라이버가 이름만 받으면) A02.
        const 신분축준것 = Boolean(args?.대상?.토큰) || args?.대상?.번호 != null || Boolean(args?.대상?.id);
