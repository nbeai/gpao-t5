/** 관찰 결과에서 그 요소의 현재 값. 없으면 `null` — 못 찾은 것과 값이 빈 것을 안 섞는다. */
function 요소값(본것, 요소id) {
  if (!요소id) return null;
  const e = (본것?.elements ?? []).find((x) => x?.id === 요소id);
  return e ? (e.value ?? null) : null;
}

const 같은가 = (a, b) => JSON.stringify(a) === JSON.stringify(b);

