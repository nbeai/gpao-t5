      // 라이브에서 모델이 좌표로 입력칸을 눌러 놓고도 *"어디에 넣을지 안 짚으셨어요"* 로 막혔다.
      // 규율은 그대로다: 커서가 어디 있는지 **우리가 모르므로** 이 걸음은 언제나 카드를 거친다.
