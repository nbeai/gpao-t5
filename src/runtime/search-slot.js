// L3 · **검색 슬롯의 배선 (S8 첫 소비자)** — 있던 셋을 드라이버로 등록한다.
//
// 오너 착수 지시 ①: *"첫 소비자를 CU 로 두지 않는다 — 이미 넷이 있다. 슬롯은 소비자가 둘 이상일
// 때만 모양이 잡힌다. 하나면 그냥 함수다."* 그래서 검색기 셋이 첫 드라이버가 되고, CU 는 다섯 번째다.
//
// **이 파일이 `web-search.js` 를 대신 고친다.** 새 검색기는 여기가 아니라 **밖에서** 붙는다 —
// 이 파일조차 안 고쳐도 되게 하는 것이 목표이고, 그래서 등록소를 돌려준다.
//
// 있던 셋을 여기서 **다시 정의하지 않는다.** `web-search.js` 가 이미 들고 있고
// (`SEARCH_PROVIDERS`), 두 곳에 적으면 언젠가 갈라진다(§4.4 · 두 진실 금지).
// 이 파일은 **옮기기만** 한다.
import { makeSlotRegistry } from '../kernel/l2-plan/slot-registry.js';
import { SEARCH_PROVIDERS } from './web-search.js';

/** 슬롯 이름. 문자열을 여러 곳에 흩뿌리지 않는다 — 오타 하나로 조용히 빈 목록이 된다. */
export const SEARCH_SLOT = 'web.search';

/**
 * 검색 슬롯의 계약 — **드라이버가 반드시 밝혀야 하는 칸.**
 *
 * `needs` 가 계약인 이유: 고르는 쪽이 `p.id === 'tavily'` 처럼 **이름으로 짐작하면** 새 드라이버가
 * 붙을 때마다 그 짐작을 늘려야 하고, 그게 곧 코어를 고치는 일이다. 드라이버가 스스로 밝히면
 * 고르는 쪽은 아무것도 안 고쳐도 된다. 설정이 필요 없으면 빈 배열이다.
 */
const 검색계약 = ['id', 'run', 'needs'];

/**
 * 검색 슬롯을 세우고 **있던 셋을 붙인 등록소**를 돌려준다.
 *
 * 층 순서(오너 결정: 무키 → 키, 위에서 되면 아래로 안 간다)는 **붙이는 순서**로 표현한다.
 * 등록소는 순서를 지켜 돌려주고, 고르는 것은 `makeWebSearch` 가 한다 — 등록소는 판정하지 않는다.
 *
 * @param {object} [등록소] 이미 있는 등록소에 얹고 싶을 때(다른 슬롯과 한 등록소를 나눠 쓰는 경우)
 */
export function 검색슬롯세우기(등록소 = makeSlotRegistry()) {
  등록소.슬롯세우기({
    id: SEARCH_SLOT,
    계약: 검색계약,
    설명: '웹에서 후보를 찾아 목록으로 낸다. 드라이버는 `needs` 로 자기 조건을 밝힌다.',
  });
  for (const 드라이버 of [SEARCH_PROVIDERS.duckduckgo, SEARCH_PROVIDERS.searxng, SEARCH_PROVIDERS.tavily]) {
    등록소.붙이기(SEARCH_SLOT, 드라이버);
  }
  return 등록소;
}

/**
 * **기본 등록소** — 제품이 실제로 쓰는 자리. 새 검색기는 여기에 붙는다.
 *
 * 없으면 슬롯이 다시 이음매가 된다: 부를 때마다 새 등록소를 만들면 있던 셋만 매번 다시 서고
 * **네 번째를 붙일 자리가 없다.** 붙일 자리가 없는 슬롯은 슬롯이 아니다.
 *
 * 모듈 수준 상태라 검사끼리 오염될 수 있다. 그래서 **검사는 이걸 안 쓴다** —
 * `검색슬롯세우기()` 가 매번 새 등록소를 주고, 검사는 자기 것을 세워 쓴다.
 * 여기는 배선(라이브) 전용이다.
 */
let 기본등록소 = null;

/** 제품이 쓰는 등록소. 처음 부를 때 있던 셋으로 세운다. */
export function 검색등록소() {
  기본등록소 ??= 검색슬롯세우기();
  return 기본등록소;
}

/**
 * 배선의 편의 한 줄 — 소비자가 쓰는 모양.
 * **빈 배열을 조용히 돌려주지 않는다.** 아무도 안 붙어 있으면 배선이 깨진 것이고,
 * 그 상태로 돌면 "검색이 원래 안 되나 보다"가 된다(없는 한계를 지어내는 자리).
 */
export function 검색드라이버(등록소 = 검색등록소()) {
  const 목록 = 등록소.드라이버(SEARCH_SLOT);
  if (!목록.length) throw new Error(`검색드라이버: 슬롯 ${SEARCH_SLOT} 에 붙은 드라이버가 0개다 — 배선을 확인할 것`);
  return 목록;
}
