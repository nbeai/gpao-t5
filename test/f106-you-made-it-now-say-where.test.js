// **F-106 · 만들어 놓고 어디에 뒀는지 말하지 않는다** (선빨강 · 라이브 6/8)
//
// ── 사용자가 밟은 것 ─────────────────────────────────────────────────────────
// 오너 지시(2026-08-12): *"실제 인간처럼 목적형 대화 테스트를 하고 문제가 발견되면
// 그 때 그 때 수정 보강."* 파일을 만들어 달라는 평범한 부탁 여덟 번에서 **여섯 번**
// 답이 파일 자리를 말하지 않았다.
// ```
// "이번달_지출정리.xlsx 파일로 정리해 놨어요."                      ← 어디에?
// "장보기 목록을 `shopping_list.txt` 파일로 저장해 뒀어요."          ← 어디에?
// "지금 작업 폴더에 저장되어 있으니, 필요하면 …"                     ← 「작업 폴더」가 어디?
// ```
// 파일은 **진짜로 생겼다**(`file(1)`: Microsoft Excel 2007+ · zip 안 XML 5개).
// 문제는 사용자가 **그것을 찾아갈 수 없다**는 것이다. 파인더를 뒤지거나 한 턴을 더 써서
// "그거 어디 있어?"를 물어야 한다. **목적이 한 걸음 앞에서 멈춘다.**
//
// ── 왜 이것이 커널의 자리인가 ────────────────────────────────────────────────
// 알맹이 판단이 아니다. **커널이 이미 아는 기계 사실**이다 — 원장에 `result.path` 가
// 통째로 들어 있다. 모델이 그 사실을 답에 안 실었을 뿐이다. 이 저장소는 같은 모양을
// 이미 한 번 물었다: **「읽고도 안 실은 파일」**(읽은 표의 숫자가 답에서 조용히 빠짐).
// 이번 것은 그 **쌍둥이**다 — 쓰고도 안 실은 자리.
//
// ── 정의역을 좁게 잡는다 (F-95 의 교훈) ──────────────────────────────────────
// `/^local\./` 로 넓게 잡았다가 참인 답을 죽인 적이 있다. 그래서 이 그물은 **셋이 동시에
// 참일 때만** 문다:
//   ① 파일 실물 손이 **실제로 썼고** 경로가 있다
//   ② 답이 그 파일을 **이름으로 부른다**(만들었다고 말하고 있다)
//   ③ 그런데 답 어디에도 그 **폴더**가 없다
// 편집 자유는 그대로다 — 전체 경로든 폴더 이름 한 마디든 **말하기만 하면 통과**다.
import assert from 'node:assert/strict';
import test from 'node:test';

import { 완료주장검증 } from '../src/kernel/l2-plan/exit-verification.js';

const 쓴영수증 = (path, text = '가나다') => ({
  actualCall: { tool: 'local.file', args: { action: 'write', path: path.split('/').pop(), text } },
  result: { path, bytes: 100, format: path.endsWith('.xlsx') ? 'xlsx' : 'txt', formatVerified: true },
  failureState: 'none',
  lifecycle: 'delivered',
});

const 집 = '/Users/yun/GPAO-T5';

// ── ① 밟은 그 답 — 이름만 부르고 자리를 안 말한다 ────────────────────────────
test('F106 ①: 파일 이름만 부르고 **어디 뒀는지 안 말하면** 되부른다 — 라이브에서 6/8 로 났다', () => {
  const v = 완료주장검증({
    reply: '이번달_지출정리.xlsx 파일로 정리해 놨어요.\n- 식비 420,000\n- 교통 80,000\n- 통신 60,000',
    receipts: [쓴영수증(`${집}/이번달_지출정리.xlsx`)],
    원장글: '',
  });
  assert.equal(v.일치, false,
    '**만들었다고만 하고 자리를 안 말했는데 그냥 지나갔다** — 사용자는 그 파일을 찾아갈 수 없다. '
    + '파인더를 뒤지거나 한 턴을 더 써서 "그거 어디 있어?"를 물어야 한다');
  assert.match(String(v.모델에게 ?? ''), /어디|자리|폴더/,
    '되부르는 말이 **무엇을 고쳐야 하는지**를 안 알려 준다 — 모델은 다음 턴에도 같은 답을 낸다');
});

// ── ② 「작업 폴더」 같은 말은 자리가 아니다 ──────────────────────────────────
//
// 라이브 8번 답이 정확히 이랬다: *"지금 작업 폴더에 저장되어 있으니…"*
// 사용자는 그 「작업 폴더」가 자기 컴퓨터의 어디인지 모른다.
test('F106 ②: **가리키는 말**만으로는 안 된다 — 「작업 폴더」는 사용자에게 자리가 아니다', () => {
  const v = 완료주장검증({
    reply: '팀원연락처.xlsx 파일을 만들었어요. 지금 작업 폴더에 저장되어 있으니 필요하면 열어 보세요.',
    receipts: [쓴영수증(`${집}/팀원연락처.xlsx`)],
    원장글: '',
  });
  assert.equal(v.일치, false,
    '**「작업 폴더」를 자리로 인정했다** — 그 말로는 아무도 못 찾아간다');
});

// ── ③ 반대편 — 말하면 통과한다. 편집 자유를 안 뺏는다 ────────────────────────
test('F106 ③-a: **전체 경로**를 말하면 통과한다', () => {
  const v = 완료주장검증({
    reply: `이번달_지출정리.xlsx 파일로 정리했어요. 자리는 ${집}/이번달_지출정리.xlsx 입니다.`,
    receipts: [쓴영수증(`${집}/이번달_지출정리.xlsx`)],
    원장글: '',
  });
  assert.equal(v.일치, true, `전체 경로를 말했는데 물었다 — 되부른 말: ${v.모델에게}`);
});

test('F106 ③-b: **폴더 이름 한 마디**만 말해도 통과한다 — 형식을 강제하지 않는다', () => {
  const v = 완료주장검증({
    reply: '이번달_지출정리.xlsx 파일로 정리해서 GPAO-T5 폴더에 뒀어요.',
    receipts: [쓴영수증(`${집}/이번달_지출정리.xlsx`)],
    원장글: '',
  });
  assert.equal(v.일치, true, `폴더 이름을 말했는데 물었다 — 되부른 말: ${v.모델에게}`);
});

// ── ④ 정의역 밖은 안 문다 ────────────────────────────────────────────────────
test('F106 ④-a: 파일을 **안 만든 턴**은 안 문다 — 회의록 초안을 글로만 준 턴이 여기다', () => {
  const v = 완료주장검증({
    reply: '8월 정기회의 회의록 초안입니다.\n참석자: 나, 김대리\n필요하면 파일로도 만들어 드릴게요.',
    receipts: [],
    원장글: '',
  });
  assert.equal(v.일치, true, `아무것도 안 만든 턴을 물었다 — ${v.모델에게}`);
});

test('F106 ④-b: 답이 그 파일을 **아예 안 부르면** 이 그물의 자리가 아니다', () => {
  // 만든 것을 말도 안 했으면 그건 다른 병이다(빈손·미고지). 여기서 겹쳐 물지 않는다.
  const v = 완료주장검증({
    reply: '정리했어요.',
    receipts: [쓴영수증(`${집}/메모.txt`)],
    원장글: '',
  });
  assert.equal(v.일치, true,
    '이름조차 안 부른 턴까지 이 그물이 물면 **정의역이 넓어져** 다른 병의 자리를 뺏는다');
});

test('F106 ④-c: **읽기만** 한 턴은 안 문다 — 쓰지 않았으면 알릴 자리도 없다', () => {
  const v = 완료주장검증({
    reply: '메모.txt 를 읽어 봤어요. 장보기 목록이 들어 있네요.',
    receipts: [{
      actualCall: { tool: 'local.file', args: { action: 'read', path: '메모.txt' } },
      result: { path: `${집}/메모.txt`, text: '우유' },
      failureState: 'none',
      lifecycle: 'delivered',
    }],
    원장글: '',
  });
  assert.equal(v.일치, true, `읽기만 한 턴을 물었다 — ${v.모델에게}`);
});

// ── ⑤ 여러 개를 만들었을 때 ──────────────────────────────────────────────────
test('F106 ⑤: 같은 폴더에 여럿 만들었으면 **폴더 한 번**으로 족하다', () => {
  const v = 완료주장검증({
    reply: `가.txt 와 나.txt 를 만들어서 ${집} 에 뒀어요.`,
    receipts: [쓴영수증(`${집}/가.txt`), 쓴영수증(`${집}/나.txt`)],
    원장글: '',
  });
  assert.equal(v.일치, true, `한 폴더를 말했는데 물었다 — ${v.모델에게}`);
});
