// **F-105 · 안 잰 0 은 0 이 아니다 — F-104 의 자가 자기 파일만 물었다** (넷째 재발)
//
// ── 무슨 일이 났나 ──────────────────────────────────────────────────────────
// 조항 ⑥ 라이브 10회차에서 「무효 0 · 실패 흔적 없음」을 얻었다. 그런데 그 근거였던
// `원장` 이 **10회차 전부 빈 배열**이었다. 대본이 이렇게 읽었다:
// ```js
// const 원장 = r.result?.ledgerEntries ?? r.ledgerEntries ?? [];   // ← 항상 []
// ```
// `/turn` 응답은 `result` 만 보내고 `ledgerEntries` 는 **세션에만** 붙는다(`server.js:1832`).
// 그래서 `실패흔적` 스크린은 **구조적으로 참이 될 수 없었다.** 「0건 발생」이 아니라 **미측정**이었고,
// 나는 그 빈 배열 위에서 「무효 0」을 적을 뻔했다. 감시자가 잡았다.
//
// ── 왜 이것이 넷째인가 ──────────────────────────────────────────────────────
// ```
// S2   부재가 안전의 증거로 읽혔다 (아무것도 안 막히니 read→자동)          제품
// J6   「폴더 N개를 훑었어요」가 「다 봤어요」로 읽혔다 (필터 전 절단)        제품
// X5   계측기 0건이 「문서 생성 없음」으로 지도·계획서에 실렸다 (F-104)      계측기
// 이번  라이브 대본의 빈 배열이 「실패 흔적 없음」으로 읽혔다               계측기
// ```
// **셋째에서 이미 구조를 세웠다** — F-104 의 「양성 대조 없이 부재를 선언하지 못한다」.
// 그런데 그 자의 정의역이 `scripts/state-probe.mjs` **한 파일**이었다
// (`test/f104-…:36` 의 import 대상이 그것 하나다). 라이브 대본은 처음부터 자의 밖이었다.
// 지도 관리자 판정: *"줄을 더하지 말고 그 정의역을 고쳐 적어라."* 그래서 이 파일이다.
//
// ── 구조 — 0 을 근거로 쓰는 자리는 **잰 양**을 함께 남긴다 ──────────────────
// 「없다」와 「안 봤다」를 사람이 구분하려 하면 언젠가 또 틀린다. 기계가 구분하게 한다:
// 0 을 근거로 쓰기 전에 **분모(잰 양)를 칸으로 남기고**, 그 분모가 0 이면 결과는
// 「없다」가 아니라 **「이 자로는 못 봤다」**로 나간다.
import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

const 뿌리 = dirname(dirname(fileURLToPath(import.meta.url)));
const 대본 = join(뿌리, 'scripts/live/h04-memory-round.mjs');

// ── ① 밟은 자리 — 원장을 **응답**에서 찾지 않는다 ────────────────────────────
//
// 이것이 이번에 실제로 밟은 돌이다. `/turn` 응답에 없는 이름을 응답에서 찾으면
// 결과는 늘 빈 값이고, 빈 값은 조용히 「없음」으로 읽힌다.
test('F105 ①: 라이브 대본이 원장을 **응답이 아니라 저장본**에서 읽는다', async () => {
  const 본문 = await readFile(대본, 'utf8');
  assert.ok(!/r\.result\?\.ledgerEntries|r\.ledgerEntries/.test(본문),
    '**원장을 `/turn` 응답에서 찾고 있다** — 응답은 `result` 만 보내고 `ledgerEntries` 는 '
    + '세션에만 붙는다(`server.js:1832`). 여기서 읽으면 **항상 빈 배열**이고, '
    + '그 빈 배열이 「실패 흔적 없음」으로 읽힌다. 2026-08-12 에 이 모양으로 열 회차를 버렸다');
  assert.match(본문, /store\.load\([^)]*\)[^\n]*ledgerEntries/,
    '원장은 `store.load(id).ledgerEntries` 로 읽어야 한다 — **저장본이 원본이다**');
});

// ── ② 0 을 근거로 쓰는 칸은 **잰 양**을 함께 남긴다 ──────────────────────────
test('F105 ②: 「실패 흔적 없음」 옆에 **분모(잰 양)** 가 있다 — 없으면 미측정과 구분이 안 된다', async () => {
  const 본문 = await readFile(대본, 'utf8');
  assert.match(본문, /원장잼\s*:/,
    '**`실패흔적: false` 만 있고 잰 양이 없다** — 그 false 가 「0건 발생」인지 「안 봤다」인지 '
    + '아무도 모른다. 원장을 몇 건 봤는지를 같은 칸에 남겨라');
  // 잰 양이 칸에만 있고 집계로 안 나오면 사람이 손으로 세게 된다 — 그때 또 틀린다.
  assert.match(본문, /원장미측정/,
    '**집계에 「미측정」 축이 없다** — 잰 양을 칸에만 두면 결국 사람이 손으로 센다. '
    + '판정표가 스스로 「이 축은 못 봤다」를 말해야 한다');
});

// ── ③ 판정하지 않는 문항을 통과/실패로 찍지 않는다 ───────────────────────────
//
// 부수로 밟은 것: `통과` 필드가 없는 원본 수집 문항이 `v.통과 ? 초록 : 빨강` 을 지나
// **10/10 빨강**으로 찍혔다. 값은 정상인데 화면이 거짓말을 했다.
test('F105 ③: `통과` 가 없는 문항은 빨강이 아니라 **원본**으로 찍힌다', async () => {
  const 본문 = await readFile(대본, 'utf8');
  assert.match(본문, /통과\s*===\s*undefined/,
    '**판정 필드가 없는 문항을 색으로 찍고 있다** — 원본 수집 문항은 통과/실패가 아닌데 '
    + '늘 빨강으로 나온다. 화면이 거짓말을 하면 사람이 화면을 안 믿게 되고, '
    + '그 다음부터는 손으로 센다');
});

// ── ④ 자의 정의역 — **라이브 대본 전부**가 이 규율 안에 있다 ─────────────────
//
// F-104 는 `state-probe.mjs` 하나만 물었다. 그래서 넷째가 났다. 여기서 넓힌다:
// **응답에 실리지 않는 이름을 응답에서 찾는** 그 한 가지 모양을 라이브 대본 전체에서 막는다.
// (완전한 자는 아니다 — 이 자는 「응답에 없는 원장을 응답에서 읽는 것」 하나를 문다.
//  다른 모양의 미측정은 여전히 사람이 봐야 한다. **과장하지 않는다.**)
test('F105 ④: 규율이 `state-probe` 한 파일이 아니라 **라이브 대본 전부**를 문다', async () => {
  const 방 = join(뿌리, 'scripts/live');
  const 파일들 = (await readdir(방)).filter((f) => f.endsWith('.mjs'));
  assert.ok(파일들.length >= 5, `라이브 대본을 못 찾았다 — ${파일들.length}개`);
  const 걸린것 = [];
  for (const f of 파일들) {
    const 본문 = await readFile(join(방, f), 'utf8');
    // 응답 객체(`r`·`res`·`resp`)에서 세션 전용 이름을 꺼내는 모양.
    if (/\b(r|res|resp|응답)\s*(\?\.)?\.(result\s*\?\.)?\s*ledgerEntries/.test(본문)) 걸린것.push(f);
  }
  assert.deepEqual(걸린것, [],
    `**세션에만 있는 \`ledgerEntries\` 를 응답에서 읽는 대본이 있다: ${걸린것.join(', ')}** — `
    + '항상 빈 배열이 나오고 그것이 「없음」으로 읽힌다. `store.load(id)` 로 읽어라');
});
