// **F-104 · 「0건」을 「없다」로 읽었다. 실제로는 「안 봤다」였다** (선빨강)
//
// 오너 2026-08-12: *"그 맨날 틀리는 자 좀 어떻게 해봐라."*
//
// ── 오늘 여섯 번 틀렸고, 세어 보니 **한 병이다** ────────────────────────────
// ```
// ① 착수 점검이 SyntaxError 로 아예 안 돌았다          자가 안 돈다
// ② 선빨강 ③-b 가 띄어쓰기에서 끊겨 뒤 토막만 봤다      자가 좁다
// ③ 선빨강 ①-b 표본 둘이 정규식에 아무것도 안 걸렸다     **0 을 통과로 읽음**
// ④ 감사 실패를 stdout 에서만 읽어 stderr 를 놓쳤다      **0 을 통과로 읽음**
// ⑤ 한국어 거절문을 'worktree' 글자로 걸러 못 잡았다     **0 을 통과로 읽음**
// ⑥ 셸 반복문이 먹혀 「표식이 어느 가지에도 없다」        **0 을 부재로 읽음**
// ⑦ 최상위 description 만 보고 「엑셀 기능 없다」         **0 을 부재로 읽음**
// ⑧ state-probe 가 「문서 만들기 (없음)」이라 냈다        **0 을 부재로 읽음**
// ```
// **공통 기계 원인 하나: 「0」이 「없다」인지 「안 봤다」인지를 자가 스스로 구분 못 한다.**
//
// 이 저장소는 **제품에서 같은 병을 이미 두 번 고쳤다**:
//   S2 *"부재가 안전의 증거로 읽혔다"*(아무것도 안 막히니 read→자동)
//   J6 *"「폴더 N개를 훑었어요」가 「다 봤어요」로 읽혔다"*(필터 전 절단)
// **제품에서 두 번 고친 병을 계측에서 계속 저질렀다.** 그래서 이번엔 고백이 아니라 구조다.
//
// ── 실제 피해 — 오보가 정본 문서 둘에 실렸다 ────────────────────────────────
// `state-probe.mjs` 의 `document-create` 검색어는 **전부 외부 라이브러리 이름**이다
// (`exceljs`·`pdf-lib`·`sheetjs`…). T5 는 라이브러리 없이 자체 구현했으므로 0건이 나왔고,
// 그 0 이 「기관 ⑧ 문서 만들기 = 있는 동사 (없음)」으로 출력돼 **지도와 계획서가 받아 적었다.**
// 실제로는 `local-file.js` 가 **진짜 xlsx 를 만든다**(zip 서명 `PK\x03\x04` 로 검사 초록).
//
// ── 구조 — 부재는 **양성 대조 없이 선언하지 못한다** ────────────────────────
// 자마다 *"이 검색법이 실제로 존재하는 것을 잡을 수 있는가"* 를 **먼저** 증명한다.
// 못 잡으면 결과는 「없다」가 아니라 **「이 자로는 못 본다」**로 나간다.
// 그러면 다음 사람이 그 줄을 부재로 읽지 않는다.
import assert from 'node:assert/strict';
import test from 'node:test';

import { 부재규격 } from '../scripts/state-probe.mjs';

// ── ① 자마다 양성 대조가 있다 ────────────────────────────────────────────────
test('F104 ①: 모든 부재 규격이 **양성 대조**를 갖는다 — 못 잡는 자로는 부재를 선언 못 한다', () => {
  assert.ok(Array.isArray(부재규격) && 부재규격.length > 0, '부재 규격을 읽지 못했다');
  for (const 규격 of 부재규격) {
    assert.ok(규격.양성대조,
      `**${규격.subject} 에 양성 대조가 없다** — 「0건」이 「없다」인지 「안 봤다」인지 `
      + '이 자가 스스로 구분하지 못한다. 오늘 이 모양으로 여섯 번 틀렸다');
    assert.ok(typeof 규격.양성대조.말 === 'string' && 규격.양성대조.말.trim(),
      `${규격.subject}: 양성 대조에 **잡혀야 할 말**이 없다`);
    assert.ok(typeof 규격.양성대조.자리 === 'string' && 규격.양성대조.자리.trim(),
      `${규격.subject}: 양성 대조에 **그 말이 실제로 있는 자리**가 없다`);
    assert.ok(typeof 규격.양성대조.왜 === 'string' && 규격.양성대조.왜.trim(),
      `${규격.subject}: 양성 대조가 **무엇을 증명하는지**가 없다 — 칸만 채우면 그것도 빈 측정이다`);
  }
});

// ── ② 양성 대조가 실제로 문다 ────────────────────────────────────────────────
//
// 규격이 칸만 갖고 그 대조가 안 걸리면 그건 또 하나의 빈 측정이다. 실물로 확인한다.
test('F104 ②: 양성 대조가 **실제 파일에서 실제로 걸린다** — 칸만 채운 게 아니다', async () => {
  const { readFile } = await import('node:fs/promises');
  const { dirname, join } = await import('node:path');
  const { fileURLToPath } = await import('node:url');
  const 뿌리 = dirname(dirname(fileURLToPath(import.meta.url)));
  for (const 규격 of 부재규격) {
    const { 말, 자리 } = 규격.양성대조;
    const 본문 = await readFile(join(뿌리, 자리), 'utf8').catch(() => null);
    assert.ok(본문 !== null, `${규격.subject}: 양성 대조 자리를 못 읽었다 — ${자리}`);
    assert.ok(본문.includes(말),
      `**${규격.subject} 의 양성 대조가 안 걸린다** — ${자리} 에 ${JSON.stringify(말)} 이 없다. `
      + '대조가 안 걸리면 그 자가 무는지 아무도 모르고, 0건이 또 부재로 읽힌다');
    // **자가 실재하는 구현을 잡는 것을 보인다** — 그래야 다른 자리의 0 이 「없다」로 읽힌다.
    // (검색어 자체를 대조로 쓰는 것은 요구하지 않는다: 진짜 부재인 주제는 그럴 대상이 없다.
    //  그 대신 **같은 검색법이 실재하는 것을 잡는다**를 보인다 — 방법이 눈이 멀지 않았다는 증명이다.)
    const 검색어 = [...(규격.생성전용 ?? [])];
    if (규격.양성대조.검색어로잡힌다 === true) {
      assert.ok(검색어.some((w) => 말.includes(w) || w.includes(말)),
      `**${규격.subject} 의 검색어가 자기 양성 대조를 못 잡는다** — 잡아야 할 말 ${JSON.stringify(말)} 이 `
      + `검색어 ${JSON.stringify(검색어.slice(0, 6))} 어디에도 안 걸린다. `
        + '이것이 오늘 「문서 만들기 (없음)」 오보를 낸 그 모양이다(검색어가 전부 외부 라이브러리 이름이었다)');
    }
  }
});

// ── ③ 밟은 오보 — 문서 만들기는 「없음」이 아니다 ────────────────────────────
test('F104 ③: `document-create` 가 T5 자체 구현 xlsx 를 **본다** — 오보를 낸 그 자리', () => {
  const 규격 = 부재규격.find((r) => r.subject === 'document-create');
  assert.ok(규격, 'document-create 규격이 없다');
  const 검색어 = 규격.생성전용 ?? [];
  const 외부라이브러리만 = 검색어.every((w) => !/표행들|xlsx로쓰기|PK|시트|sheetXml|만들수있음/.test(w));
  assert.ok(!외부라이브러리만,
    '**검색어가 전부 외부 라이브러리 이름이다** — T5 는 라이브러리 없이 자체 구현했으므로 '
    + '0건이 나오고, 그 0 이 「기관 ⑧ = 없음」으로 지도·계획서에 실렸다. '
    + `지금 검색어: ${JSON.stringify(검색어.slice(0, 8))}`);
});
