// **F-15 — 거짓 성공은 막되, 정직한 답은 살린다.**
//
// 두 축을 **한 파일에서 같이** 잰다. 하나만 세우면 다른 하나가 조용히 무너진다.
//
// ── 축 ① 정직한 답이 살아남는다 (S2 라이브에서 죽었다) ─────────────────────
// 2026-08-05 라이브(gpt-5.1 · 격리 증명 PASS): 차단 교환을 받은 모델이 453자로 정직하게 답했다.
//   "네이버 모바일 검색 결과 페이지는 내가 직접 내용을 못 읽게 막혀 있어서 …
//    대신 이렇게 해볼 수 있어: 1. 링크 열어서 나온 화면을 캡처해서 올릴 수 있으면 …"
// 런타임이 그걸 버리고 "그 사이트가 수집을 허용하지 않아요…" 로 갈아치웠다.
// `출처못댐` 이 **답의 내용을 보지 않고** 단독으로 막았기 때문이다.
//
// ── 축 ② 지어낸 답은 여전히 막힌다 (2026-08-03 실제 사고) ──────────────────
//   원장   `web.collect` 두 번 실패 · 확인 0 · 출처 0
//   T5     "국세청 … 안내를 기준으로 정리하면 아래와 같습니다" + 날짜 단정
// 그때의 처방이 `출처못댐` 단독 차단이었다. 원인은 **모델이 실패를 못 받은 것**이었고
// (차단 호출이 교환에 안 들어갔다), S2 가 그걸 고쳤다. 보상책은 이제 정직한 답만 죽인다.
//
// ── 새 판정: 문구가 아니라 **뒷받침 없는 구체 사실** ──────────────────────
// 목록을 늘리지 않는다(§4-6). 읽기가 전패했으면 T5 가 그 대상에 대해 가진 사실은
// "대상 신분 + 실패" 뿐이다. 그런데 답이 **원장 어디에도 없는 구체 사실**(두 자리 이상 수·
// 날짜·금액·비율)을 말하면, 그건 얻지 못한 것을 얻은 것처럼 말한 것이다.
// "못 읽었다"는 답에는 그런 토막이 없다. 지어낸 답에는 있다.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 읽은척차단 } from '../src/kernel/l2-plan/recovery-ladder.js';

const 실패영수증 = (over = {}) => ({
  intended: 'web.collect 실행',
  actualCall: { tool: 'web.collect', args: { request: 'https://m.search.naver.com/search.naver?query=짬뽕애호가' } },
  failureState: 'blocked',
  userSafeSummary: '그 사이트가 수집을 허용하지 않아요.',
  nextSafeAction: '주소를 다시 확인해 주시겠어요?',
  sources: [],
  ...over,
});
const 출처계약손 = ['web.collect'];

// ── 축 ① ────────────────────────────────────────────────────────────────
test('① **못 읽었다고 정직하게 말한 답은 그대로 나간다**(라이브 실제 문장)', () => {
  const 정직한답 = '네이버 모바일 검색 결과 페이지는 내가 직접 내용을 못 읽게 막혀 있어서, '
    + '링크 안쪽 화면은 지금 바로는 볼 수가 없어.\n\n대신 이렇게 해볼 수 있어:\n'
    + '1. 링크 열어서 나온 화면을 캡처해서 올릴 수 있으면(텍스트만 복붙해도 좋고), 그 부분을 그대로 적어 줘.\n'
    + '2. 특히 짬뽕애호가가 사람/가게/커뮤니티 중 뭘 가리키는지 알려 주면 더 정확히 도울 수 있어.';
  assert.equal(읽은척차단([실패영수증()], 정직한답, { 출처계약손 }), null,
    '모델이 정직하게 답했는데 런타임이 갈아치운다 — 원리 ⑤ 위반');
});

test('① 짧게 못 했다고만 말한 답도 살아남는다', () => {
  assert.equal(읽은척차단([실패영수증()], '그 페이지는 못 읽었어. 주소를 다시 줄래?', { 출처계약손 }), null);
});

test('① 대안을 제시하는 답도 살아남는다(다음 길을 주는 것이 우리 계약이다)', () => {
  const 답 = '거기는 수집이 막혀 있어서 못 봤어. 화면을 캡처해서 붙여 주면 그걸로 볼 수 있어.';
  assert.equal(읽은척차단([실패영수증()], 답, { 출처계약손 }), null);
});

// ── 축 ② ────────────────────────────────────────────────────────────────
test('② **2026-08-03 그 문장은 여전히 막힌다**(문구 목록 없이)', () => {
  const 지어낸답 = '국세청 홈택스 안내를 기준으로 정리하면 아래와 같습니다.\n'
    + '종합소득세 확정신고 기한은 2026년 5월 31일까지이고, 성실신고확인 대상자는 6월 30일까지입니다.\n'
    + '가산세는 무신고 시 20% 입니다.';
  const 결과 = 읽은척차단([실패영수증(), 실패영수증()], 지어낸답, { 출처계약손 });
  assert.ok(결과?.blocked, '읽지도 못한 자료의 내용을 사실처럼 말하는데 통과했다(P0 거짓 성공)');
  assert.match(결과.정직한답, /수집을 허용하지 않아요/, '차단은 빈 답이 아니다 — 정직한 사실을 준다');
});

test('② 문구가 무엇이든 **뒷받침 없는 구체 사실**이면 막힌다(예문 규칙이 아니다)', () => {
  // `내용서술` 정규식에 없는 표현으로만 쓴다 — 목록에 기대지 않는지 확인한다.
  const 답 = '해당 페이지 기준 평점은 4.7 이고 리뷰는 1,284건이야. 주차는 2시간 무료.';
  assert.ok(읽은척차단([실패영수증()], 답, { 출처계약손 })?.blocked,
    '문구는 안 걸리지만 얻지 못한 구체 사실을 말했다');
});

test('② 예전 문구 판정(내용서술)도 그대로 문다(기존 그물 유지)', () => {
  assert.ok(읽은척차단([실패영수증()], '열어 보니 이런 내용이더라.', { 출처계약손 })?.blocked);
});

// ── 경계: 게이트가 과잉으로 번지지 않는다 ────────────────────────────────
test('③ 실제로 읽은 것이 있으면 서술은 근거가 있다 — 안 막는다', () => {
  const 성공 = { intended: 'web.collect 실행', actualCall: { tool: 'web.collect', args: {} },
    failureState: 'none', userSafeSummary: '읽었어요.', sources: ['https://a.example'] };
  assert.equal(읽은척차단([성공, 실패영수증()], '평점은 4.7 이야.', { 출처계약손 }), null);
});

test('③ 사용자가 준 숫자를 되풀이하는 것은 지어낸 것이 아니다', () => {
  // 원장(호출 인자)에 있는 값은 뒷받침이 있다 — 대조 대상은 원장 전체다.
  const r = 실패영수증({ actualCall: { tool: 'web.collect', args: { request: '2026년 5월 31일 기한 확인' } } });
  assert.equal(읽은척차단([r], '네가 말한 2026년 5월 31일 기한은 아직 확인 못 했어.', { 출처계약손 }), null);
});
