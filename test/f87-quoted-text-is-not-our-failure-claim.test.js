// ── F-87 · **인용 안의 말은 T5 의 주장이 아니다** (콘솔 라이브 실측 2/2 · 2026-08-12) ──
//
// `exit-verification.js` 의 「거짓 실패도 회수한다」 갈래가 **멀쩡한 답을 회수했다.**
// 여는 조건인 원장 사실 둘(바뀐 것 > 0 · 실패 흔적 0)은 맞았는데, 마지막 자를
// **답 전문**에 그대로 물려서 답이 **옮겨 온 자료** 안의 낱말까지 T5 자신의 실패 선언으로 읽었다.
//
//   회차 A(팔식당 후기 · 손 2건 전부 ok)
//     답 안의 문장  "처음 가도 실패 없이 먹을 수 있다"는 톤일 가능성이 큼   ← 후기 내용이다
//     진단          "…바뀐 것이 2개 있고 실패한 걸음은 하나도 없다. 답은 실패·불가능이라고…"
//   회차 B(전세사기 특약 · 손 4건 전부 ok · 110.8초)
//     최종 답에는 그 낱말이 아예 없는데 진단이 떴다 → 중간 답이 걸려 회수되고 다시 쓰였다.
//     전세 특약 문구는 대부분 "…할 수 없다" 꼴이다.
//
// **F-85 와 같은 계열이다** — 일어난 것을 안 일어났다고 판정한다. 거기서는 표기(NFD/NFC)가
// 원장을 못 읽게 했고, 여기서는 **자리**(인용인가 우리 말인가)를 안 봐서 남의 말을 우리 말로 읽는다.
//
// 고치는 축은 **문구가 아니라 구조**다. 같은 파일 `안돌린명령`(:313)이 이미 그 길을 밟았다 —
// *"대신 **구조**로 본다: 셸이라고 **모델이 스스로 표시한** 코드블록만."* 여기도 같다:
// 따옴표·코드블록·인용줄은 **모델이 스스로 「이건 옮겨 온 말」이라고 표시한 자리**다.
// 낱말을 빼거나 예외 목록을 붙이지 않는다(F-12 가 배제한 길).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 완료주장검증 } from '../src/kernel/l2-plan/exit-verification.js';

/** 자료를 가져오는 손 — 읽기·목록이 아니므로 `바꾼개수` 가 1로 센다(원장 사실 그대로). */
const 가져온손 = (query) => ({
  failureState: 'none',
  actualCall: { tool: 'web.search', args: { action: 'search', query } },
  result: { items: [{ title: query, snippet: '…' }] },
});
const 성공쓰기 = (path) => ({
  failureState: 'none',
  actualCall: { tool: 'local.file', args: { action: 'write', path } },
  result: { path },
});
const 성공읽기 = (path) => ({
  failureState: 'none',
  actualCall: { tool: 'local.file', args: { action: 'read', path } },
  result: { path, text: '내용' },
});
const 막힘 = (tool, action) => ({
  failureState: 'blocked', actualCall: { tool, args: action ? { action } : {} }, result: {},
});

test('① 회차 A: 따옴표 안의 「실패」는 후기 내용이다 — 우리 실패 선언이 아니므로 안 문다', () => {
  const r = 완료주장검증({
    reply: '네이버 플레이스 후기를 살펴봤어요.\n\n'
      + '- 방문자 후기 톤: "처음 가도 실패 없이 먹을 수 있다"는 톤일 가능성이 큼\n'
      + '- 재방문 의사를 밝힌 후기가 여러 건이었어요.',
    receipts: [가져온손('팔식당'), 가져온손('팔식당 후기')],
  });
  assert.equal(r.사용자에게, true,
    `**멀쩡한 답이 회수됐다** — 인용 안의 낱말을 우리 주장으로 읽었다: ${r.모델에게}`);
});

test('② 회차 B: 인용한 계약 특약 문구의 「…할 수 없다」도 안 문다', () => {
  const r = 완료주장검증({
    reply: '요즘 권하는 특약을 정리했어요.\n\n'
      + '1. "임대인은 잔금일 다음 날까지 근저당권 등 어떠한 담보물권도 설정할 수 없다"\n'
      + '2. "위 사항 위반 시 임차인은 계약을 해제할 수 있다"',
    receipts: [가져온손('전세사기 특약'), 가져온손('전세 특약 문구')],
  });
  assert.equal(r.사용자에게, true, `인용한 특약 문구가 우리 실패 선언으로 읽혔다: ${r.모델에게}`);
});

test('②-2 코드블록·인용줄도 같은 자리다 — 모델이 스스로 옮겨 온 말이라고 표시한 곳', () => {
  const 코드 = 완료주장검증({
    reply: '원문은 이랬어요.\n\n```\n본 계약은 해지할 수 없다\n```\n\n정리하면 해지 제한 조항이에요.',
    receipts: [가져온손('약관')],
  });
  assert.equal(코드.사용자에게, true, `코드블록 안의 인용을 우리 주장으로 읽었다: ${코드.모델에게}`);

  const 인용줄 = 완료주장검증({
    reply: '원문을 그대로 옮기면\n\n> 임차인은 이를 거절할 수 없다\n\n라고 돼 있어요.',
    receipts: [가져온손('약관')],
  });
  assert.equal(인용줄.사용자에게, true, `인용줄을 우리 주장으로 읽었다: ${인용줄.모델에게}`);
});

test('③ 진짜 거짓 실패는 그대로 잡힌다 — 실물을 세워 놓고 「만들지 못했어요」', () => {
  const r = 완료주장검증({
    reply: '죄송해요, 그 파일은 만들지 못했어요. 지금은 불가능해요.',
    receipts: [성공쓰기('/방/보고서.md')],
  });
  assert.equal(r.사용자에게, false, '**그물이 하는 일이 사라졌다** — 수리가 아니라 파괴다');
  assert.match(String(r.모델에게 ?? ''), /바뀐|성공/, `원장 사실이 모델에게 안 간다: ${r.모델에게}`);
});

test('③-2 인용이 섞여 있어도 우리 말 자리의 실패 선언은 잡힌다 — 인용은 은신처가 아니다', () => {
  const r = 완료주장검증({
    reply: '원문에는 "환불은 요청할 수 없다"고 적혀 있어요.\n\n'
      + '그런데 저는 그 페이지를 여는 데 실패했어요.',
    receipts: [성공쓰기('/방/정리.md')],
  });
  assert.equal(r.사용자에게, false, '인용 밖의 실패 선언을 놓쳤다 — 따옴표가 빠져나가는 문이 됐다');
});

test('③-3 답 전체가 인용 하나면 걷어낼 것이 없다 — 원문 그대로 잰다', () => {
  const r = 완료주장검증({
    reply: '"그 작업은 실패했어요. 지금은 불가능해요."',
    receipts: [성공쓰기('/방/보고서.md')],
  });
  assert.equal(r.사용자에게, false, '따옴표로 답 전체를 감싸면 그물이 통째로 열린다');
});

test('④ 바뀐 것이 0인 턴은 여전히 안 건드린다 — 커널은 알맹이를 재지 않는다', () => {
  const r = 완료주장검증({
    reply: '파일을 읽어봤는데 그 항목은 찾을 수 없었어요.',
    receipts: [성공읽기('/방/원장.txt')],
  });
  assert.equal(r.사용자에게, true);
});

test('⑤ 실패 흔적이 원장에 있는 턴은 여전히 안 문다 — 정직한 실패 보고', () => {
  const r = 완료주장검증({
    reply: '읽기가 실패해서 못 끝냈어요.',
    receipts: [막힘('local.file', 'read')],
  });
  assert.equal(r.사용자에게, true, '정직한 실패 보고를 되돌렸다');
});

test('⑥ 정직한 미완 고지는 그대로 나간다 — 부분 완료 보고', () => {
  const r = 완료주장검증({
    reply: '결과는 만들었는데 전송은 실패해서 아직 못 보냈어요.',
    receipts: [성공쓰기('/방/결과.md'), 막힘('telegram.send')],
  });
  assert.equal(r.사용자에게, true, '부분 완료의 정직한 보고를 되돌렸다 — 반대 방향의 거짓');
});
