// **F-111 · 이미 떠 있는 앱을 켜려 하자 「막혔다」가 됐다** (선빨강)
//
// ── 오너가 실제로 밟았다 (2026-08-13 · 세션 0d9dcae7) ──────────────────────
// ```
// [윤]  내 카톡 열어봐
// [T5]  카카오톡 앱 직접 여는 건 지금 이 환경에선 막혀 있어서 제가 바로 실행까지는 못 했어요
// [윤]  뭐가 안 떠있어. 지금 떠있는 상태고 대화목록도 보이는데
//  …
// [윤]  아이 씨발... 진짜 할줄 아는게 머야.
// [T5]  이건 현재 권한/환경 때문에 막혀 있습니다. … 물리적으로 못 합니다.
// ```
// **T5 는 손을 쥐고 있었다.** `desktop.act` 에 `launch`·`focus`·`click`·`scroll` 이 다 있고,
// 실제로 승인 카드까지 떴다. 그런데 「막혔다」고 답하고 사용자에게 떠넘겼다.
//
// ── 원장이 말하는 진짜 이유 ────────────────────────────────────────────────
// ```
// desktop.act {"action":"launch","app":"KakaoTalk"} → **failed**
//   "요청은 받아들여졌는데, 다시 봤을 때 그 상태가 아니었어요."
// ```
// 카톡은 **이미 떠 있었다.** 창이 셋이나 있었고(원장의 다음 걸음이 그걸 봤다),
// 다만 **다른 Space** 에 있어서 `frontmost` 가 아니었다.
//
// `도달했나()` 가 `launch` 를 이렇게 잰다(`desktop-act-tool.js:199-203`):
// ```js
// if (행동 === 'focus' || 행동 === 'launch') return 앞.includes(대상) || 대상.includes(앞);
// ```
// **`focus` 와 같은 자로 잰다** — 즉 「켜졌나」를 **「앞에 왔나」**로 묻는다.
// 그런데 바로 아래 이 파일의 주석이 스스로 반대를 말한다:
// > *"**켠 것과 앞에 둔 것은 다른 일이다.** 뭉뚱그리면 사용자는 앞에 왔다고 듣고
// >  화면을 보고 어리둥절해진다(cua 는 켜고도 앞으로 안 올린다)."*
//
// **말은 갈라 놓고 자는 안 갈랐다.**
//
// ── 왜 이것이 나비효과 자리인가 ────────────────────────────────────────────
// 이 한 줄이 서면 살아나는 것: **이미 실행 중인 모든 앱**. 사용자는 대개 앱을 켜 놓고
// 부탁한다 — 카톡·슬랙·노션·엑셀 전부 같은 자리다. 지금은 그 전부가 「막혔다」로 나온다.
// 그리고 `launch` 가 성공하면 그 영수증에 실린 `다음수단: focus` 가 모델에게 간다
// (`:866`). 지금은 실패라 그 길이 안 보인다 — **손 관리자가 말한 「길을 안 준 문장이
// 벽이 된다」가 여기서 두 번째로 났다**(첫 번째는 2026-08-05, 같은 파일 주석에 있다).
import assert from 'node:assert/strict';
import test from 'node:test';

import { 목표도달 } from '../src/runtime/desktop-act-tool.js';

// 실제 계약은 `목표도달(행동, args, 후)` 이고 `후` 는 **관측 요약**이다
// (`대조할값[행동](본것, args)` 의 결과). 검사가 그 모양을 안 쓰면 무엇을 재는지 알 수 없다.
const 요약 = (본것) => ({
  창수: (본것.windows ?? []).length,
  frontmost: 본것.frontmost?.name ?? null,
});
const 도달했나 = (행동, app, 본것) => 목표도달(행동, { app }, 요약(본것));

// 오너 화면 그대로 — 카톡 창 셋이 **다른 Space** 에 있고, 앞에 있는 것은 크롬이다.
const 본것 = {
  frontmost: { name: 'Google Chrome' },
  windows: [
    { app: 'KakaoTalk', title: '카카오톡', offScreen: true },
    { app: 'KakaoTalk', title: 'Absolute. M.', offScreen: true },
    { app: 'KakaoTalk', title: 'Kim Namsu', offScreen: true },
    { app: 'Google Chrome', title: 'GPAO-T5 · Work Chat' },
  ],
};

// ── ① 밟은 그 자리 ──────────────────────────────────────────────────────────
test('F111 ①: **커널은 「켜졌나」를 다시 재지 않는다** — 드라이버가 확인한 것을 뒤집지 않는다', () => {
  const 결과 = 도달했나('launch', 'KakaoTalk', 본것);
  assert.equal(결과, null,
    '**이미 떠 있는 앱의 launch 가 실패로 찍혔다** — 앱은 실행 중이고 창이 셋이나 있다. '
    + '다만 다른 Space 라 frontmost 가 아닐 뿐이다. 이 실패를 모델이 「막혔다」로 읽고 '
    + '사용자에게 떠넘겼다(오너 라이브 2026-08-13). '
    + '이 파일 주석이 스스로 적었다 — **"켠 것과 앞에 둔 것은 다른 일이다."**');
});

// ── ② 켜지지 않은 앱은 그대로 실패다 ────────────────────────────────────────
test('F111 ②: **안 떠 있는 앱도 커널은 안 잰다** — 그 판정은 드라이버 몫이다', () => {
  // 여기서 `false` 를 내면 그것이 곧 드라이버를 뒤집는 것이다. 재는 자가 둘이면 갈린다.
  assert.equal(도달했나('launch', 'Slack', 본것), null,
    '**커널이 launch 를 다시 쟀다** — 드라이버의 `list_apps.running` 이 더 정확하고, '
    + '커널이 창 목록으로 뒤집으면 다른 Space·창 없는 앱에서 거짓 실패가 난다');
});

// ── ③ focus 는 예전 그대로 — 앞에 와야 성공이다 ─────────────────────────────
//
// 여기가 갈라지는 지점이다. `focus` 의 목적은 **앞에 두는 것**이고, `launch` 의 목적은
// **켜는 것**이다. 같은 자로 재면 둘 중 하나는 반드시 거짓말을 한다.
test('F111 ③: **focus 는 앞에 와야 성공**이다 — 켜진 것만으로는 아니다', () => {
  assert.equal(도달했나('focus', 'KakaoTalk', 본것), false,
    'focus 가 무르게 됐다 — 다른 Space 에 있는 창을 「앞으로 띄웠어요」라고 말하면 '
    + '사용자는 화면을 보고 어리둥절해진다');
  assert.equal(도달했나('focus', 'Google Chrome', 본것), true, '앞에 있는 앱의 focus 가 실패로 나온다');
});

// ── ④ 모르면 모른다고 한다 ──────────────────────────────────────────────────
test('F111 ④: 창 목록을 **못 본 경우**는 실패가 아니라 「모름」이다', () => {
  assert.equal(목표도달('focus', { app: 'KakaoTalk' }, { frontmost: null }), null,
    '**관측 실패를 행동 실패로 바꿨다** — 이 파일이 이미 네 번 밟았다고 적어 둔 병이다');
});
