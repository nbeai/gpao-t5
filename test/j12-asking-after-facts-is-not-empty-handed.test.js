// J12 — **파악을 마친 물음은 빈손이 아니다.**
//
// 선빨강(사슬 22개 · 35턴 실측 · 기준선 §7-m·§7-n): 같은 발화·같은 걸음 순서인데 답글의
// 물음표 하나로 되부름이 갈렸다. 손을 불러 목록을 정확히 답하고 "먼저 볼 파일 있어?"를
// 붙인 답이 「빈손」으로 읽혀 재생성이 돌았고, 그 재생성은 **한 번도 채택되지 않았다**(0/35).
// 오너 정의(2026-08-14 · 말귀): *"되물음은 감점이 아니다. 파악 없이 묻는 것이 떠넘김이다."*
//
// 수리는 **끄는 문 하나**다(규칙 자체는 불변 · 인자 없이 부르는 자리는 한 글자도 안 바뀐다).
// 이 검사가 무는 것은 그 문의 계약과 **반대편 보호 둘**이다 — 껍데기 걸음·약속 종결.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { 빈손으로끝났나 } from '../src/kernel/l2-plan/exit-verification.js';
import { 빈손으로돌아왔나 } from '../src/kernel/l0-evidence/working-state.js';

const 뿌리 = join(dirname(fileURLToPath(import.meta.url)), '..');

const 사실을댄물음 = '시작문서 폴더 안에는 네 개가 있어요. README.md · 현재상황.md … 먼저 같이 보고 싶은 파일 있어?';

test('① 사실을 가져온 걸음이 있으면 그 턴의 물음은 빈손이 아니다', () => {
  assert.equal(빈손으로끝났나(사실을댄물음, null, { 심문은빈손아님: true }), false,
    '파악을 마치고 던진 최소 질문이 빈손으로 잡힌다 — 「계속 가려면 안 물어야 한다」가 된다');
});

test('② 반대시험: 걸음이 껍데기면 같은 물음이 여전히 빈손이다', () => {
  // 손이 "메뉴뿐이라 알맹이가 없었어요"(읽은상태 shell)로 돌아온 걸음은 사실을 가져온 것이
  // 아니다 — F-107 이 세운 자를 그대로 쓴다. 이 보호가 빠지면 껍데기 턴이 조용해진다.
  const 껍데기 = { failureState: 'none', result: { 읽은상태: 'shell' } };
  assert.equal(빈손으로돌아왔나(껍데기), true, '자가 껍데기를 못 알아본다');
  assert.equal(빈손으로끝났나(사실을댄물음, null, { 심문은빈손아님: false }), true,
    '껍데기 걸음뿐인 턴의 물음이 통과했다');
});

test('③ 반대시험: 약속 갈래는 안 꺼진다 — 사실을 가져와도 예고로 끝내면 빈손이다', () => {
  // turn.js:2811 이 기록한 회귀(browser.observe 1건 성공 + "이어서 검색해 볼게요"가
  // 조용해짐)를 다시 열지 않는다. 심문을 꺼도 미래 종결 판정으로 내려가야 한다.
  assert.equal(빈손으로끝났나('정산 폴더를 봤어요. 이어서 나머지도 확인해 볼게요', null, { 심문은빈손아님: true }), true,
    '심문을 끄면서 약속 갈래까지 같이 껐다 — 측정 밖의 수리다');
});

test('④ 기본값은 불변 — 인자 없이 부르는 자리는 한 글자도 안 바뀐다', () => {
  // r3 의 ⑬ 봉인(후보 다섯 받고 열다섯 되묻기)과 turn.js:2740 이 이 기본값 위에 서 있다.
  assert.equal(빈손으로끝났나(사실을댄물음), true, '기본 규칙이 바뀌었다 — r3 봉인이 풀린다');
  assert.equal(빈손으로끝났나('정산을 봤어요. 지금 볼까요?'), true);
});

test('⑤ 만든 문을 실제로 쓴다 — turn.js 가 그 옵션에 「사실을 가져온 걸음」을 넘긴다', async () => {
  // 만든 것과 닿은 것은 다르다. 호출부가 안 쓰면 이 수리는 라이브에서 0이다.
  const turn = await readFile(join(뿌리, 'src/kernel/turn.js'), 'utf8');
  assert.match(turn, /const 사실을가져온걸음 = 부른것들\.some\(\(r\) => \(r\.failureState \?\? 'none'\) === 'none' && !빈손으로돌아왔나\(r\)\)/,
    '「사실을 가져온 걸음」을 F-107 의 자로 세는 줄이 없다');
  assert.match(turn, /빈손으로끝났나\(답글원문, null, \{ 심문은빈손아님: 사실을가져온걸음 \}\)/,
    '걸음이말하는미달이 그 문을 안 쓴다 — 만든 것이 닿지 않았다');
  // :2822(걸음 0)와 :2740(후보 미개봉)은 이번 범위 밖 — 그대로 있어야 한다.
  assert.match(turn, /빈손으로끝났나\(답글원문, \{ 가져온것: 0 \}\)/, '걸음 0 입구가 바뀌었다');
  assert.match(turn, /const 목적에안닿은답 = 빈손으로끝났나\(답글원문\) \|\| 미완료를밝혔나\(답글원문\)/,
    ':2740(후보 미개봉 봉인)이 바뀌었다 — 이번 표적이 아니다');
});
