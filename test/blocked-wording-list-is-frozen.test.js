// **어법 목록을 얼린다** — 오너 결정 2026-08-16: *"외우기 금지하자."*
//
// ── 왜 이 검사가 있나 ──────────────────────────────────────────────────────
//
// `executionBlock` 은 「이 실패가 우리 샌드박스 때문인가」를 **stderr 문자열 어법**으로 가른다.
// 그 목록이 세 번 자랐다:
//   ① `Permission denied` 계열        ② `Failed to open '<자리>'`(§7-ai)   ③ 대조 불능(§7-am)
// 그리고 세 번 자라고도 샌다 — 실측 미탐: `sqlite3 … unable to open database file`.
//
// `sandbox.js` 첫 문단이 이 저장소의 답을 이미 적어 뒀다:
//   *"명령이 위험한지 알아맞히지 않는다. 돌려 보고 안다. **목록은 항상 뚫린다.**"*
// 어법 갈래는 그 원칙의 예외로 자라고 있었다. 지우지는 못한다 — 사본 재실행으로 대체하려
// 했으나 **cwd 밖에 쓰는 명령**(`cd ..`·절대경로)에서 사본이 충실하지 않아 오늘 되던 것이
// 죽는 것을 손 관리자가 기계로 확인했다(§7-aq). 그래서 지우는 대신 **얼린다.**
//
// ── 이 검사가 무는 것 ──────────────────────────────────────────────────────
// 이 자리에 **새 말투를 한 줄 더 넣으면 빨개진다.** 그때 할 일은 줄을 늘리는 게 아니라
// 위로 올리는 것이다 — 새 말투가 나왔다는 사실 자체가 「어법으로는 안 된다」의 증거다.
//
// ⚠️ 이 검사는 **문구를 지키는 검사가 아니다.** 기존 정규식을 고치는 것(포획 오류 수정 등)은
//    막지 않는다 — 세는 것은 **갈래의 수**다. 목록이 자라는 것만 문다.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

/** 주석을 걷어낸다 — 주석 안의 `/…/` 는 정규식이 아니다(밟았다: 22개 중 8개가 주석이었다). */
function 주석없이(src) {
  return src.replace(/\/\*[\s\S]*?\*\//g, '').split('\n')
    .map((줄) => 줄.replace(/(^|\s)\/\/.*$/, '$1')).join('\n');
}

/** `executionBlock` 본문에서 「막힘 어법」을 가르는 갈래의 수. 정규식 리터럴로 센다. */
async function 어법갈래수() {
  const src = 주석없이(await readFile(new URL('../src/runtime/terminal-run.js', import.meta.url), 'utf8'));
  const 시작 = src.indexOf('export function executionBlock');
  assert.notEqual(시작, -1, 'executionBlock 을 못 찾았다 — 이 검사가 무는 자리가 사라졌다');
  // 끝은 **다음 최상위 선언**이다. 특정 함수 이름을 박으면 그 함수가 옮겨질 때 검사가
  // 조용히 파일 끝까지 세게 된다(밟았다 — `redactEnv` 가 `export` 라 못 찾고 -1 이 됐다).
  const 끝 = src.indexOf('\nexport function ', 시작 + 1);
  assert.notEqual(끝, -1, 'executionBlock 다음의 최상위 선언을 못 찾았다 — 검사를 다시 겨눠라');
  const 본문 = src.slice(시작, 끝);
  return [...본문.matchAll(/\/(?![/*])((?:[^/\\\n[]|\\.|\[[^\]\n]*\])+)\/[a-z]*/g)].map((m) => m[0]);
}

// 얼린 값 = **현재값 그대로**(직접 세었다). **이 숫자를 올리는 수리는 이 저장소가 그만두기로 한
// 그 수리다.** 여유를 한 칸이라도 두면 동결선이 안 문다 — 처음에 12 로 잡았다가 갈래를 하나
// 더해도 초록인 것을 양성 대조로 잡았다(빈 측정을 통과 증거로 세우지 않는다).
const 얼린갈래수 = 11;

test('어법 목록이 자라지 않는다 — 새 말투가 나오면 줄을 늘리지 말고 위로 올린다', async () => {
  const 갈래 = await 어법갈래수();
  assert.ok(갈래.length <= 얼린갈래수,
    `**「막혔다」를 가르는 어법 갈래가 ${얼린갈래수} → ${갈래.length} 로 늘었다.**\n`
    + `${갈래.map((r, i) => `  ${i + 1}. ${r}`).join('\n')}\n\n`
    + '오너 결정(2026-08-16): *"외우기 금지하자."* 이 목록은 세 번 자랐고 세 번 다 다시 샜다.\n'
    + '`sandbox.js` 첫 문단: *"목록은 항상 뚫린다."*\n'
    + '**새 말투를 만났다는 것은 어법으로는 안 된다는 증거다.** 줄을 늘리지 말고 위로 올려라 —\n'
    + '판정을 어법이 아니라 **밟은 사실**로 옮기는 설계가 §7-ao~aq 에 재료까지 적혀 있다\n'
    + '(선반에 올려 둔 사본 재실행 · 되살아나는 조건은 「모델이 cwd 를 명시로 넘기게 배선이 바뀌면」).');
});

test('반대시험 — 갈래를 줄이는 것은 막지 않는다 (동결은 상한이지 고정이 아니다)', async () => {
  const 갈래 = await 어법갈래수();
  assert.ok(갈래.length > 0, 'executionBlock 에서 정규식을 하나도 못 찾았다 — 세는 자가 깨졌다');
  // 상한(`<=`)으로 문다. 어법을 **덜어내는** 수리는 이 검사를 지나야 한다 — 그게 가려는 방향이다.
  assert.ok(얼린갈래수 >= 갈래.length,
    '얼린 값이 현재값보다 작다 — 동결선을 내렸으면 이 상수도 같이 내려야 한다');
});
