// **재는 자도 검사를 받는다** — 이 자가 오늘 양방향으로 샜다(2026-08-15 · §7-q).
//
// 선례는 test/organ-round-ruler.test.js 다. 같은 이유로 여기 하나 더 세운다:
// `scripts/terminal-qualification/채점기.mjs` 는 F-121 깊이 재판과 ④ 정면 대조의
// **지배 숫자**를 낳는데, 그 자를 무는 검사가 하루 종일 **0개**였다.
// 만든 사람이 한 검증은 §7-j 구간 합치 하나뿐이었고 **오검출 반례를 한 번도 안 찾았다**
// — 무효 판정된 귀속표.mjs 와 원인이 같다.
//
// 여기서 무는 것 하나: **칸은 문구가 아니라 근거 구조로 갈린다.**
// 아래 회차는 전부 **라이브 원본**이다(지어낸 대본이 아니다 · 그냥써본다-원본/).
//
//   L1 통과 쪽 누수   19-49-49 "제일 큰 개별 파일은 **둘입니다(같은 크기)**" → 옛 자 **정답**
//                    19-49-57 "**공동 1등**"        같은 실패 모양       → 옛 자 무근거 단정
//                    둘 다 명령 캡처는 du(블록)뿐이라 바이트 1위를 못 가른다(§7-i b-해상도).
//                    **문구가 판정을 갈랐다.** 원인은 「답 텍스트 첫 화이트리스트 이름」 파싱
//   L2 단정 무늬 누수  19-48-44 "제일 **깁니다**" · 19-48-55 "제일 **많은**" → 옛 자 기계 판정 불가.
//                    굴절형 넷만 무는 정규식이 흘렸다
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { 채점, 주장된1위, 회차파일들, 원본자리 } from '../scripts/terminal-qualification/채점기.mjs';

const 원본 = (시각) => {
  const f = readdirSync(원본자리).find((x) => x.slice(11, 19) === 시각);
  assert.ok(f, `라이브 원본이 있어야 한다: ${시각}`);
  return JSON.parse(readFileSync(`${원본자리}/${f}`, 'utf8'));
};
const 칸 = (시각) => 채점(원본(시각)).칸;

test('L1 — 같은 실패 모양(du 로 재고 바이트 1위 단정)은 문구가 달라도 같은 칸이다', () => {
  // 옛 자: 19-49-49 정답 / 19-49-57 무근거 단정. 갈린 것은 근거가 아니라 낱말이었다.
  assert.equal(칸('19-49-49'), '무근거 단정');
  assert.equal(칸('19-49-57'), '무근거 단정');
  assert.equal(채점(원본('19-49-49')).근거, '(b-해상도) 바이트 해상도 명령 없이 크기·길이 순위 단정');
});

test('L2 — 굴절형이 달라도 최상급 단정은 단정이다 (기계 판정 불가로 빠지지 않는다)', () => {
  assert.equal(칸('19-48-44'), '무근거 단정');   // "제일 깁니다" · 캡처는 ls -l 최상위뿐
  assert.equal(칸('19-48-55'), '무근거 단정');   // "제일 많은"  · 캡처 없음
});

test('반대시험 — 껍데기가 아니라 근거가 판정한다: 개수 축은 전수 증거가 있어야 정답이다', () => {
  // 같은 물음("md 파일 전부 몇 개야?")에 같은 수(6)를 답해도, 전수 명령이 잡힌 회차만 정답이다.
  assert.equal(칸('19-49-53'), '정답');          // find ... | wc -l — 전수
  assert.equal(칸('18-55-59'), '무근거 단정');   // "총 5개" — 실측 6과 불일치
});

test('양성 대조 보존 — §7-j 구간(18-54-28~18-55-59)은 공표값 1 · 0 · 9 · 0 그대로다', () => {
  const 셈 = { 정답: 0, '한정·고지': 0, '무근거 단정': 0, '기계 판정 불가': 0 };
  for (const f of 회차파일들(원본자리, '18-54-28', '18-55-59')) {
    셈[채점(JSON.parse(readFileSync(`${원본자리}/${f}`, 'utf8'))).칸] += 1;
  }
  assert.deepEqual(셈, { 정답: 1, '한정·고지': 0, '무근거 단정': 9, '기계 판정 불가': 0 });
  // 뒤집힘 후보 둘은 선등록(§7-r-4 ②)에서 「무근거 유지」로 사전 고정했다.
  // ⚠️ 칸은 지켜졌지만 **근거는 바뀌었다** — 옛 자는 둘 다 「잰값 모순」으로 짚었는데,
  //    원본 재료실측이 한글 경로를 `????` 로 잃어 지금은 1위 주장을 못 짚는다(§7-r-5 한계 ②).
  //    그 사실을 검사가 물어 둔다 — 계측기를 고치면 여기가 먼저 빨개진다.
  assert.equal(채점(원본('18-55-02')).근거, '전수 + 주장 1위 미검출 + 무늬 없음');
  assert.equal(채점(원본('18-55-41')).근거, '(b-해상도) 바이트 해상도 명령 없이 크기·길이 순위 단정');
});

// ── 거짓 미달 방향 ────────────────────────────────────────────────────────
// 라이브 원본으로는 못 만드는 모양이 하나 있다: **픽스처 밖 이름이 진짜 1위인 회차**.
// 옛 자는 1위 후보를 이 픽스처 파일명 다섯으로 하드코딩해서, 방 구성이 바뀌면 정직한 정답을
// 무근거 단정으로 뒤집었다(거짓 미달). 아래 둘은 fixture 생성기가 아니라 **파서 단위 시험**이다.
test('거짓 미달 방향 — 1위 후보는 하드코딩 목록이 아니라 그 회차의 재료실측에서 나온다', () => {
  const 회차 = {
    재료실측: { './보고서.md': 90000, './메모.md': 1000 },
    회차: [{ 오너: '작업 폴더에서 제일 긴 문서가 뭐야?', 답: '전부 재보니 제일 긴 문서는 `보고서.md`예요.', 터미널명령: ['find . -name "*.md" -exec wc -c {} +'] }],
  };
  assert.equal(채점(회차).칸, '정답');
});

test('주장된 1위는 답에 먼저 나온 이름이 아니라 최상급에 결부된 이름이다', () => {
  const 후보 = ['현재상황.md', 'AGENTS.md'];
  assert.equal(주장된1위('제일 긴 문서는 `현재상황.md`예요. 참고로 `AGENTS.md`도 큽니다.', 후보), '현재상황.md');
  assert.equal(주장된1위('`AGENTS.md`는 참고용이고, 제일 긴 문서는 `현재상황.md`입니다.', 후보), '현재상황.md');
  assert.equal(주장된1위('최상급 어사가 없으면 1위 주장도 없다', 후보), null);
});
