// ② 집계 범위 — **순위 단정은 안 잰 자리를 안다** (선등록 §7-ay-2 · 선빨강 2026-08-16)
//
// 라이브 실물(집계-선빨강-회차1.json · ccf33e2f): "제일 두꺼운 문서 하나만" →
// 모델은 목록(관측)까지 하고 무게는 **하나도 안 잰 채** `AGENTS.md`(16,051B)라 단정.
// 진값은 시작문서/T5-비전과-성능철학.md **45,534B**. 터미널 명령 0줄.
//
// 장치는 이미 있다 — 완료주장검증의 「반만 읽고 총을 말한다」(exit-verification.js:695).
// 귀가 세 곳에서 멀 뿐이다(§7-ay-1): 파일 read 영수증만 · /총|전체|합계/ 만 · childCount 미연결.
// 닫는 문장(영역): **"요구가 순위·집계인데 원장에 안 잰 자리가 남아 있으면,
// 손은 답을 확정하기 전에 그 사실을 안다."** 사건("wc 대신 find") 아님.
//
// 이 검사는 채점기.mjs 를 안 쓴다(§7-ay-4 자 결정 ①). 무늬 자 없음 — 원장 기계 사실만.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 완료주장검증 } from '../src/kernel/l2-plan/exit-verification.js';

/** 라이브 회차1 의 원장 모양 그대로 — 목록만 있고(크기 칸 없음 · childCount 만) 잰 값이 없다. */
const 목록영수증 = () => ({
  failureState: 'none',
  actualCall: { tool: 'local.file', args: { action: 'list', path: '/방/작업' } },
  result: {
    path: '/방/작업',
    items: [
      { name: 'AGENTS.md', kind: 'file' },
      { name: 'README.md', kind: 'file' },
      { name: '시작문서', kind: 'folder', childCount: 7 },
    ],
    total: 3,
  },
});

test('★ 선빨강 — 안 잰 자리를 두고 순위를 단정하면 손이 그 사실을 안다', () => {
  const 판 = 완료주장검증({
    reply: '이 폴더에서 제일 두꺼운 문서는 AGENTS.md예요.',
    receipts: [목록영수증()],
  });
  assert.equal(판.일치, false,
    '**잰 값이 원장에 하나도 없는데 「제일 두꺼운」이 그냥 나갔다.** 목록은 이름·개수만 안다 — '
    + '무게 재료가 없고(local-file.js:729 크기 칸 없음), 시작문서/ 안 7개는 이름조차 안 봤다. '
    + '라이브에서 이 모양이 45,534B 진값을 두고 16,051B 오답이 됐다');
  assert.ok(String(판.모델에게 ?? '').length > 0,
    '막기만 하고 사실을 안 주면 모델은 같은 자리를 돈다 — 안 잰 자리가 사실로 가야 한다');
});

// ── 초록 반례 셋 — 「무조건 발동」이면 이 검사가 잡는다 (§7-q 규율: 오검출 반례 동봉) ──

test('반례 ① — 범위를 밝힌 순위 답은 통과한다 (정직한 고지를 벌하지 않는다)', () => {
  const 판 = 완료주장검증({
    reply: '최상위만 봤을 때는 AGENTS.md 가 제일 커요 — 시작문서 폴더 안 7개는 아직 안 쟀어요.',
    receipts: [목록영수증()],
  });
  assert.equal(판.일치, true,
    '부분합 선례의 계약 그대로 — 「밝혔으면 통과」. 이걸 막으면 §7-ad-1 의 정직한 4회차를 '
    + '다시 벌하는 것이고, 오너 말귀 정의(파악을 마친 답은 빈손이 아니다)와 충돌한다');
});

test('반례 ② — 순위·집계 주장이 없는 답은 건드리지 않는다', () => {
  const 판 = 완료주장검증({
    reply: '작업 폴더에는 AGENTS.md, README.md 와 시작문서 폴더가 있어요.',
    receipts: [목록영수증()],
  });
  assert.equal(판.일치, true, '순위를 주장하지 않는 답에 범위를 요구하면 그건 유도가 아니라 강제다');
});

// ⚠️ 초록 반례로 설계했는데 돌려 보니 빨강 — 둘째 선빨강으로 재분류(§7-q: 반례를 실제로 돌린다).
// ⚠️⚠️ **조준 정정(단일 변수 실측)**: 첫 판에 "터미널로 잰 값이 원장으로 안 쳐진다"고 적었는데
//    **한 칸 넓었다.** `원장속말` 은 stdout 을 이미 담는다 — 같은 답을 띄어쓰기만 바꾸면
//    (`….md 예요 (45,534바이트)`) 통과한다. 진짜 기제는 **이름 추출기의 토큰 경계**다:
//    `….md(45,534바이트)` 처럼 괄호가 이름에 바로 붙으면 괄호·조사까지 토큰에 딸려 나와
//    원장 대조가 실패한다. 모델이 자연스럽게 쓰는 표기에서 **참인 답이 죽는다** — F-95 가족
//    (네 얼굴 전부 「이름을 잘못 뽑아 참을 벌함」)의 다섯째 얼굴이고, 수리는 원장 정의가 아니라
//    **추출 경계**다. 괄호는 파일 이름 문자가 아니다.
// ⚠️⚠️⚠️ **별건 재분류(감시자 판정 2026-08-16)**: 이 결함은 이 슬라이스의 닫는 문장
//    ("안 잰 자리를 안다")의 실물이 아니다 — 라이브 재현 없는 구성 사례이고, 수리 자리도
//    다르다(가리킨자리들:310 토큰 경계). **별건 장부행으로 남긴다**(관측을 결함으로 승격하지
//    않는다). 아래 검사는 「지금 사실」 고정이다 — 경계를 고치면 이 단언을 계약으로 뒤집어라.
test('별건 기록(F-95 다섯째 얼굴) — 이름에 괄호가 붙으면 참인 답이 지금은 죽는다', () => {
  const 전수영수증 = {
    failureState: 'none',
    actualCall: { tool: 'local.terminal', args: { command: 'find . -type f -name "*.md" -exec wc -c {} +' } },
    result: {
      command: 'find . -type f -name "*.md" -exec wc -c {} +', exitCode: 0,
      stdout: '16051 ./AGENTS.md\n11373 ./README.md\n45534 ./시작문서/T5-비전과-성능철학.md\n72958 total',
    },
  };
  const 판 = 완료주장검증({
    reply: '제일 두꺼운 문서는 시작문서/T5-비전과-성능철학.md(45,534바이트)예요.',
    receipts: [목록영수증(), 전수영수증],
  });
  // 지금 사실: 추출 경계 결함으로 일치:false 가 난다. 띄어쓰기 판은 통과한다(조준 정정 실측).
  assert.equal(판.일치, false,
    '이 줄이 빨개졌다면 경계가 고쳐진 것이다 — 이 검사를 「전수 정답은 통과」 계약으로 뒤집어 적어라');
});

test('반례 ③ — 터미널로 전수해 정답을 말하면 통과한다 (다른 출처로 잰 값은 취소된다)', () => {
  const 전수영수증 = {
    failureState: 'none',
    actualCall: { tool: 'local.terminal', args: { command: 'find . -type f -name "*.md" -exec wc -c {} +' } },
    result: {
      command: 'find . -type f -name "*.md" -exec wc -c {} +', exitCode: 0,
      stdout: '16051 ./AGENTS.md\n11373 ./README.md\n45534 ./시작문서/T5-비전과-성능철학.md\n72958 total',
    },
  };
  const 판 = 완료주장검증({
    // 별건(위)의 괄호-붙임 함정을 피한 표기 — 이 반례가 무는 것은 취소 조항 하나다.
    reply: '제일 두꺼운 문서는 시작문서/T5-비전과-성능철학.md 예요 (45,534바이트).',
    receipts: [목록영수증(), 전수영수증],
  });
  assert.equal(판.일치, true,
    '전수로 재고 정답을 말한 턴이 막혔다 — 비교군이 이기는 그 답을 우리가 금지하는 모양이다. '
    + '목록 밖 원장(stdout)에 이름이 있으면 「다른 출처로 잰 것」으로 취소돼야 한다');
});

// 갈래 판별 실측(2026-08-16)이 잡은 자의 맹점 — 위 검사들은 원장글 없이 불러 초록이었는데,
// 턴은 **전체 영수증 JSON 을 원장글로** 준다. 목록 항목 이름이 그 안에 그대로 있어
// 취소 조항이 표적을 삼켰고, 게이트가 **턴 안에서만** 침묵했다(단위는 초록·라이브는 무반응).
test('턴 모양 — 원장글(전체 영수증 JSON)이 와도 게이트가 침묵하지 않는다', () => {
  const rec = 목록영수증();
  const 판 = 완료주장검증({
    reply: '이 폴더에서 제일 두꺼운 문서는 AGENTS.md예요.',
    receipts: [rec],
    원장글: JSON.stringify([[rec], [], []]),   // ← 턴이 주는 그 모양(turn.js:2864)
  });
  assert.equal(판.일치, false,
    '원장글에 든 목록 항목 이름을 「다른 출처로 잼」으로 읽으면 취소가 표적을 삼킨다 — '
    + '취소의 근거는 목록 아닌 영수증의 실측뿐이어야 한다');
});
