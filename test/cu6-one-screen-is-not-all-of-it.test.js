// **CU-⑥ 읽기 — 한 화면이 전부가 아니다.**
//
// 오너 계획서의 네 질문 중 셋째다:
//   *"③ 스크롤을 해서 이전 대화 내용도 살펴봐 줄 수 있는가"*
//
// 라이브(2026-08-06)로 그대로 물었다 — *"카카오톡 TNT 대화방을 스크롤해서 그 전에 무슨
// 대화가 있었는지도 읽어줘."* T5 의 답:
//   *"윤님이 위로 스크롤한 화면을 계속 캡처해서 보내 주시면…"*
//   *"제가 이 컴퓨터 화면을 직접 조작할 수 있게 **허용된 상태라면**…"*
// **스크롤을 한 번도 시도하지 않았다.** 방 이름까지 지정해 줬는데도 되물었다.
//
// 손은 붙어 있었다(다음 턴에 *"권한은 이미 열려 있어요"* 라고 답했다). 못 한 게 아니라
// **자기 손에 그 동작이 있는 줄 몰랐다.** 기계 사실 둘:
//   · `desktop.act` 의 `action` enum 에 `scroll` 은 있다 — 그런데 그 enum 은 **스키마**다.
//   · **모델이 실제로 읽는 한 줄인 `operatorFact`** 에는 누르기·입력·키만 있고 **스크롤이 없다.**
//     같은 병을 이미 한 번 앓았다(좌표 손을 붙이고 이 줄을 안 고쳐서 모델이 *"버튼을 누르거나
//     글자를 입력하는 동작은 못 한다"* 고 답했다). **여기 없는 손은 모델에게 없는 손이다.**
//
// 그리고 스크롤은 그냥 손 하나가 아니다 — **화면에 없는 것을 보는 유일한 길**이다.
// 창은 지금 보이는 만큼만 준다. 대화 기록·주문 목록·긴 표는 밀어야 나머지가 나온다.
// AX 가 0인 창(카톡 대화방이 그렇다)에서는 더더욱, 밀지 않으면 **어제 것은 영영 못 읽는다.**
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 화면다루는법 } from '../src/kernel/screen-guidance.js';

test('모델이 읽는 한 줄에 스크롤이 있다 — 없으면 있는 손도 없는 손이다', async () => {
  const { demoDescriptors } = await import('../src/surface/demo-context.js');
  const 손 = (demoDescriptors({ desktopAct: true }) ?? []).find((c) => c.id === 'desktop.act');
  assert.ok(손, 'desktop.act 가 없다');
  assert.match(String(손.operatorFact ?? ''), /스크롤|밀어|내려/,
    `**모델이 읽는 줄에 스크롤이 없다** — 스키마 enum 에만 있으면 모델은 그 손을 모른다: ${손.operatorFact}`);
});

test('화면 밖은 밀어서 본다고 가르친다 — 한 장으로 끝내면 어제 대화는 영영 못 읽는다', () => {
  const 글 = String(화면다루는법(['desktop.screen', 'desktop.act']) ?? '');
  assert.match(글, /한 화면이 전부가 아니다/,
    `**"보이는 게 전부"로 끝낸다** — 스크롤이 있는데 안 쓴다: ${글.slice(0, 200)}`);
  assert.match(글, /밀/, '미는 동작을 안 가르친다');
});

test('사람에게 대신 올려 달라고 하지 않는다 — 미는 것은 우리 손이다', () => {
  const 글 = String(화면다루는법(['desktop.screen']) ?? '');
  assert.match(글, /캡처해 (?:달라|주세요)|올려 달라|대신 밀어/,
    `**사용자에게 스크롤을 떠넘긴다** — 라이브에서 그렇게 답했다: ${글.slice(0, 300)}`);
});

test('화면 손이 없으면 이 안내도 없다 — 없는 손의 사용법에 값을 치르지 않는다', () => {
  assert.equal(화면다루는법(['local.file']), null);
});

// ── 관찰 결과를 "받은 것"이 아니라 "본 것"으로 준다 ─────────────────────
// 라이브(2026-08-06)에서 T5 는 세 번 다 이렇게 끝냈다:
//   *"현재 제게는 딱 이 한 화면만 **전달된** 상태라…"*
//   *"윤님이 위로 스크롤한 화면을 **캡처해서 보내 주시면**…"*
// **자기가 본 것을 남이 준 것으로 안다.** 그러면 다시 볼 생각을 안 한다 —
// 받은 그림은 내가 더 얻을 수 없지만, **내가 본 화면은 밀고 다시 볼 수 있다.**
//
// 우리가 그렇게 적어 줬다: `보여 드린 화면 500×768`. 이 말은 T5→사용자 방향인데
// 모델이 읽는 자리에서는 정반대로 읽힌다. **압축본은 모델이 읽는 글이다.**
test('본 화면은 "내가 본 것"으로 적는다 — 받은 것으로 적으면 다시 볼 생각을 안 한다', async () => {
  const { compactResult } = await import('../src/kernel/l1-intent/task-context.js');
  const s = String(compactResult({
    본창: { id: 9, app: '카카오톡', title: 'TNT' },
    그림크기: { w: 500, h: 768 },
    elements: [],
  }));
  assert.doesNotMatch(s, /보여 드린 화면/,
    `**"보여 드린"은 남이 준 것으로 읽힌다** — 라이브에서 "전달된 상태"라고 답했다: ${s}`);
  assert.match(s, /네가 본 화면|본 화면/, `본 것이라고 안 적는다: ${s}`);
});

test('지금 보이는 만큼이라고 밝힌다 — 창은 늘 일부만 준다', async () => {
  const { compactResult } = await import('../src/kernel/l1-intent/task-context.js');
  const s = String(compactResult({
    본창: { id: 9, app: '카카오톡', title: 'TNT' },
    그림크기: { w: 500, h: 768 },
    elements: [],
  }));
  assert.match(s, /지금 보이는 만큼/,
    `**한 장이 전부인 줄 안다** — 밀면 더 있다는 걸 모른다: ${s}`);
});
